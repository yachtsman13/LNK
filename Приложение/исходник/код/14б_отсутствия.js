function проверкиОтсутствий(доб, сс){
  const живые=live(ОТС);
  const битые=живые.filter(x=>!x.с || !x.по || x.по<x.с || !x.вид);
  if(битые.length) доб("ошибка","Отсутствия сотрудников",
    "Отсутствие без дат, без вида или «по» раньше «с»: "+битые.length,
    битые.slice(0,10).map(x=>сс(имяОтс(x)+" — "+(x.вид||"вид не указан")+", "+(x.с?ru(x.с):"?")+" — "+(x.по?ru(x.по):"?"),"abs",x.id)));
  const безСп=живые.filter(x=>!найтиПоИд(live(P),x.сотрудник));
  if(безСп.length) доб("ошибка","Отсутствия сотрудников",
    "Отсутствие ссылается на удалённого или неизвестного сотрудника: "+безСп.length,
    безСп.slice(0,10).map(x=>сс((x.вид||"")+" "+периодОтс(x),"abs",x.id)));
  // Пересечения у одного сотрудника
  const пер=[];
  live(P).forEach(сп=>{ const сп2=отсутствияСпец(сп);
    for(let i=0;i<сп2.length;i++) for(let j=i+1;j<сп2.length;j++)
      if(сп2[j].с<=сп2[i].по) пер.push([сп2[i],сп2[j]]); });
  if(пер.length) доб("внимание","Отсутствия сотрудников",
    "Периоды отсутствия одного сотрудника пересекаются: "+пер.length,
    пер.slice(0,10).map(([а,б])=>сс(имяОтс(а)+": "+а.вид+" "+периодОтс(а)+" и "+б.вид+" "+периодОтс(б),"abs",б.id)));
  // Работы в журнале в день отсутствия исполнителя
  const раб=[];
  if(живые.length) liveJ().forEach(z=>{ if(!z.дата) return;
    Object.keys(z.методы||{}).forEach(м=>{ const сп=специалистПоИмени((z.методы[м]||{}).исп); const о=сп&&отсутствиеНа(сп,z.дата);
      if(о) раб.push({z,м,сп,о}); }); });
  if(раб.length) доб("внимание","Отсутствия сотрудников",
    "Работа по журналу в день, когда исполнитель по графику отсутствует: "+раб.length,
    раб.slice(0,10).map(р=>сс(ru(р.z.дата)+" · "+р.м+" · "+(р.сп.вдок||р.сп.фио)+" — "+текстОтс(р.о),"journal",р.z.id)));
}

