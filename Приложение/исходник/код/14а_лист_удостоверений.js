// Заказчик: «добавлять буду только узкую полоску для удостоверения или ПБ.
// В одном удостоверении может быть указано сразу несколько методов
// контроля. Нужно, чтобы на одном листе сразу были необходимые
// удостоверения и ПБ; если поместится целиком, то и удостоверения на
// другого специалиста, если не поместится — другой специалист полностью
// на следующем листе. Квалификационное удостоверение неотрывно от ПБ».
// Полоски — картинки (JPG/PNG), не PDF (ответ заказчика): PDF внутрь
// печатной страницы браузера не вставить.
//
// Где лежат: в папке с документами, как и остальные файлы. Имя полоски —
// у записи аттестации (поле «полоска») и у специалиста (поле
// «полоска_пб»). Одно удостоверение — несколько записей (по методу на
// запись) с одним номером и одной датой выдачи: полоска берётся у любой
// из них, вносить её в каждую запись не нужно.
//
// Как раскладывается (правила мои, кроме двух названных заказчиком):
// лист A4 книжный, поля 10 мм; полоски одна под другой; у специалиста
// сначала удостоверения, сразу под ними ПБ; между специалистами отступ.
// Специалист, который не помещается на остаток листа, начинает новый лист.
// Если ему мало и целого листа — удостоверения делятся по листам, и ПБ
// повторяется на КАЖДОМ из них (иначе удостоверение оторвалось бы от ПБ);
// такое называется в предупреждениях. Размер полоски — по разрешению,
// записанному в самом файле (тогда печатается в натуральную величину),
// без него — во всю ширину листа; режим можно сменить.
const УДЛ_ЛИСТ={ш:210, в:297, поле:10};
const УДЛ_ЗАЗОР_ВНУТРИ=2, УДЛ_ЗАЗОР_МЕЖДУ=8;   // мм
const УДЛ_ШИРИНА=УДЛ_ЛИСТ.ш-2*УДЛ_ЛИСТ.поле, УДЛ_ВЫСОТА=УДЛ_ЛИСТ.в-2*УДЛ_ЛИСТ.поле;
const REG_УДЛ="lnk_udl";                        // режим размера — настройка места
const УДЛ_КАРТИНКА=/\.(jpe?g|png|gif|bmp|webp)$/i;
function этоКартинка(имя){ return УДЛ_КАРТИНКА.test(String(имя||"").trim()); }
