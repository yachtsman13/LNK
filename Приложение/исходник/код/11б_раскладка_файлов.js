// Дата поверки по дате окончания: обратное к поверкаДоРасчёт (дата + МПИ −
// 1 день). Ставится, только если прямой расчёт даёт ровно ту же дату
// окончания — иначе остаётся прежняя и в отчёте просьба вписать её.
function поверкаДатаОбратно(до, мес){
  const m=/^(\d{4})-(\d{2})-(\d{2})$/.exec(String(до||"")); if(!m || !(мес>0)) return "";
  const d=new Date(Date.UTC(+m[1],+m[2]-1,+m[3]+1));
  const всего=d.getUTCFullYear()*12+d.getUTCMonth()-мес, г=Math.floor(всего/12), мс=всего%12;
  const дн=Math.min(d.getUTCDate(), new Date(Date.UTC(г,мс+1,0)).getUTCDate());
  const дата=new Date(Date.UTC(г,мс,дн)).toISOString().slice(0,10);
  return поверкаДоРасчёт(дата, мес)===до ? дата : "";
}
