// Что везти на флешке: свои ВЕРНЫЕ файлы (лежат и совпадают с реестром),
// которых нет хотя бы у одного известного места (или там не та версия).
// Ни одного места не знаем — везём все. «все» — тоже все.
function файлыДляВыгрузки(все){
  const пути=путиСсылок(), другие=файлыДругих(), я=getWS().код;
  const места=Object.keys(другие).filter(к=>к!==я);
  const из=[];
  Object.keys(пути).forEach(id=>{
    if(состояниеФайла(пути[id])!=="ок") return;
    const з=ФАЙЛЫ.find(x=>x.id===id && !x.удалено); if(!з) return;
    const надо=все || !места.length || места.some(к=>{ const у=(другие[к].ф||{})[id];
      return у!==(з.отп||("размер:"+з.размер)); });
    if(надо) из.push({id, путь:пути[id], размер:з.размер, кому:места.filter(к=>(другие[к].ф||{})[id]!==(з.отп||("размер:"+з.размер)))});
  });
  return из;
}
