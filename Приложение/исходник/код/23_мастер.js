// ── Мастер первого запуска ────────────────────────────────
// Новое рабочее место (на этом компьютере код места ни разу не
// сохранялся) открывается не пультом, а мастером: откуда взять данные,
// код места и роль, папки для копий и документов, итог. Без него новое
// место молча работало бы под кодом «М1» по умолчанию — тем же, что у
// первого места, а код входит в id каждой новой записи (newId) и в
// отметки правок: два «М1» путали бы обмен и разбор правок с двух мест.
// Мастер можно пропустить (больше сам не откроется) и открыть снова из
// «Обмена». Хранит только отметку «пройден/пропущен» — lnk_setup,
// настройка места (в обмен и копию не идёт).
const REG_МАСТЕР="lnk_setup";
const КОДЫ_МЕСТ=["М1","М2","М3","М4","М5","М6"];
const ШАГИ_МАСТЕРА=["Данные","Код места","Папки","Готово"];
// Места, чьи файлы обмена приняты в этом сеансе. Отдельно от «Контроля
// обмена»: тот не запоминает файл от места с тем же кодом, что у этого,
// а на новом месте код ещё «М1» по умолчанию — ровно тот случай, когда
// знать о чужом «М1» важнее всего.
const _местаИзФайлов=new Set();
let _мастер={шаг:1, код:"", начальник:false, свод:false};
function нуженМастер(){
  try{ return !ХР.getItem("lnk_ws") && !ХР.getItem(REG_МАСТЕР); }catch(e){ return false; }
}
function кодСохранён(){ try{ return !!ХР.getItem("lnk_ws"); }catch(e){ return false; } }
// Коды других мест, о которых программа знает наверняка: от них приняты
// файлы обмена. Отметки «место» в самих записях сюда не берутся — часть
// записей программа заводит сама при первом запуске под кодом по
// умолчанию, и «М1» оказался бы «занят» на любом новом компьютере.
function занятыеМеста(){
  const я=кодСохранён()?getWS().код:"";
  return [...new Set(Object.keys(обменМеста().места).concat([..._местаИзФайлов]))]
    .filter(м=>м && м!==я).sort();
}
function свободныйКод(){ const з=занятыеМеста(); return КОДЫ_МЕСТ.find(к=>з.indexOf(к)<0)||""; }
function открытьМастер(){
  const ws=getWS();
  _мастер={шаг:1, код:кодСохранён()?ws.код:"", начальник:ws.начальник, свод:ws.мастер};
  switchView("setup");
}
// Выбор папки, приём файла обмена и восстановление копии перерисовывают
// «Обмен»; запущенные из мастера, они должны вернуть в мастер.
function обновитьОбменИлиМастер(){ if(curView==="setup") renderМастер(); else renderExchange(); }
function мастерПоля(){
  const к=document.getElementById("мКод"); if(!к) return;
  _мастер.код=к.value.trim();
  _мастер.начальник=document.getElementById("мНач").checked;
  _мастер.свод=document.getElementById("мСвод").checked;
}
function мастерШаг(н){
  if(_мастер.шаг===2){
    мастерПоля();
    if(н>2){
      if(!_мастер.код){ toast("Впишите код места"); return; }
      if(занятыеМеста().indexOf(_мастер.код)>=0 &&
         !confirm("Код «"+_мастер.код+"» уже у другого места — от него принят файл обмена.\n\n"+
                  "Два места с одним кодом путают обмен. Всё равно взять этот код?")) return;
      // Код сохраняется сразу, а не в конце: папки и следующие приёмы
      // файлов уже должны видеть это место под его настоящим кодом.
      saveWS({код:_мастер.код, мастер:_мастер.свод, начальник:_мастер.начальник});
    }
  }
  _мастер.шаг=н; renderМастер();
}
function мастерПропустить(){
  if(!confirm("Пропустить мастер?\n\nСам он больше не откроется; открыть снова можно в «Обмене файлами»."+
    (кодСохранён()?"":"\n\nКод места останется «М1» по умолчанию — если это не первое место, "+
      "поменяйте код в «Обмене», иначе записи двух мест перепутаются."))) return;
  try{ ХР.setItem(REG_МАСТЕР, JSON.stringify({когда:new Date().toISOString(), пропущен:true})); }catch(e){}
  switchView("dash");
}
function мастерГотово(куда){
  try{ ХР.setItem(REG_МАСТЕР, JSON.stringify({когда:new Date().toISOString(), код:getWS().код})); }catch(e){}
  setChrome(); toast("Рабочее место «"+getWS().код+"» настроено");
  switchView(куда||"dash");
}
function renderМастер(){
  curView="setup";
  document.querySelectorAll(".nav").forEach(n=>n.classList.remove("on"));
  const ш=_мастер.шаг, ws=getWS();
  const шаги=`<div class="шаги">${ШАГИ_МАСТЕРА.map((т,i)=>
    `<span class="${i+1===ш?"on":(i+1<ш?"сделан":"")}">${i+1}. ${esc(т)}</span>`).join("")}</div>`;
  const принято=[..._местаИзФайлов].sort();
  const кнопки=(назад,далее)=>`<div class="formbtns">
    ${назад?`<button class="btn" onclick="мастерШаг(${ш-1})">← Назад</button>`:""}
    ${далее}
    <button class="btn" style="margin-left:auto" onclick="мастерПропустить()">Пропустить мастер</button></div>`;
  let тело="";
  if(ш===1) тело=`
    <h3>1. Откуда взять данные</h3>
    <div class="note">Программа уже несёт в себе журнал и справочники из книги Excel. Если
      другие места уже работают, начните с их файла обмена — тогда здесь будет всё, что там
      наработано. Файл обмена ничего не стирает: новое добавляется, изменённое обновляется по
      свежести.</div>
    <div class="вариант"><button class="btn primary" onclick="exchangeImport()">▲ Принять файл обмена…</button>
      <div class="note">Другие места уже работают: возьмите их последний файл «Обмен ЛНК …» с
        флешки или из общей папки. Можно выбрать сразу несколько файлов.</div></div>
    <div class="вариант"><button class="btn" onclick="backupOpen()">▲ Восстановить из резервной копии…</button>
      <div class="note">Перенос места на новый компьютер: файл «Переезд места …» (кнопка
        «Переезд места» в «Обмене» на старом компьютере) — с ним переезжают и код места, и право
        выдачи номеров. Подойдёт и «Резервная копия ЛНК …». Восстановление <b>заменяет</b>
        данные, программа переспросит.</div></div>
    <div class="вариант"><button class="btn" onclick="мастерШаг(2)">Это первое место →</button>
      <div class="note">Других мест пока нет — работать с данными, что уже в программе.</div></div>
    ${принято.length?`<div class="note" style="color:var(--ok)"><b>Приняты файлы мест: ${esc(принято.join(", "))}.</b>
      Записей журнала: ${liveJ().length}, объектов: ${live(O).length}, приборов: ${live(S).length}.</div>`:""}
    ${кнопки(false, принято.length?`<button class="btn primary" onclick="мастерШаг(2)">Далее →</button>`:"")}`;
  else if(ш===2){
    const код=_мастер.код || свободныйКод() || "";
    const занято=занятыеМеста();
    тело=`
    <h3>2. Код этого места и кто за ним работает</h3>
    <div class="form"><div class="grid">
      <label>Код места
        <input id="мКод" value="${esc(код)}" maxlength="6" list="мКоды" placeholder="М1"></label>
      <datalist id="мКоды">${КОДЫ_МЕСТ.map(к=>`<option value="${к}">`).join("")}</datalist>
      <label style="justify-content:flex-end">
        <span style="display:flex;gap:8px;align-items:center;color:var(--ink)">
          <input type="checkbox" id="мНач" ${_мастер.начальник?"checked":""} style="width:auto">
          Начальник — ставит задачи и принимает работу</span></label>
      <label style="justify-content:flex-end">
        <span style="display:flex;gap:8px;align-items:center;color:var(--ink)">
          <input type="checkbox" id="мСвод" ${_мастер.свод?"checked":""} style="width:auto">
          Мастер — собирает свод всех мест</span></label>
    </div></div>
    <div class="note">Код у каждого места <b>свой</b>: М1, М2, … Он входит в номер каждой новой
      записи, поэтому при обмене места не затирают друг друга.
      ${занято.length?`<br>Уже заняты другими местами (от них приняты файлы): <b>${esc(занято.join(", "))}</b>.`
        :`<br>Других мест программа пока не знает — если они есть, возьмите код, которого у них нет.`}</div>
    <div class="note">Начальник и мастер — обычно одно место на всю лабораторию. Если не знаете —
      оставьте пустыми: поменять можно в любой момент в «Обмене файлами».</div>
    ${кнопки(true, `<button class="btn primary" onclick="мастерШаг(3)">Далее →</button>`)}`;
  }
  else if(ш===3) тело=`
    <h3>3. Папки</h3>
    ${ЕСТЬ_ПАПКИ?`
    <div class="вариант"><button class="btn ${_папка?"":"primary"}" onclick="выбратьПапкуКопий()">Папка для копий…</button>
      <div class="note">${_папка?`Выбрана: <b>${esc(_папка.name)}</b>.`:"<b>Не выбрана.</b>"}
        Программа сама пишет туда копию базы во время работы и держит последние
        ${ДЕРЖАТЬ_КОПИЙ}. Лучше всего — флешка или общая папка, не этот же диск.</div></div>
    <div class="вариант"><button class="btn" onclick="выбратьПапкуДок()">Папка с документами…</button>
      <div class="note">${_папкаДок?`Выбрана: <b>${esc(_папкаДок.name)}</b>.`:"Не выбрана — можно позже."}
        Сканы и PDF: свидетельства о поверке, удостоверения, протоколы. Нужна для «Пачки на
        печать» к акту.</div></div>`
    :`<div class="note">Этот браузер не умеет писать в выбранную папку — так умеют <b>Chrome и
      Edge</b>. Копии здесь делаются кнопкой «Сохранить копию» в «Обмене файлами»: файл уходит в
      папку загрузок, оттуда — на флешку.</div>`}
    ${кнопки(true, `<button class="btn primary" onclick="мастерШаг(4)">Далее →</button>`)}`;
  else {
    const л=getЛаб(), лабПуста=!(л.организация||л.наименование);
    тело=`
    <h3>4. Готово</h3>
    <div class="bar"><span class="g" style="flex:1">Код места</span><b>${esc(ws.код)}</b></div>
    <div class="bar"><span class="g" style="flex:1">Роль</span><b>${
      [ws.начальник?"начальник":"", ws.мастер?"мастер (свод)":""].filter(Boolean).join(", ")||"обычное место"}</b></div>
    <div class="bar"><span class="g" style="flex:1">Данные</span><b>журнал ${liveJ().length},
      объекты ${live(O).length}, приборы ${live(S).length}, специалисты ${live(P).length}</b></div>
    ${ЕСТЬ_ПАПКИ?`<div class="bar"><span class="g" style="flex:1">Папка для копий</span><b>${_папка?esc(_папка.name):"не выбрана"}</b></div>`:""}
    ${!ЕСТЬ_ПАПКИ||!_папка?`<div class="note" style="color:var(--warn)">Автокопий нет — делайте копию
      кнопкой «Сохранить копию» в «Обмене файлами» хотя бы раз в несколько дней.</div>`:""}
    ${лабПуста?`<div class="note" style="color:var(--warn)">Карточка лаборатории не заполнена — без неё
      шапка акта останется пустой. Если другие места её уже заполнили, она придёт с их файлом обмена.</div>`:""}
    <div class="note">Дальше обмен идёт обычным порядком: «Обмен файлами» → «Выгрузить всё» на
      этом месте и «Принять файлы» от других.</div>
    <div class="formbtns">
      <button class="btn" onclick="мастерШаг(3)">← Назад</button>
      <button class="btn primary" onclick="мастерГотово('dash')">Готово — на пульт</button>
      ${лабПуста?`<button class="btn" onclick="мастерГотово('lab')">Готово — заполнить карточку лаборатории</button>`:""}
    </div>`;
  }
  document.getElementById("main").innerHTML=`
    <div class="head"><h2>Новое рабочее место</h2><span class="sub">мастер первого запуска</span></div>
    <div class="мастер">${шаги}<div class="panel">${тело}</div></div>`;
}

