let _прот=null;     // {zid, м, ф, откуда}
function открытьПротокол(zid, м, ф){
  const z=J.find(x=>String(x.id)===String(zid) && !x.удалено);
  if(!z){ toast("Запись не найдена"); return; }
  if(м==="ВД"){ toast("Образца протокола ВД нет — пришлите образец, сделаю бланк"); return; }
  if(!естьФормаПротокола(м)){ toast("Для метода "+м+" образца протокола нет"); return; }
  const формы=формыМетода(м); ф=ф||формы[0];
  if(curView!=="prot" && !уходСФормы()) return;
  if(curView==="prot" && _прот && (_прот.zid!==String(zid)||_прот.ф!==ф) && !уходСФормы()) return;
  const откуда=curView==="prot"&&_прот?_прот.откуда:curView;
  if(curView!=="prot") спроситьРодительный([z]);
  формаСохранена();
  _прот={zid:String(zid), м, ф, откуда:(откуда==="edit"?"edit":откуда)||"journal"};
  curView="prot";
  document.querySelectorAll(".nav").forEach(n=>n.classList.toggle("on",n.dataset.view==="journal"));
  const мод=документЗаписи(z,м,ф);
  const заблок=записьЗакрыта(z) && !_закрРазрешено.has(String(z.id));
  document.getElementById("main").innerHTML=`
    <div class="head noprint">
      <button class="btn" onclick="закрытьПротокол()">← Назад</button>
      <h2 style="font-size:16px">${esc(названиеФормы(ф))}${мод.номер?" № "+esc(мод.номер):""}</h2>
      <span class="sub">${esc(z.объект||"")}${мод.правлен?" · есть сохранённые правки":""}</span>
      <div class="spring"></div>
      ${формы.length>1?формы.map(x=>`<button class="btn ${x===ф?"on":""}" onclick="открытьПротокол('${esc(z.id)}','${м}','${x}')">${esc(названиеФормы(x))}</button>`).join(""):""}
      ${заблок?"":`<button class="btn primary" onclick="сохранитьПротокол()">✓ Сохранить</button>`}
      <button class="btn" onclick="выгрузитьПротокол()">⤓ Word</button>
      <button class="btn" onclick="window.print()">⎙ Печать</button>
      ${мод.правлен&&!заблок?`<button class="btn" onclick="сброситьПротокол()" title="Убрать сохранённые правки — всё снова заполнится из записи и карточек">↺ Заполнить заново</button>`:""}
    </div>
    ${заблок?`<div class="draftnote noprint">Запись закрытого года — бланк только для просмотра.</div>`:""}
    <div class="draftnote noprint">Жёлтым — поля для правки. Правки сохраняются кнопкой «✓ Сохранить» (Ctrl+S) и попадают в Word.
      Пока поле не правили, оно заполняется из записи и карточек само — поправили прибор или удостоверение в карточке, бланк это увидит.
      В таблицах строки добавляются и убираются кнопками под ними.${мод.родНет?` <b>Наименование объекта не в родительном падеже</b> — поправьте строку объекта.`:""}</div>
    <div class="sheet протлист${заблок?" заблок":""}">${протHTML(мод, заблок)}</div>`;
}
function протHTML(мод, заблок){
  const ред=заблок?"false":"true";
  const fld=(к,v,ph,кл)=>`<span class="fld${кл?" "+кл:""}" contenteditable="${ред}" data-к="${esc(к)}" data-ph="${esc(ph||"")}">${esc(v||"")}</span>`;
  const ячейка=(я)=>{ const о=(я&&typeof я==="object")?я:{т:я};
    return `<th${о.span?` colspan="${о.span}"`:""}${о.vm==="restart"?` rowspan="3"`:""}>${тHTML(о.т||"").replace(/\n/g,"<br>")}</th>`; };
  return мод.блоки.map(б=>{
    const v=б.знач;
    if(б.т==="шапка") return `<p class="пп">${fld(б.к,v,"дата, место")}</p><p class="пподп" style="text-align:left;padding-left:1.25cm">(Дата и место проведения контроля)</p>`;
    if(б.т==="пусто") return `<p class="пп">&nbsp;</p>`;
    if(б.т==="загол") return `<p class="пп пзаг${б.к?" пкурс":""}">${тHTML(б.текст)}</p>`;
    if(б.т==="ввод") return `<p class="пп пкр">В соответствии с нарядом-заказом (заявкой) ${fld(б.к,v,"номер")} <u>${esc(б.глагол)}</u></p>`;
    if(б.т==="подп") return `<p class="пподп"${б.слева?` style="text-align:left;padding-left:${(б.слева/567).toFixed(2)}cm"`:""}>${esc(б.текст)}</p>`;
    if(б.т==="линия") return `<p class="пп плин">&nbsp;</p>`;
    if(б.т==="метка") return `<p class="пп пкр">${тHTML(б.текст)}</p>`;
    if(б.т==="строка") return `<p class="пп${б.красная?" пкр":""}">${б.пред?(б.предU?`<u>${esc(б.пред)}</u>`:esc(б.пред)):""}${fld(б.к,v,"",б.подсв&&v===б.по?"подсв":"")}${б.после?esc(б.после):""}</p>`;
    if(б.т==="поле") return `<div class="fld пполе" contenteditable="${ред}" data-к="${esc(б.к)}" data-поле="1" data-ph="впишите">${esc(v||"").replace(/\n/g,"<br>")}</div>`;
    if(б.т==="таблица"){
      const ряды=Array.isArray(v)?v:б.по;
      return `<table class="doctbl пт" data-к="${esc(б.к)}" data-табл="1"><colgroup>${б.ширины.map(ш=>`<col style="width:${(ш/ПРОТ_ШИРИНА*100).toFixed(2)}%">`).join("")}</colgroup>
        <thead>${б.шапка.map(р=>`<tr>${р.filter(я=>!(я&&я.vm==="continue")).map(ячейка).join("")}</tr>`).join("")}</thead>
        <tbody>${ряды.map(р=>`<tr>${р.map((я,j)=>`<td contenteditable="${ред}" class="fld"${б.слева&&j===р.length-1?` style="text-align:left"`:""}>${esc(я||"").replace(/\n/g,"<br>")}</td>`).join("")}</tr>`).join("")}</tbody></table>
        ${заблок?"":`<div class="noprint пткн"><button class="btn small" onclick="протСтрока(this,1)">＋ строка</button> <button class="btn small" onclick="протСтрока(this,-1)">− последняя строка</button></div>`}`;
    }
    if(б.т==="кв") return `<table class="doctbl пт" data-к="${esc(б.к)}" data-кв="1"><colgroup><col style="width:44%"><col></colgroup><tbody>${
      б.ряды.map(([л],i)=>`<tr><td style="text-align:left">${esc(л)}</td><td contenteditable="${ред}" class="fld" style="text-align:left" data-л="${esc(л)}">${esc((v||[])[i]||"").replace(/\n/g,"<br>")}</td></tr>`).join("")}</tbody></table>`;
    if(б.т==="подписьТК") return `<p class="пп">${esc(б.роль)} &nbsp; ${fld(б.к,v,"Ф.И.О.")} &nbsp; ____________ &nbsp; ____________</p><p class="пподп" style="text-align:left;padding-left:5.8cm">Ф.И.О. · подпись · дата</p>`;
    return "";
  }).join("");
}
function протСтрока(кн, шаг){
  const t=кн.parentNode.previousElementSibling; if(!t || !t.tBodies[0]) return;
  const tb=t.tBodies[0];
  if(шаг>0){ const n=tb.rows[0]?tb.rows[0].cells.length:1; const tr=tb.insertRow();
    for(let i=0;i<n;i++){ const td=tr.insertCell(); td.contentEditable="true"; td.className="fld"; }
    if(tr.cells[0] && /^\d+$/.test((tb.rows[tb.rows.length-2]||{cells:[{innerText:""}]}).cells[0].innerText.trim())) tr.cells[0].innerText=String(tb.rows.length); }
  else if(tb.rows.length>1) tb.deleteRow(-1);
  _несохранено=true;
}
// Сравнение «правили ли поле» — без учёта лишних пробелов: браузер в
// поле правки схлопывает подряд идущие пробелы, и нетронутая строка
// иначе считалась бы правкой.
function нормПрот(v){
  if(Array.isArray(v)) return v.map(нормПрот);
  return String(v==null?"":v).replace(/[ \t\u00a0]+/g," ").replace(/ *\n */g,"\n").trim();
}
const текстЯчейки=el=>String(el.innerText||"").replace(/ /g," ").replace(/\n+$/,"");
function значенияБланка(){
  const зн={};
  document.querySelectorAll(".протлист [data-к]").forEach(el=>{
    const к=el.dataset.к;
    if(el.dataset.табл) зн[к]=[...el.tBodies[0].rows].map(tr=>[...tr.cells].map(текстЯчейки));
    else if(el.dataset.кв){ const о={}; el.querySelectorAll("td[data-л]").forEach(td=>{ о[td.dataset.л]=текстЯчейки(td); }); зн[к]=о; }
    else зн[к]=текстЯчейки(el).trim();
  });
  return зн;
}
function сохранитьПротокол(){
  if(!_прот) return;
  const z=J.find(x=>String(x.id)===_прот.zid && !x.удалено); if(!z) return;
  if(записьЗакрыта(z) && !разрешитьЗакрытые([z])) return;
  const мод=модельПротокола(z,_прот.м,_прот.ф), вв=значенияБланка(), зн={};
  мод.блоки.forEach(б=>{
    if(!б.к || !(б.к in вв)) return;
    if(б.т==="кв"){ const отл={}; б.ряды.forEach(([л,по])=>{ if(нормПрот(вв[б.к][л]||"")!==нормПрот(String(по||""))) отл[л]=вв[б.к][л]; });
      if(Object.keys(отл).length) зн[б.к]=отл; return; }
    const по=б.т==="поле"?"":б.по;
    if(JSON.stringify(нормПрот(вв[б.к]))!==JSON.stringify(нормПрот(по))) зн[б.к]=вв[б.к];
  });
  const ид=идПрот(_прот.zid,_прот.ф), ts=new Date().toISOString(), место=getWS().код;
  const был=ПРОТ.find(p=>p.id===ид);
  if(был) Object.assign(был,{зн, удалено:"", изменено:ts, место});
  else ПРОТ.push({id:ид, зид:_прот.zid, м:_прот.м, форма:_прот.ф, зн, изменено:ts, место});
  saveReg(REG_ПРОТ,ПРОТ);
  формаСохранена();
  toast("Сохранено: "+названиеФормы(_прот.ф)+(Object.keys(зн).length?" · правок: "+Object.keys(зн).length:" · без правок, всё из записи"));
  открытьПротокол(_прот.zid,_прот.м,_прот.ф);
}
function выгрузитьПротокол(){
  if(!_прот) return;
  if(_несохранено && confirm("В бланке несохранённые правки. Сохранить их перед выгрузкой?")) сохранитьПротокол();
  const z=J.find(x=>String(x.id)===_прот.zid && !x.удалено); if(!z) return;
  const мод=документЗаписи(z,_прот.м,_прот.ф);
  dlBlob(мод.имя, файлПротокола(мод)); toast("Выгружено в Word: "+мод.имя);
}
function сброситьПротокол(){
  if(!_прот) return;
  if(!confirm("Убрать сохранённые правки этого документа? Всё снова заполнится из записи и карточек.")) return;
  const был=ПРОТ.find(p=>p.id===идПрот(_прот.zid,_прот.ф));
  if(был){ был.удалено=new Date().toISOString(); был.изменено=был.удалено; был.место=getWS().код; saveReg(REG_ПРОТ,ПРОТ); }
  формаСохранена(); открытьПротокол(_прот.zid,_прот.м,_прот.ф);
}
function закрытьПротокол(){
  if(!уходСФормы()) return;
  const п=_прот; формаСохранена();
  if(п && п.откуда==="edit"){ editJournal(п.zid); return; }
  switchView(п&&п.откуда&&п.откуда!=="prot"?п.откуда:"journal");
}
