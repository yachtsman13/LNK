// «исполнитель» записей, тем же, по которому собираются подписи акта.
function специалистыАкта(zs){
  const поИмени={}; live(P).forEach(x=>{ if(x.вдок) поИмени[String(x.вдок).trim()]=x; });
  const карта=new Map();
  zs.forEach(z=>methodsOf(z).forEach(м=>{
    const и=String(((z.методы||{})[м]||{}).исп||"").trim(); if(!и) return;
    const c=поИмени[и]; if(!c) return;
    if(!карта.has(c.id)) карта.set(c.id,{спец:c, методы:[]});
    const п=карта.get(c.id); if(п.методы.indexOf(м)<0) п.методы.push(м);
  }));
  return [...карта.values()];
}

// Свидетельства о поверке печатаются по 4 на листе (ваше требование) —
// это отдельное задание печати с настройкой «4 страницы на листе», её
// нельзя задать из программы. Поэтому они кладутся своей подпапкой,
// название которой и есть напоминание, как её печатать.
const ПАПКА_ПОВЕРОК="Свидетельства о поверке (печатать по 4 на листе)";
// Состав пачки в том порядке, в каком её печатать. Имена файлов
// получают номер спереди: Проводник и Acrobat сортируют по имени, так
// порядок печати и задаётся. Чистая функция — ничего не пишет на диск,
// поэтому её видно на экране до сборки и можно проверить тестом.
function составПачки(ключ){
  const zs=записиАкта(ключ), из=[];
  let н=0, нп=0;
  const двузн=x=>(x<10?"0":"")+x;
  const добавить=(файл,что,подпапка)=>{
    const ф=String(файл||"").trim();
    if(!ф) return;
    const номер=подпапка?(++нп):(++н);
    из.push({файл:ф, что:что, подпапка:подпапка||"", имя:двузн(номер)+" "+имяБезПапок(ф)});
  };
  // 1. Акт — первым листом. Его собирает сама программа (.docx), из
  //    папки брать нечего.
  из.push({акт:true, что:"акт о проведении работ", подпапка:"",
           имя:двузн(++н)+" Акт "+номерАкта(ключ)+".docx"});
  // 2. Протоколы — в том же порядке, что разделы перечня в самом акте.
  const видели={};
  ПОРЯДОК_В_АКТЕ.concat(METHODS).forEach(м=>{
    if(видели[м]) return; видели[м]=1;
    zs.filter(z=>обозначениеПротокола(z,м))
      .sort((a,b)=>(parseInt(номерМетода(a,м),10)||0)-(parseInt(номерМетода(b,м),10)||0))
      .forEach(z=>добавить(((z.методы||{})[м]||{}).файл, "протокол № "+обозначениеПротокола(z,м)));
  });
  // 3. Свидетельство об аттестации лаборатории.
  добавить(getЛаб().файл_свидетельства, "свидетельство об аттестации ЛНК");
  // 4. Удостоверения специалистов — только по методам, по которым они
  //    работали в этом акте; один файл на несколько методов не двоится.
  const файлыУд={};
  специалистыАкта(zs).forEach(({спец,методы})=>{
    const дляТВ=удостоверениеДляТВ(спец,методы,zs);
    аттестации(спец).forEach(а=>{
      if(!методы.some(м=>аттестацияОхватывает(а.метод,м)) && а!==дляТВ) return;
      const ф=String(а.файл||"").trim(); if(!ф||файлыУд[ф]) return;
      файлыУд[ф]=1;
      добавить(ф, "удостоверение "+(спец.вдок||спец.фио||"")+" · "+(а.метод||""));
    });
    добавить(спец.файл_пб, "удостоверение ПБ "+(спец.вдок||спец.фио||""));
  });
  // 5. Свидетельства о поверке — своей подпапкой, со своей нумерацией.
  приборыАкта(zs).forEach(п=>добавить(п.файл_поверки,
    "поверка: "+(п.наименование||"")+(п.зав?(" зав. № "+п.зав):""), ПАПКА_ПОВЕРОК));
  return из;
}
// Для твердометрии своего удостоверения нет — в пачку идёт то, что даёт к
// ней допуск (любая действующая аттестация на дату работы), но только если
// удостоверения по другим методам этого акта его и так не покрывают.
function удостоверениеДляТВ(спец, методы, zs){
  if(методы.indexOf(МЕТОД_БЕЗ_АТТЕСТАЦИИ)<0) return null;
  const свои=аттестации(спец).filter(а=>методы.some(м=>м!==МЕТОД_БЕЗ_АТТЕСТАЦИИ && аттестацияОхватывает(а.метод,м)));
  if(свои.length) return null;
  const даты=zs.filter(z=>methodsOf(z).indexOf(МЕТОД_БЕЗ_АТТЕСТАЦИИ)>=0).map(z=>z.дата).filter(Boolean).sort();
  return аттестацияНа(спец, МЕТОД_БЕЗ_АТТЕСТАЦИИ, даты[даты.length-1]);
}
// Чего не хватает для полной пачки — считается по тем же правилам, что
// и сам состав: карточка в акте есть, а имя файла у неё не заполнено.
function пробелыПачки(ключ){
  const zs=записиАкта(ключ), нет=[];
  const видели={};
  ПОРЯДОК_В_АКТЕ.concat(METHODS).forEach(м=>{
    if(видели[м]) return; видели[м]=1;
    zs.filter(z=>обозначениеПротокола(z,м)).forEach(z=>{
      if(!String(((z.методы||{})[м]||{}).файл||"").trim())
        нет.push("протокол № "+обозначениеПротокола(z,м));
    });
  });
  if(!String(getЛаб().файл_свидетельства||"").trim()) нет.push("свидетельство об аттестации ЛНК");
  специалистыАкта(zs).forEach(({спец,методы})=>{
    const дляТВ=удостоверениеДляТВ(спец,методы,zs);
    const подходящие=аттестации(спец).filter(а=>методы.some(м=>аттестацияОхватывает(а.метод,м)) || а===дляТВ);
    if(!подходящие.length || !подходящие.some(а=>String(а.файл||"").trim()))
      нет.push("удостоверение "+(спец.вдок||спец.фио||""));
    if(!String(спец.файл_пб||"").trim()) нет.push("ПБ "+(спец.вдок||спец.фио||""));
  });
  приборыАкта(zs).forEach(п=>{
    if(!String(п.файл_поверки||"").trim())
      нет.push("поверка: "+(п.наименование||"")+(п.зав?(" зав. № "+п.зав):""));
  });
  return нет;
}
// Сборка пачки в папку: подпапка на акт, в ней акт .docx и копии
// найденных файлов с номерами. Файл, которого в папке нет, не
// выдумывается — попадает в отчёт «не нашлось», чтобы это было видно,
// а не молча пропущено.
async function собратьПачку(ключ){
  const h=await папкаДок();
  if(!h){ toast("Сначала выберите папку с документами — «Обмен файлами»"); switchView("exchange"); return; }
  if(await правоНаПапкуДок(true)!=="есть"){ toast("Нет разрешения на папку с документами"); return; }
  const состав=составПачки(ключ);
  const имяПачки="Акт "+номерАкта(ключ)+" — пачка на печать";
  let готово=0; const ненайдены=[];
  try{
    const цель=await h.getDirectoryHandle(имяПачки,{create:true});
    const подпапки={};
    for(const п of состав){
      const куда = п.подпапка
        ? (подпапки[п.подпапка] = подпапки[п.подпапка] ||
            await цель.getDirectoryHandle(п.подпапка,{create:true}))
        : цель;
      let данные=null;
      if(п.акт){
        const д=актВWord(ключ,true); if(!д) continue; данные=д.данные;
      } else {
        try{ const ф=await файлИзПапкиДок(h,п.файл); данные=await (await ф.getFile()).arrayBuffer(); }
        catch(e){ ненайдены.push(п.файл+" — "+п.что); continue; }
      }
      const вых=await куда.getFileHandle(п.имя,{create:true});
      const w=await вых.createWritable(); await w.write(данные); await w.close();
      готово++;
    }
  }catch(e){ toast("Не удалось собрать пачку: "+e.name); return; }
  const пробелы=пробелыПачки(ключ);
  // Приборы берутся из отметок в записи или из стандартного набора
  // метода. Пока ни там, ни там ничего не отмечено, свидетельств о
  // поверке в пачке не будет вовсе — это не поломка, но догадаться
  // трудно, поэтому говорим прямо.
  const нетПриборов=!приборыАкта(записиАкта(ключ)).length;
  alert("Пачка собрана в папке «"+имяПачки+"».\n\n"+
    "Файлов записано: "+готово+"\n"+
    (нетПриборов?("\nСвидетельств о поверке в пачке нет: по методам этого акта не отмечено "+
      "ни одного прибора. Отметьте их в записи журнала (кнопка «Приборы и НД» у метода) "+
      "или разом в разделе «Методики контроля».\n"):"")+
    (ненайдены.length?("\nНе нашлось в папке с документами ("+ненайдены.length+"):\n· "+
      ненайдены.join("\n· ")+"\n"):"")+
    (пробелы.length?("\nИмя файла не заполнено в карточке ("+пробелы.length+"):\n· "+
      пробелы.join("\n· ")+"\n"):"")+
    "\nПечать: сначала содержимое самой папки (по порядку номеров), затем подпапку\n«"+
    ПАПКА_ПОВЕРОК+"» — отдельным заданием, поставив в Acrobat «несколько страниц на листе: 4».");
}

