// «1 наименование / 2 наименования / 5 наименований» — счётная форма.
function склЧисло(n, одно, два, много){
  const д=n%10, с=n%100;
  return n+" "+((с>=11&&с<=14)||д===0||д>=5 ? много : д===1 ? одно : два);
}
