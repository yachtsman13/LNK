// центр — выравнивание по центру и по высоте (нужно паспорту, заказчик
// попросил явно); по умолчанию false — старое поведение (слева/сверху),
// чтобы не тронуть план ППР, который делит эти же функции с паспортом.
// серый — заливка строки-шапки; по умолчанию true (старое поведение,
// план ППР); паспорт передаёт false — заказчик попросил убрать.
// t — строка ИЛИ массив строк: массив даёт несколько абзацев в ячейке,
// каждый своей строкой (заказчик попросил для Формы 2 паспорта: тип
// прибора, «И», изготовитель/зав.№/год/ввод — каждый на своей строке).
// span — объединение колонок (w:gridSpan); порядок в CT_TcPr строгий:
// tcW → gridSpan → shd → tcMar → vAlign, иначе Word объявит файл
// повреждённым (тот же класс ошибки, на котором уже трижды ловился).
function wЯчейкаТабл(t, ш, шапка, центр, серый, span, держать){
  серый=серый!==false;
  const стр=(Array.isArray(t)?t:[t]).map(x=>String(x==null?"":x)).filter(x=>x!=="");
  const абз=(стр.length?стр:[""]).map(x=>
    '<w:p><w:pPr>'+(держать?'<w:keepNext/>':'')+
    '<w:spacing w:after="0" w:line="260" w:lineRule="exact"/>'+
    '<w:jc w:val="'+(центр?"center":"left")+'"/>'+rPrТабл(шапка)+'</w:pPr>'+
    (x?wRunТабл(x,шапка):'')+'</w:p>').join('');
  return '<w:tc><w:tcPr><w:tcW w:w="'+ш+'" w:type="dxa"/>'+
    (span>1?'<w:gridSpan w:val="'+span+'"/>':'')+
    (шапка&&серый?'<w:shd w:val="clear" w:color="auto" w:fill="F0F0F0"/>':'')+
    '<w:tcMar><w:left w:w="80" w:type="dxa"/><w:right w:w="80" w:type="dxa"/>'+
    '<w:top w:w="40" w:type="dxa"/><w:bottom w:w="40" w:type="dxa"/></w:tcMar>'+
    (центр?'<w:vAlign w:val="center"/>':'')+'</w:tcPr>'+абз+'</w:tc>';
}
// Ячейка вида {т, span} занимает несколько колонок — её ширина равна
// сумме ширин объединённых колонок, иначе tblW разойдётся с gridCol.
function wСтрокаТабл(ячейки, ширины, шапка, центр, серый, держать){
  let к=0, из='';
  ячейки.forEach(я=>{
    const объед=(я && !Array.isArray(я) && typeof я==="object");
    const span=объед?(я.span||1):1;
    let ш=0; for(let j=0;j<span;j++) ш+=(+ширины[к+j]||0);
    из+=wЯчейкаТабл(объед?я.т:я, ш, шапка, центр, серый, span, держать);
    к+=span;
  });
  return '<w:tr>'+(шапка?'<w:trPr><w:tblHeader/></w:trPr>':'')+из+'</w:tr>';
}
// Таблица с шапкой (специалисты, приборы): первая строка — заголовки.
function wТаблШапка(шапка, ширины, строки, центр, серый){
  const grid=ширины.map(ш=>'<w:gridCol w:w="'+ш+'"/>').join('');
  let из='<w:tbl><w:tblPr><w:tblW w:w="'+ШИРИНА_ТЕКСТА+'" w:type="dxa"/>'+
    '<w:tblBorders>'+wГраницыТабл()+'</w:tblBorders>'+
    '<w:tblLayout w:type="fixed"/>'+
    '<w:tblCellMar><w:left w:w="80" w:type="dxa"/><w:right w:w="80" w:type="dxa"/></w:tblCellMar>'+
    '</w:tblPr><w:tblGrid>'+grid+'</w:tblGrid>';
  из+=wСтрокаТабл(шапка,ширины,true,центр,серый);
  строки.forEach(р=>из+=wСтрокаТабл(р,ширины,false,центр,серый));
  из+='</w:tbl>';
  return из;
}
