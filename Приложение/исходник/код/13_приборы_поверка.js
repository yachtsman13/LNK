function группыПоверки(год){
  const г0=(год==null?годПоверки:год);
  const карта=new Map();
  приборыДляЗаявки().forEach(п=>{
    if(!месяцПрибора(п,г0)) return;    // без месяца НА ЭТОТ ГОД прибор в документы не идёт
    const ключ=имяПрибораДок(п).toLowerCase();
    if(!карта.has(ключ)) карта.set(ключ,{имя:имяПрибораДок(п), приборы:[]});
    карта.get(ключ).приборы.push(п);
  });
  return [...карта.values()].map(г=>{
    const помес={};
    г.приборы.forEach(п=>{ const м=месяцПрибора(п,г0); помес[м]=(помес[м]||0)+1; });
    return { имя:г.имя, кол:г.приборы.length,
             месяцы:МЕСЯЦЫ.filter(м=>помес[м]), помес:помес,
             класс:(г.приборы.find(п=>String(п.класс_точности||"").trim())||{}).класс_точности||"",
             комплект:г.приборы.map(комплектностьПрибора).filter(Boolean)[0]||"" };
  });
}
// Неотъемлемая часть (датчик, преобразователь, мера из комплекта)
// поверяется вместе с основным прибором — так сказал заказчик, поэтому
// даты поверки у части не её собственные, а берутся у основного и
// руками не правятся (то же решение, что и с «действительно до» у
// аттестации специалиста: поле перестало быть источником истины).
// Свидетельство у комплектного прибора одно на весь комплект: у части
// тот же номер и тот же файл, что у основного (указание заказчика) —
// поэтому они в том же списке, что и даты, и так же не редактируются.
// Отметка «И» (исправен) — итог той же поверки, что и свидетельство на
// комплект, поэтому тоже от основного (заказчик заметил, что у частей её
// не поставить).
const ПОЛЯ_ПОВЕРКИ_ЧАСТИ=["поверка_дата","поверка_до","свидетельство","файл_поверки","исправен","сокращённая","объём_поверки","калибровка"];
function сокращённаяПоверка(п){ return String((п&&п.сокращённая)||"").trim()==="Да"; }
// Приведение уже сохранённых данных: у каждой части даты выставляются
// по основному прибору. Зовётся при загрузке, после сохранения карточки,
// после импорта из Excel и после приёма обмена/копии — то есть на всех
// путях, какими данные попадают в S. Возвращает, менялось ли что-то.
function синхронизироватьЧасти(){
  let менялось=false;
  live(S).forEach(ч=>{
    if(!ч.основной_ид) return;
    const осн=найтиПоИд(S,ч.основной_ид);
    if(!осн || тотЖеИд(осн.id,ч.id)) return; // битую ссылку ловит «Проверка данных»
    ПОЛЯ_ПОВЕРКИ_ЧАСТИ.forEach(к=>{
      const надо=осн[к]||"";
      if((ч[к]||"")!==надо){ ч[к]=надо; менялось=true; }
    });
  });
  return менялось;
}
// Поля, которых у неотъемлемой части не бывает: в заявку и план-график
// она идёт в составе основного прибора, отдельной строкой — нет, значит
// и месяц представления, и комплектность, и класс точности ей не нужны
// (со слов заказчика). Прячем их и очищаем, чтобы в данных не осталось
// значения, которое потом молча всплывёт в документе.
const ПОЛЯ_НЕ_У_ЧАСТИ=["месяцы_поверки","класс_точности","комплектность"];
// Поля, которые у части обычно те же, что у основного прибора, но
// законно могут отличаться (датчик другого года выпуска, свой владелец):
// подставляются ТОЛЬКО в пустые и остаются редактируемыми — в отличие от
// поверки, которая у части не своя вовсе. Инвентарный номер, метод
// контроля, место хранения и состояние добавлены по указанию заказчика:
// комплект лежит в одном помещении и живёт одной судьбой с основным
// прибором, но исключения бывают, поэтому поля не запираются.
// Категория (раздел паспорта) — тоже: в паспорте часть всё равно стоит в
// разделе основного прибора, а в карточке пустая категория выглядела
// недоделкой.
const ПОЛЯ_ОТ_ОСНОВНОГО=["инв","метод","хранение","состояние","категория","ответственный",
                         "изготовитель","год_выпуска","дата_ввода","владелец"];
// Список приборов, которые можно выбрать основным для неотъемлемой части:
// все живые, кроме явно отмеченных «составных частей нет». Пустое значение
