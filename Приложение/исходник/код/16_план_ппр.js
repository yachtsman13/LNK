// План приходит из книги только ПЕРВЫЙ раз: позиции лежат своим реестром
// lnk_ppr_plan (засевается из вшитой книги, когда ключа ещё нет), правятся
// формой, ходят в обмене и в копии, как любые рабочие данные. id позиций
// из книги («ППР-001») одинаковы на всех местах, поэтому обмен не двоит
// их; новая позиция получает newId("ППР") — с кодом места внутри.
// Часы в клетке — СВОЁ число, а не норма × количество: в книге у трёх
// позиций (ежедневное и подекадное обслуживание) они суммируются за месяц
// (0,2…1,15 ч при норме 0,05–0,1), формулы для такого случая в книге нет,
// поэтому норма × количество только подсказывается, а не навязывается.
function годыФормыППР(){
  const г=годыППР(); const макс=г.length?Math.max(...г):new Date().getFullYear();
  return г.concat([макс+1]);      // следующий год — чтобы план можно было продлить
}
