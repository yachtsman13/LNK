# -*- coding: utf-8 -*-
"""План-график ППР из книги заказчика → Приложение/ппр.json.

Разбор строгий: ничего не достраивается и не исправляется. Что в книге
записано криво (например квартальная позиция, размеченная на десять
месяцев подряд), сюда попадает как есть — программа покажет это
заказчику, а решать ему.

Устройство книги (лист «Пятилетний»), проверено по файлу:
  A  № п/п                     E  единица измерения
  B  наименование средства     F  количество
  C  № карточки учёта          G  периодичность: доля года + вид (0,25 ТО-4)
  D  группа обслуживания       J  норма трудозатрат на одно ТО
  H,I,K,L — ТР и СР: в книге пусты, в плане только ТО.
  Далее по 13 столбцов на год: 12 месяцев + «Всего трудозатрат».
  M..Y — 2026, Z..AL — 2027, AM..AY — 2028, AZ..BL — 2029, BM..BY — 2030.

Запуск:  python3 scripts/export_ppr.py
"""
import io, json, os, re, sys
import openpyxl

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
КНИГА = os.path.join(КОРЕНЬ, "Исходники", "План-график_ППР_2026-2030.xlsx")
ИТОГ = os.path.join(КОРЕНЬ, "Приложение", "ппр.json")

ЛИСТ = "Пятилетний"
ПЕРВАЯ = 4
ПЕРВЫЙ_ГОД_СТОЛБЕЦ = 13          # M
ШИРИНА_ГОДА = 13                 # 12 месяцев + «Всего»


def текст(ws, r, c):
    v = ws.cell(r, c).value
    return "" if v is None else " ".join(str(v).split())


def число(ws, r, c):
    v = ws.cell(r, c).value
    if v in (None, ""):
        return None
    try:
        return float(str(v).replace(",", "."))
    except ValueError:
        return None


def разобрать_периодичность(s):
    """«0,25 ТО-4» → (0.25, "ТО-4"). Доля года и вид обслуживания.

    Доля года подтверждается самими данными: 0,25 размечено раз в
    квартал, 0,083 — ежемесячно, 0,027 — примерно каждые десять дней,
    0,0027 — по рабочим дням. А вот ЧТО ИМЕННО стоит за номерами
    ТО-1…ТО-4, в книге не написано — здесь они не расшифровываются, а
    переносятся как есть.
    """
    m = re.match(r"^([\d.,]+)\s*(.*)$", s or "")
    if not m:
        return None, s or ""
    try:
        доля = float(m.group(1).replace(",", "."))
    except ValueError:
        доля = None
    return доля, " ".join(m.group(2).split())


def собрать():
    if not os.path.exists(КНИГА):
        raise SystemExit("Не найдена книга: %s" % КНИГА)
    wb = openpyxl.load_workbook(КНИГА, data_only=True)
    ws = wb[ЛИСТ]

    # Годы читаем из шапки, а не задаём числом: продлят план — подхватится
    годы = []
    c = ПЕРВЫЙ_ГОД_СТОЛБЕЦ
    while c <= ws.max_column:
        m = re.search(r"(20\d\d)", текст(ws, 1, c))
        if not m:
            break
        годы.append(int(m.group(1)))
        c += ШИРИНА_ГОДА
    if not годы:
        raise SystemExit("В шапке не найдено ни одного года")

    позиции, замечания = [], []
    for r in range(ПЕРВАЯ, ws.max_row + 1):
        имя = текст(ws, r, 2)
        if not имя:
            continue
        доля, вид = разобрать_периодичность(текст(ws, r, 7))
        поз = {
            "id": "ППР-%03d" % (len(позиции) + 1),
            "нп": число(ws, r, 1),
            "наименование": имя,
            "карточка": текст(ws, r, 3),
            "группа": текст(ws, r, 4),
            "ед": текст(ws, r, 5),
            "кол": число(ws, r, 6),
            "доля_года": доля,
            "вид": вид,
            "норма": число(ws, r, 10),
            "план": {},
        }
        for i, год in enumerate(годы):
            нач = ПЕРВЫЙ_ГОД_СТОЛБЕЦ + i * ШИРИНА_ГОДА
            месяцы = {}
            for м in range(12):
                v = число(ws, r, нач + м)
                if v:
                    месяцы[str(м + 1)] = v
            if месяцы:
                поз["план"][str(год)] = месяцы
            # книга сама считает «Всего» — сверяем, чтобы поймать порчу
            итог = число(ws, r, нач + 12)
            сумма = round(sum(месяцы.values()), 4)
            if итог is not None and abs(итог - сумма) > 0.005:
                замечания.append("%s, %d: «Всего» %.2f, а сумма месяцев %.2f"
                                 % (имя[:40], год, итог, сумма))
        # заявленная периодичность против фактической разметки
        ожид = {0.25: 4, 0.083: 12, 0.027: 12, 0.0027: 12}.get(доля)
        for год in годы:
            n = len(поз["план"].get(str(год), {}))
            if ожид and n and n != ожид:
                замечания.append("%s, %d: периодичность «%s» — ожидалось %d месяцев, размечено %d"
                                 % (имя[:40], год, вид, ожид, n))
        позиции.append(поз)

    return {"годы": годы, "позиции": позиции, "замечания": замечания}


def main():
    данные = собрать()
    os.makedirs(os.path.dirname(ИТОГ), exist_ok=True)
    with io.open(ИТОГ, "w", encoding="utf-8") as f:
        json.dump(данные, f, ensure_ascii=False, separators=(",", ":"))
    print("Записано: %s (%.0f КБ)" % (ИТОГ, os.path.getsize(ИТОГ) / 1024.0))
    print("  годы:     %s" % ", ".join(str(г) for г in данные["годы"]))
    print("  позиций:  %d" % len(данные["позиции"]))
    виды = {}
    for п in данные["позиции"]:
        виды[п["вид"]] = виды.get(п["вид"], 0) + 1
    print("  по видам: %s" % ", ".join("%s — %d" % (к, в) for к, в in sorted(виды.items())))
    for год in данные["годы"]:
        часы = sum(sum(п["план"].get(str(год), {}).values()) for п in данные["позиции"])
        работ = sum(len(п["план"].get(str(год), {})) for п in данные["позиции"])
        print("  %d: работ %3d, трудозатрат %.2f" % (год, работ, часы))
    if данные["замечания"]:
        print("\n  ЗАМЕЧАНИЯ ПО КНИГЕ (не исправлены, показаны как есть):")
        for з in данные["замечания"]:
            print("    · %s" % з)
    return 0


if __name__ == "__main__":
    sys.exit(main())
