// ── Для «Проверки данных» и пульта ───────────────────────
function проверкиВибрации(доб, сс){
  const карты=live(ВИБК); if(!карты.length) return;
  const сост=карты.map(состояниеКарты);
  const подпись=к=>"№ "+(к.номер||"")+" "+заголовокКарты(к);
  const безПричины=[];
  live(ВИБИ).forEach(з=>{ const к=найтиПоИд(карты,з.карта); if(!к) return;
    if(оценкаЗамера(з,к).худ==="прев" && !естьПричина(з)) безПричины.push(сс(подпись(к)+" — замер "+ru(з.дата),"vibrocard",к.id)); });
  if(безПричины.length) доб("ошибка","Вибрация","Превышение вибрации без указанной причины: "+безПричины.length,
    безПричины.slice(0,10).concat(безПричины.length>10?["…и ещё "+(безПричины.length-10)]:[]),"vibro");
  const прев=сост.filter(с=>с.ур==="прев");
  if(прев.length) доб("внимание","Вибрация","Превышение вибрации в последнем замере: "+прев.length,
    прев.slice(0,10).map(с=>сс(подпись(с.к)+" — "+ru(с.посл.дата),"vibrocard",с.к.id))
      .concat(["По превышению — протокол в заказывающее подразделение с сопроводительным письмом."]),"vibro");
  const прог=сост.filter(с=>с.ур==="прог");
  if(прог.length) доб("внимание","Вибрация","Возможное превышение вибрации по тренду: "+прог.length,
    прог.slice(0,10).map(с=>сс(подпись(с.к)+" — около "+ru(с.прог[0].когда),"vibrocard",с.к.id)),"vibro");
  const безПред=сост.filter(с=>с.посл && !с.п.предел);
  if(безПред.length) доб("внимание","Вибрация","Карточки с замерами без максимального значения (не с чем сравнивать): "+безПред.length,
    безПред.slice(0,10).map(с=>сс(подпись(с.к),"vibrocard",с.к.id)),"vibro");
  const несвер=live(ВИБН).filter(н=>!н.сверено && карты.some(к=>тотЖеИд(к.норма_ид,н.id)));
  if(несвер.length) доб("наблюдение","Вибрация","Нормы вибрации, не сверенные с текстом документа, применяются в карточках: "+несвер.length,
    несвер.slice(0,10).map(н=>сс(текстНормы(н),"vn",н.id)),"vibronorm");
  const ном={}; карты.forEach(к=>{ const н=String(к.номер||"").trim(); if(н) (ном[н]=ном[н]||[]).push(к); });
  const дубли=Object.keys(ном).filter(н=>ном[н].length>1);
  if(дубли.length) доб("ошибка","Вибрация","Один номер у нескольких карточек учёта вибрации: "+дубли.length,
    дубли.slice(0,10).map(н=>"№ "+н+": "+ном[н].map(заголовокКарты).join("; ")),"vibro");
}
