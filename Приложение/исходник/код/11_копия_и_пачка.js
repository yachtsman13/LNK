// Приборы, применённые по акту: у записи берётся её собственный набор
// (панель «Приборы и НД»), а если запись его не переопределяла —
// стандартный набор метода из «Методик контроля».
function приборыАкта(zs){
  const мт=getМетодики(), ид=[], видели={};
  zs.forEach(z=>methodsOf(z).forEach(м=>{
    const запись=(z.методы||{})[м]||{};
    const список=запись.приборы!=null?запись.приборы:((мт[м]||{}).приборы||[]);
    (список||[]).forEach(id=>{ if(!видели[id]){ видели[id]=1; ид.push(id); } });
  }));
  return ид.map(id=>live(S).find(x=>String(x.id)===String(id))).filter(Boolean);
}
