// 0,25 стоит раз в квартал, 0,083 ежемесячно, 0,027 примерно каждые десять
// дней, 0,0027 по рабочим дням. А что именно означают номера ТО-1…ТО-4, в
// книге не написано — они показаны как есть, расшифровку не выдумываю.
