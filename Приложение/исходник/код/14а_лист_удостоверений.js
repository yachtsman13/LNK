// Чтение картинок из папки и их размеров. Ошибки — по файлу, лист
// собирается из того, что прочиталось.
async function прочестьПолоски(группы, режим){
  const ошибки={};
  const файлы=[...new Set([].concat(...группы.map(г=>г.полоски.map(п=>п.файл))))];
  if(!файлы.length) return {ошибки, папка:"нет файлов"};
  if(!ЕСТЬ_ПАПКИ) return {ошибки, папка:"браузер"};
  const h=await папкаДок(); if(!h) return {ошибки, папка:"нет папки"};
  if(await правоНаПапкуДок(true)!=="есть") return {ошибки, папка:"нет разрешения"};
  const сведения={};
  for(const ф of файлы){
    try{
      const файл=await (await файлИзПапкиДок(h,ф)).getFile();
      const буф=await файл.arrayBuffer();
      const url=URL.createObjectURL(new Blob([буф],{type:файл.type||"image/"+(/png$/i.test(ф)?"png":"jpeg")}));
      const разм=await new Promise((ок,нет)=>{ const im=new Image();
        im.onload=()=>ок({w:im.naturalWidth,h:im.naturalHeight}); im.onerror=()=>нет(new Error("не картинка")); im.src=url; });
      if(!разм.w||!разм.h) throw new Error("пустая картинка");
      сведения[ф]={url, w:разм.w, h:разм.h, dpi:разрешениеКартинки(буф)};
    }catch(e){ ошибки[ф]=e&&e.name==="NotFoundError"?"нет в папке с документами":"не читается как картинка"; }
  }
  группы.forEach(г=>{
    г.полоски=г.полоски.filter(п=>{
      const с=сведения[п.файл];
      if(!с){ г.нет.push((ошибки[п.файл]||"не прочитан")+": "+п.что+" — "+п.файл); return false; }
      const р=размерПолоски(с.w, с.h, с.dpi, режим);
      Object.assign(п, {url:с.url, ш:р.ш, в:р.в, dpi:с.dpi?Math.round(с.dpi.x):0, пикс:с.w+"×"+с.h});
      return true;
    });
  });
  return {ошибки, папка:"есть", урлы:Object.values(сведения).map(с=>с.url)};
}
