const СИМВОЛЫ_ПОЛЯ=["°","±","×","÷","≤","≥","≈","Ø","\u2116","µ"];
function вставитьСимвол(id, с){
  const п=document.getElementById(id); if(!п) return;
  const a=(п.selectionStart==null)?п.value.length:п.selectionStart;
  const b=(п.selectionEnd==null)?a:п.selectionEnd;
  п.value=п.value.slice(0,a)+с+п.value.slice(b);
  п.focus();
  try{ п.selectionStart=п.selectionEnd=a+с.length; }catch(e){}
  // тем же событием, что и обычный ввод — иначе форма не считалась бы
  // изменённой и защита от потери несохранённого её бы не удержала
  п.dispatchEvent(new Event("input",{bubbles:true}));
}
