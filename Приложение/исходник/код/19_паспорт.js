// Разделы 1-5 собираются из настоящих данных: карточки лаборатории,
// справочника специалистов (с аттестациями) и справочника приборов.
// Разделы 6-11 форма требует, а данных для них в программе нет —
// НЕ выдумываю: печатаются заголовки разделов с честной пометкой,
// что заполнить нечем, а не пустые таблицы, которые выглядели бы как
// «в лаборатории этого нет».
function специалистДляПаспорта(сп){
  const атт=аттестации(сп);
  const методСтрока=атт.length ? атт.map(а=>{
    let s=(а.метод||"—");
    if(а.уровень) s+=" ур."+а.уровень;
    if(а.объекты) s+=" ("+а.объекты+")";
    return s;
  }).join("; ") : "";
  const аттДаты=атт.length ? атт.map(а=>{
    let s=[];
    if(а.вид) s.push(а.вид.toLowerCase());
    if(а.дата) s.push("аттестован "+ru(а.дата));
    if(а.номер) s.push("уд. № "+а.номер+(а.дата_выдачи?(" от "+ru(а.дата_выдачи)):""));
    if(а.орган) s.push(а.орган);
    if(а.до) s.push("до "+ru(а.до));
    return s.join(", ");
  }).join("; ") : "";
  const пбз=пб(сп);
  const пбСтрока=пбз && пбз.номер
    ? ("ПБ: уд. № "+пбз.номер+(пбз.дата?(" от "+ru(пбз.дата)):"")) : "";
  return {
    фио: типографика(сп.фио||сп.вдок||""),
    основание: "по основному месту работы",
    должность: типографика([сп.должность, сп.функции, методСтрока].filter(Boolean).join(" · ")),
    образование: типографика([сп.образование, сп.стаж ? ("стаж по НК с "+сп.стаж) : ""]
      .filter(Boolean).join("; ")),
    аттестация: типографика([аттДаты, пбСтрока].filter(Boolean).join("; "))
  };
}
// Категория прибора определяет, в какой из разделов 5–8 паспорта (одна и
// та же Форма 2 СДАНК-01-2020) он попадёт. У записей без категории (старые,
// заведённые до этого поля, или из журнала/приборов, где категория не
// заполнялась) считаем «Средство НК» — иначе раздел 5 внезапно опустеет.
// Импорт из Excel не проверяет текст категории против списка (это select
// только в форме ручного ввода) — опечатка или лишний пробел в файле дадут
// значение, которого нет в КАТЕГОРИИ_СИ. Без этой подстраховки такой прибор
// не попал бы НИ В ОДИН из разделов 5-8 паспорта: прТабл()/прТаблWord()
// берут только 4 канонических ключа, а неопознанное значение осело бы в
// незнакомом ключе группировки и осталось бы невидимым молча.
function приборКатегория(x){
  return (x.категория && КАТЕГОРИИ_СИ.includes(x.категория)) ? x.категория : "Средство НК";
}
function приборыПоКатегориям(){
  const г={}; КАТЕГОРИИ_СИ.forEach(к=>г[к]=[]);
  // Списанные в паспорт не идут (см. приборыВДокументы) — разделы 5-8
  // перечисляют оборудование, которое у лаборатории есть.
  приборыВДокументы().forEach(x=>{ const к=приборКатегория(x); if(!г[к]) г[к]=[]; г[к].push(x); });
  return г;
}
// Заказчик попросил делить оборудование (разделы 5-8) и нормативные
// документы (раздел 9) паспорта на подгруппы по методу контроля —
// список упорядочен как METHODS (порядок журнала), группа без метода
// (свободный текст не из списка или вовсе пусто) — последней, отдельно.
// Общая функция для обоих разделов, поле для группировки — параметром,
// у прибора и у норм. документа оно называется одинаково («метод»), но
// незачем это жёстко зашивать.
// Общая группировка по полю с фиксированным порядком значений (список
// значений — параметром, не зашит): приборы — по METHODS, норм. документы
// раздела 9 — по НД_КАТЕГОРИИ (девять содержательных групп из настоящего
// паспорта, не по методу — там смесь предмета и метода, простой METHODS
// не подходит). Значение не из списка (пусто, опечатка, старая запись без
// поля) — в отдельную группу с ключом "" последней, не пропадает молча.
function группыПоПолю(список, поле, порядок){
  const группы={};
  список.forEach(x=>{
    const зн=x[поле];
    const ключ=(зн && порядок.includes(зн)) ? зн : "";
    (группы[ключ]=группы[ключ]||[]).push(x);
  });
  const из=[];
  порядок.forEach(зн=>{ if(группы[зн]) из.push([зн, группы[зн]]); });
  if(группы[""]) из.push(["", группы[""]]);
  return из;
}
function группыПоМетоду(список, методПоле){
  return группыПоПолю(список, методПоле||"метод", METHODS);
}
function группыНдПоКатегории(список){
  return группыПоПолю(список, "категория", НД_КАТЕГОРИИ);
}
