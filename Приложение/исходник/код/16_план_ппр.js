// Годы плана: книжные плюс любой год, до которого план продлили руками.
function годыППР(){
  const г=new Set((ППР.годы||[]).map(Number));
  live(ППР_ПОЗ||[]).forEach(п=>Object.keys(п.план||{}).forEach(x=>{
    if(Object.keys(п.план[x]||{}).length) г.add(+x); }));
  return [...г].filter(x=>isFinite(x)).sort((a,b)=>a-b);
}
// Расхождение разметки с заявленной периодичностью — то же правило, что
// export_ppr.py применял к книге, но по ЖИВОМУ плану: поправили позицию —
// замечание ушло само, а не висит текстом из книги.
function замечанияППР(){
  const из=[];
  позицииППР().forEach(п=>{
    const ожид={0.25:4, 0.083:12, 0.027:12, 0.0027:12}[+п.доля_года];
    if(!ожид) return;
    Object.keys(п.план||{}).sort().forEach(г=>{
      const n=Object.keys(п.план[г]||{}).length;
      if(n && n!==ожид) из.push(String(п.наименование||"").slice(0,40)+", "+г+
        ": периодичность «"+(п.вид||"")+"» — ожидалось "+ожид+" месяцев, размечено "+n);
    });
  });
  return из;
}
function ключОтметки(п,год,мес){ return п.id+"|"+год+"|"+мес; }
function отметка(п,год,мес){
  return live(ОТМ).find(о=>о.id===ключОтметки(п,год,мес))||null;
}
function отметить(идПоз,год,мес,кто,тихо){
  const п=live(ППР_ПОЗ).find(x=>x.id===идПоз); if(!п) return;
  const к=ключОтметки(п,год,мес);
  const был=ОТМ.find(о=>о.id===к);
  if(был && !был.удалено){                       // повторное нажатие снимает отметку
    был.удалено=new Date().toISOString(); был.изменено=был.удалено; был.место=getWS().код;
  } else if(был){
    был.удалено=""; был.выполнено=new Date().toISOString().slice(0,10);
    был.кто=кто||был.кто||""; был.изменено=new Date().toISOString(); был.место=getWS().код;
  } else {
    ОТМ.push({id:к, поз:идПоз, год:год, мес:мес,
              выполнено:new Date().toISOString().slice(0,10), кто:кто||"",
              место:getWS().код, изменено:new Date().toISOString()});
  }
  saveReg(REG_ППР,ОТМ);
  if(!тихо) renderPlan();
}

let план={год:null, толькоНеВыполненные:false};
function годПлана(){
  if(план.год) return план.год;
  const т=new Date().getFullYear();
  const годы=годыППР();
  план.год = годы.indexOf(т)>=0 ? т : (годы[0]||т);
  return план.год;
}
