//       Поверка <наименование> <тип> зав. №<номер> поверка до ДД.ММ.ГГГГ.pdf
//       Паспорт <тип> зав. №<номер>.pdf, Руководство по эксплуатации <тип>.pdf …
//   Средства измерений/Архив/<та же папка метода>/        — истёкшие свидетельства
//   Нормативные документы/<раздел IX паспорта>/<обозначение> <наименование>.pdf
//   Нормативные документы/Архив/<раздел IX паспорта>/     — заменённые и отменённые
