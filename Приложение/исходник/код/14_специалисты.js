// Ширина колонки ФИО в «Специалистах» — по самой широкой фамилии в
// списке, а не общий min-width:280px у td.obj (тот стоит для других
// таблиц программы, где имена и названия обычно длиннее). Тот же приём,
// что и у ширинаДолжностей в акте — canvas-замер настоящим шрифтом
// таблицы (table{font-size:13px} перебивает шрифт body, меряем именно им),
// не оценка на глаз.
function мераUI(){
  if(!мераUI._к) мераUI._к=document.createElement("canvas").getContext("2d");
  return мераUI._к;
}
function ширинаФИОКолонки(значения){
  const ctx=мераUI(); if(!ctx) return 200;
  ctx.font='13px "Segoe UI", system-ui, Arial, sans-serif';
  let макс=ctx.measureText("ФИО").width;
  (значения||[]).forEach(s=>{ макс=Math.max(макс, ctx.measureText(String(s||"")).width); });
  // отступы ячейки (12px слева и справа) + запас, чтобы не переносило
  // вплотную — тем же принципом, что и у ширинаДолжностей (3%, не меньше
  // небольшого фиксированного зазора).
  return Math.ceil(макс*1.03)+24+10;
}
// Сортировка списка специалистов — тот же приём, что у журнала
// (jsort/sortJournal): состояние в localStorage, стрелка на заголовке,
// пустые значения всегда внизу. Статусные колонки сортируются по
// СЫРОЙ дате «до» (не по тексту статуса — «просрочено» не должно
// сортироваться как обычная строка вперемешку с «до …»).
let псорт=(function(){ try{ const r=ХР.getItem("lnk_psort");
  if(r){ const o=JSON.parse(r); if(o&&o.c) return {c:o.c,d:o.d===1?1:-1}; } }catch(e){}
  return {c:"фио", d:1}; })();
function псортSave(){ try{ ХР.setItem("lnk_psort",JSON.stringify(псорт)); }catch(e){} }
function sortPeople(c){
  if(псорт.c===c) псорт.d=-псорт.d; else { псорт.c=c; псорт.d=1; }
  псортSave(); renderPeople();
}
function peopleSortKey(p,c){
  switch(c){
    case "должность": return p.должность||"";
    case "функции": return p.функции||"";
    case "стаж": return p.стаж||"";
    case "инструктаж": return инструктажДо(p.инструктаж_дата)||"";
    case "огрпр": return огрПространстваДо(p.огр_простр_дата)||"";
    case "электробез": return электробезДо(p.эл_безоп_дата)||"";
    case "пожбез": return пожбезДо(p.пожбез_дата)||"";
    case "пб": return пбДо(p)||"";
    case "а1": return а1До(p.а1_дата)||"";
    case "аттестация": return ближайшаяАттестацияДата(p)||"";
    case "классность": return ближайшаяКлассностьДата(p)||"";
    default: return p.вдок||p.фио||"";
  }
}
function peopleRows(){
  return live(P).slice().sort((a,b)=>{
    const A=String(peopleSortKey(a,псорт.c)||""), B=String(peopleSortKey(b,псорт.c)||"");
    if(!A && !B) return 0;
    if(!A) return 1;
    if(!B) return -1;
    return A.localeCompare(B,"ru",{numeric:true})*псорт.d;
  });
}
