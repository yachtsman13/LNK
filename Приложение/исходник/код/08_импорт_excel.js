function импортЖурналПрименить(строки){
  const все=ЖУРНАЛ_ПОЛЯ.map(f=>({л:f.l,k:f.k,тип:f.тип}));
  METHODS.forEach(м=>полеМетодаПравка(м).forEach(f=>все.push({л:f.l,k:f.k,м:м})));
  const шапка=строки[0], сопост={}; let колКода="";
  Object.keys(шапка).forEach(буква=>{
    const текст=String(шапка[буква]||"").trim().toLowerCase();
    if(текст===КОЛ_КОД.toLowerCase()){ колКода=буква; return; }
    const f=все.find(x=>x.л.trim().toLowerCase()===текст);
    if(f) сопост[буква]=f;
  });
  if(!Object.values(сопост).some(f=>f.k==="объект" && !f.м)){
    alert("Не нашёл колонку «Объект контроля» — сверьте шапку файла с выгрузкой "+
      "«Выгрузить для правки» (заголовки не переименовывались?).");
    return;
  }
  const живые=liveJ();
  const правки=[], новые=[];
  const кодыНеНашлись=new Set(), объектыНеНашлись=new Set();
  const непонятно=new Set(), стёрто=new Map();
  const пусто=v=>String(v==null?"":v).trim()==="";
  const такоеЖе=(a,b)=>String(a==null?"":a).trim()===String(b==null?"":b).trim();
  // Карточка объекта ищется так же, как при сохранении формы: по имени
  // ВМЕСТЕ с заводским номером — по одному имени нельзя, у десятков
  // баллонов оно одинаковое.
  const карточкаОбъекта=(строка,зав,рег)=>{
    if(!разобратьСтрокуОбъекта(строка).имя) return null;
    return карточкаПоСтроке(строка,зав,рег);
  };
  for(let i=1;i<строки.length;i++){
    const ряд=строки[i], знач={}, мзнач={};
    Object.keys(сопост).forEach(буква=>{
      const f=сопост[буква];
      let v=String(ряд[буква]||"").trim();
      if(f.тип==="дата"){
        const д=значениеДаты(v);
        if(v && !д){ непонятно.add(f.л+": «"+v+"»"); return; }   // не пусто — не стираю
        v=д;
      }
      if(f.м){ (мзнач[f.м]=мзнач[f.м]||{})[f.k]=v; } else знач[f.k]=v;
    });
    const код=колКода?String(ряд[колКода]||"").trim():"";
    if(код){
      const был=найтиПоИд(живые,код);
      if(!был){ кодыНеНашлись.add(код); continue; }
      const поля=[], мполя=[];
      // Пустая ячейка стирает значение (см. стёртоТекст).
      Object.keys(знач).forEach(k=>{
        if(такоеЖе(был[k],знач[k])) return;
        if(пусто(знач[k])) стёртоДоб(стёрто,ЖУРНАЛ_ПОЛЯ.find(f=>f.k===k).l);
        поля.push(k);
      });
      METHODS.forEach(м=>{
        const было=(был.методы||{})[м]||{};
        Object.keys(мзнач[м]||{}).forEach(k=>{
          const v=мзнач[м][k];
          if(такоеЖе(было[k],v)) return;
          if(пусто(v)) стёртоДоб(стёрто,полеМетодаПравка(м).find(f=>f.k===k).l);
          мполя.push({м:м,k:k,v:v});
        });
      });
      if(поля.length||мполя.length) правки.push({rec:был,знач:знач,поля:поля,мполя:мполя});
      continue;
    }
    // Новая запись — как в форме: нужен объект или № акта, иначе это
    // просто пустая строка в конце файла, а не ошибка.
    if(пусто(знач.объект) && пусто(знач.акт)) continue;
    const rec={};
    ЖУРНАЛ_ПОЛЯ.forEach(f=>{ if(!пусто(знач[f.k])) rec[f.k]=знач[f.k]; });
    rec.год=rec.дата?String(rec.дата).slice(0,4):"";
    const методы={};
    METHODS.forEach(м=>{
      const з={}; let есть=false;
      Object.keys(мзнач[м]||{}).forEach(k=>{ if(!пусто(мзнач[м][k])){ з[k]=мзнач[м][k]; есть=true; } });
      if(есть) методы[м]=з;
    });
    rec.методы=методы;
    const карт=карточкаОбъекта(rec.объект,rec.зав,rec.рег);
    if(карт){ rec.объект_ид=карт.id; if(!rec.наименование) rec.наименование=карт.наименование; }
    else if(!пусто(rec.объект)) объектыНеНашлись.add(rec.объект);
    новые.push(rec);
  }
  if(!новые.length && !правки.length){
    alert("Менять нечего: заполненных строк не нашлось или все значения совпадают с тем, "+
      "что уже в журнале."+
      (кодыНеНашлись.size?("\n\nКоды записей, которых нет в журнале (строки пропущены): "+
        [...кодыНеНашлись].slice(0,10).join(", ")):""));
    return;
  }
  const частей=правки.reduce((n,п)=>n+п.поля.length+п.мполя.length,0);
  const что=[
    правки.length?("обновить "+правки.length+" "+числослово(правки.length,["запись","записи","записей"])+
      " ("+частей+" "+числослово(частей,["поле","поля","полей"])+")"):"",
    новые.length?("добавить "+новые.length+" "+числослово(новые.length,["запись","записи","записей"])):""
  ].filter(Boolean).join(" и ");
  if(!confirm("Журнал: "+что+"?\n\n"+
    (правки.length?"Правка идёт по колонке «"+КОЛ_КОД+"»: строка ложится в свою запись, "+
      "а не добавляется копией. Пустая ячейка очищает поле; столбец, которого в файле нет, "+
      "не трогается.\n":"")+
    "\nВ файле нет и потому не тронутся: "+ЖУРНАЛ_НЕ_В_ФАЙЛЕ+" — они правятся в самой записи.\n"+
    (непонятно.size?("\nНе разобрано, поле оставлю как было: "+[...непонятно].slice(0,10).join(" | ")):"")+
    (кодыНеНашлись.size?("\nКодов, которых нет в журнале (строки пропущу): "+
      [...кодыНеНашлись].slice(0,10).join(", ")):"")+
    (объектыНеНашлись.size?("\n\nКарточка объекта не нашлась (запись заведу, связь с карточкой "+
      "останется пустой): "+[...объектыНеНашлись].slice(0,10).join(" | ")):"")+
    стёртоТекст(стёрто))) return;
  // Закрытые годы: строки, которые меняют запись закрытого года (или
  // переносят дату в закрытый год, или заводят запись с такой датой), —
  // отдельным вопросом. Отказ — эти строки пропускаются, остальные идут.
  const вЗакр=п=>записьЗакрыта(п.rec) || (п.поля.indexOf("дата")>=0 && годЗакрыт(String(п.знач.дата||"").slice(0,4)));
  const закрП=правки.filter(вЗакр), закрН=новые.filter(r=>годЗакрыт(годЗаписи(r)));
  if(закрП.length||закрН.length){
    const годы=[...new Set(закрП.map(п=>годЗаписи(п.rec)).concat(закрН.map(годЗаписи))
      .concat(закрП.filter(п=>п.поля.indexOf("дата")>=0).map(п=>String(п.знач.дата||"").slice(0,4))).filter(годЗакрыт))].sort();
    if(!яНачальник()) alert("🔒 Закрыт"+(годы.length>1?"ы годы ":" год ")+годы.join(", ")+".\n\nСтроки закрытого года ("+
      (закрП.length+закрН.length)+") пропущу: их правит только место начальника. Остальное загружу.");
    if(!яНачальник() || !confirm("🔒 Закрыт"+(годы.length>1?"ы годы ":" год ")+годы.join(", ")+".\n\nВ файле по закрытому году: "+
      [закрП.length?"правок записей "+закрП.length:"", закрН.length?"новых записей "+закрН.length:""].filter(Boolean).join(", ")+
      ".\n\nОК — изменить и их; Отмена — пропустить эти строки, остальное загрузить.")){
      закрП.forEach(п=>правки.splice(правки.indexOf(п),1));
      закрН.forEach(r=>новые.splice(новые.indexOf(r),1));
      if(!правки.length && !новые.length){ toast("Всё в файле — по закрытому году; ничего не загружено"); return; }
    }
  }
  отменаНачать("импорт журнала", [STORE_KEY]);
  const отметка=new Date().toISOString(), место=getWS().код;
  правки.forEach(п=>{
    п.поля.forEach(k=>{
      п.rec[k]=п.знач[k];
      if(k==="дата") п.rec.год=String(п.знач[k]||"").slice(0,4);
      if(k==="объект"){
        // Строку объекта поменяли — связь с карточкой пересчитываем, как
        // это делает форма записи; не нашлась — связь пустая, а не чужая.
        const карт=пусто(п.знач[k])?null:карточкаОбъекта(п.знач[k], п.знач.зав!=null?п.знач.зав:п.rec.зав, п.знач.рег!=null?п.знач.рег:п.rec.рег);
        п.rec.объект_ид=карт?карт.id:"";
        if(!карт && !пусто(п.знач[k])) объектыНеНашлись.add(п.знач[k]);
      }
    });
    п.мполя.forEach(({м,k,v})=>{
      п.rec.методы=п.rec.методы||{};
      п.rec.методы[м]=Object.assign({}, п.rec.методы[м]||{});
      п.rec.методы[м][k]=v;
    });
    п.rec.изменено=отметка; п.rec.место=место;   // иначе правка не уйдёт в обмен
  });
  новые.forEach((rec,i)=>{
    rec.id=newId(); rec.нп=J.length+i+1;
    rec.изменено=отметка; rec.место=место;
  });
  if(новые.length) J.unshift(...новые);
  saveJournal();
  отменаЗавершить();
  switchView("journal");
  toast([правки.length?("обновлено "+правки.length):"",
         новые.length?("добавлено "+новые.length):""].filter(Boolean).join(", "));
  // Тот же разбор столкновений, что и после приёма файла обмена: номера
  // протоколов правятся вручную, значит два места могли занять один.
  const столк=проверитьСтолкновения();
  if(столк.length) alert("ВНИМАНИЕ: одинаковые номера у разных записей.\n\n"+
    столк.slice(0,15).join("\n")+(столк.length>15?("\n… и ещё "+(столк.length-15)):""));
}

