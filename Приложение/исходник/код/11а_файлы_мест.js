// ── Сверка своей папки ─────────────────────────────────────
// Каждый файл из карточек: есть ли в своей папке и тот ли. Файлу, у
// которого ещё нет записи в реестре, она заводится отсюда (решение
// заказчика: отпечаток — с того места, где файл нашёлся первым).
let _сверкаИдёт=null;
async function сверитьФайлы(h){
  if(_сверкаИдёт) return _сверкаИдёт;
  _сверкаИдёт=(async()=>{
    const было=файлыМеста(), пути=путиСсылок(), ф={};
    let заведено=0;
    for(const id of Object.keys(пути)){
      const с=await сведенияФайла(h, пути[id], было.ф[id]);
      ф[id]=с;
      if(с.есть && !ФАЙЛЫ.some(x=>x.id===id && !x.удалено)){
        записатьВерсиюФайла(пути[id], с); заведено++;
      }
    }
    const м={проверено:new Date().toISOString(), папка:h.name||"", ф};
    сохранитьФайлыМеста(м);
    return {м, заведено};
  })();
  try{ return await _сверкаИдёт; } finally{ _сверкаИдёт=null; }
}
