// ── Вход в программу по паролю, права у человека (3.86, этап 1) ──
// Решения заказчика (ТЗ/Проработка_календарь_задачи.md): входят только
// специалисты из справочника, своим паролем 4–20 знаков; права —
// начальник / заместитель / специалист — у человека (поле «Права» в
// карточке специалиста), а не у компьютера; автовыход через N минут без
// действий, время своё на каждом компьютере (по умолчанию 15); свой пароль
// специалист меняет сам, забытый сбрасывают начальник или заместитель
// (выдают временный, при входе его меняют на свой); входа «только
// просмотр» нет; ПИН-код настроек убран — то, что он закрывал, меняют
// только начальник и заместитель (23б, ПРАВА_ГРУППЫ).
//
// Пока вход не включён, программа работает как раньше (права — по
// отметке «начальник» у места). Включает руководитель в «Лаборатории».
//
// Хранится не пароль, а его отпечаток (PBKDF2-SHA-256, своя соль у
// каждого). Отпечатки — ДАННЫЕ: ходят в обмене и копии, поэтому
// специалист входит на любом месте своим паролем, а сброс доходит до
// других мест с ближайшим обменом. Честно: программа — один файл без
// сервера; вход защищает от случайного человека и путаницы «кто правил»,
// но не от знающего — данные лежат в браузере.
const REG_ВХОД="lnk_auth", REG_ПОЛЬЗ="lnk_users", КЛ_АВТОВЫХОД="lnk_autologout", REG_ПИН_СТАРЫЙ="lnk_pin";
const ПРАВА=["Начальник","Заместитель","Специалист"];
const АВТОВЫХОД_ПО_УМОЛЧАНИЮ=15, ПАРОЛЬ_МИН=4, ПАРОЛЬ_МАКС=20, ПАРОЛЬ_ИТЕРАЦИЙ=100000;

function вход(){
  let v=null; try{ v=JSON.parse(ХР.getItem(REG_ВХОД)||"null"); }catch(e){}
  return Object.assign({вкл:false, группы:ПРАВА_ПО_УМОЛЧАНИЮ(), изменено:"", место:"", кто:"", сброшен:null}, v||{});
}
function сохранитьВход(о, какЕсть){
  if(!какЕсть){ о.изменено=new Date().toISOString(); о.место=getWS().код; о.кто=ктоЯ(); }
  try{ ХР.setItem(REG_ВХОД, JSON.stringify(о)); }catch(e){ переполнение(e); }
}
function входВкл(){ return !!вход().вкл; }
function слитьВход(вход_){
  if(!вход_ || typeof вход_!=="object") return false;
  if(String(вход_.изменено||"")>String(вход().изменено||"")){ сохранитьВход(JSON.parse(JSON.stringify(вход_)), true); return true; }
  return false;
}

// Пароли: запись на специалиста, id «У:<id специалиста>».
function загрузитьПольз(){
  try{ const v=JSON.parse(ХР.getItem(REG_ПОЛЬЗ)||"null"); return v&&Array.isArray(v.rows)?v.rows:[]; }catch(e){ return []; }
}
let ПОЛЬЗ=загрузитьПольз();
function сохранитьПольз(){
  try{ ХР.setItem(REG_ПОЛЬЗ, JSON.stringify({версия:DB.версия, сохранено:new Date().toISOString(), rows:ПОЛЬЗ})); }
  catch(e){ переполнение(e); }
}
function пользСп(ид){ return ПОЛЬЗ.find(x=>x.сп===String(ид) && !x.удалено)||null; }
function слитьПольз(вход_){
  if(!Array.isArray(вход_)) return 0;
  let n=0;
  вход_.forEach(r=>{
    if(!r || !r.id) return;
    const i=ПОЛЬЗ.findIndex(x=>x.id===r.id);
    if(i<0){ ПОЛЬЗ.push(JSON.parse(JSON.stringify(r))); n++; }
    else if(String(r.изменено||"")>String(ПОЛЬЗ[i].изменено||"")){ ПОЛЬЗ[i]=JSON.parse(JSON.stringify(r)); n++; }
  });
  if(n) сохранитьПольз();
  return n;
}

// Права специалиста: своё поле, а пусто — по должности (из книги:
// «Начальник ЛНК», «Заместитель начальника ЛНК»).
function праваСпец(сп){
  const п=String(сп&&сп.права||"").trim(); if(ПРАВА.indexOf(п)>=0) return п;
  const д=String(сп&&сп.должность||"").trim().toLowerCase().replace(/\s+/g," ");
  if(д==="начальник лнк") return "Начальник";
  if(д==="заместитель начальника лнк") return "Заместитель";
  return "Специалист";
}
function руководитель(сп){ const п=праваСпец(сп); return п==="Начальник"||п==="Заместитель"; }

