// Открыть файл из папки с документами в новой вкладке (сам документ —
// PDF, Word — показывает браузер или открывает своя программа). Окно
// открывается СРАЗУ, до чтения папки: после ожидания браузер счёл бы
// окно непрошеным и не открыл.
async function открытьФайлДок(имя){
  if(!путьФайлаДок(имя)){ toast("Имя файла не указано"); return; }
  if(!ЕСТЬ_ПАПКИ){ toast("Этот браузер не умеет открывать файлы из папки — так умеют Chrome и Edge"); return; }
  const w=window.open("about:blank","_blank");
  const закрыть=()=>{ try{ w&&w.close(); }catch(e){} };
  try{
    const h=await папкаДок();
    if(!h){ закрыть(); if(confirm("Папка с документами ещё не выбрана.\n\nВыбрать её сейчас?")) await выбратьПапкуДок(); return; }
    if(await правоНаПапкуДок(true)!=="есть"){ закрыть(); toast("Нет разрешения на папку с документами"); return; }
    let ф;
    try{ ф=await (await файлИзПапкиДок(h,имя)).getFile(); }
    catch(e){ закрыть(); toast("Файла «"+имя+"» нет в папке с документами"); return; }
    const url=URL.createObjectURL(ф);
    if(w) w.location.href=url; else window.open(url,"_blank");
    setTimeout(()=>{ try{ URL.revokeObjectURL(url); }catch(e){} }, 120000);
  }catch(e){ закрыть(); toast("Не открылось: "+(e&&e.message||e)); }
}
