async function хешПароля(пароль, соль){
  const enc=new TextEncoder();
  const ключ=await crypto.subtle.importKey("raw", enc.encode(String(пароль)), "PBKDF2", false, ["deriveBits"]);
  const б=await crypto.subtle.deriveBits({name:"PBKDF2", salt:enc.encode(соль), iterations:ПАРОЛЬ_ИТЕРАЦИЙ, hash:"SHA-256"}, ключ, 256);
  return [...new Uint8Array(б)].map(x=>x.toString(16).padStart(2,"0")).join("");
}
function новаяСоль(){ return [...crypto.getRandomValues(new Uint8Array(16))].map(x=>x.toString(16).padStart(2,"0")).join(""); }
function ошибкаПароля(пароль){
  const п=String(пароль||"");
  if(п.length<ПАРОЛЬ_МИН) return "Пароль — не меньше "+ПАРОЛЬ_МИН+" знаков";
  if(п.length>ПАРОЛЬ_МАКС) return "Пароль — не больше "+ПАРОЛЬ_МАКС+" знаков";
  return "";
}
async function записатьПароль(ид, пароль, временный){
  const соль=новаяСоль(), хеш=await хешПароля(пароль, соль);
  const id="У:"+String(ид);
  let у=ПОЛЬЗ.find(x=>x.id===id);
  if(!у){ у={id, сп:String(ид)}; ПОЛЬЗ.push(у); }
  Object.assign(у, {соль, хеш, временный:!!временный, изменено:new Date().toISOString(), место:getWS().код, кто:ктоЯ()});
  delete у.удалено;
  сохранитьПольз();
}
async function парольВерен(ид, пароль){
  const у=пользСп(ид); if(!у || !у.хеш) return false;
  return (await хешПароля(пароль, у.соль))===у.хеш;
}
function состояниеПароля(ид){
  const у=пользСп(ид);
  if(!у || !у.хеш) return "не выдан";
  return у.временный?"временный":"свой";
}
function временныйПароль(){ return String(100000+(crypto.getRandomValues(new Uint32Array(1))[0]%900000)); }

