// Ширины образца — под ширину текста (сумма = ПРОТ_ШИРИНА).
function пШирины(ш, всего){
  всего=всего||ПРОТ_ШИРИНА; const с=ш.reduce((a,b)=>a+b,0);
  const р=ш.map(x=>Math.round(x*всего/с)); р[р.length-1]+=всего-р.reduce((a,b)=>a+b,0); return р;
}

