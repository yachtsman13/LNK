// ── Комментарии, заметки, проекты задач (3.88) ──────────────
// Этап 2 проработки (ТЗ/Проработка_календарь_задачи.md, п. 3).
//
// Кто пишет: с включённым входом — вошедший специалист (автор_ид — id
// карточки, автор — «Фамилия И.О.»), без входа — рабочее место (код).
// «Своё» (правка и удаление своего комментария, своя заметка «только мне»,
// свой проект) — по автор_ид при входе, иначе по месту (мойКод учитывает и
// прежние коды места после смены кода).
function ктоПишет(){
  return {автор:ктоЯ()||getWS().код, автор_ид:(входВкл()&&_я!=null)?String(_я):"", место:getWS().код};
}
// строго — правка и удаление комментария: при входе запись без автор_ид
// (написана до включения входа) не своя ни для кого, иначе её правил бы
// любой, кто вошёл на том же месте. Не строго (заметки, проекты) — такая
// запись своя для места, где написана: иначе заметка «только мне»,
// написанная до входа, пропала бы и у автора.
function своёЗаписи(x, строго){
  if(!x) return false;
  if(входВкл()){
    if(x.автор_ид) return String(x.автор_ид)===String(_я);
    if(строго) return false;
  }
  return мойКод(x.место);
}
function датаВремя(iso){
  const с=String(iso||""); if(!с) return "";
  const д=new Date(с); if(isNaN(д)) return ru(с.slice(0,10));
  const два=n=>String(n).padStart(2,"0");
  return два(д.getDate())+"."+два(д.getMonth()+1)+"."+д.getFullYear()+(/T00:00:00/.test(с)?"":" "+два(д.getHours())+":"+два(д.getMinutes()));
}

