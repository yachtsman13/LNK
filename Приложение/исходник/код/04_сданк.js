// Черновик фразы об объектах. Две формы — обе ваши:
//   один тип на всех  → «Баллон … , зав. №№ 1, 2, 3»          (акт 28-2026)
//   разные объекты    → «испаритель …; конденсатор … и ресивер …» (акт 35-2026)
// Номера при группе одинаковых объектов: сначала ВСЕ заводские, затем ВСЕ
// регистрационные — так их и читают. В перечислении разнотипных объектов
// номера остаются при своём объекте, иначе потеряется, что чьё.
function черновикОбъектов(zs){
  const имена=[...new Set(zs.map(именоватьОбъект).filter(Boolean))];
  if(имена.length===1){
    const завы=zs.map(завЗаписи).filter(Boolean);
    const реги=zs.map(регЗаписи).filter(Boolean);
    let т=вПадеже(имена[0]);
    if(завы.length) т+=", зав. №№ "+завы.join(", ");
    if(реги.length) т+=", рег. №№ "+реги.join(", ");
    return т;
  }
  const части=zs.map(z=>{
    const ч=[вПадеже(именоватьОбъект(z))];
    if(завЗаписи(z)) ч.push("зав. № "+завЗаписи(z));
    if(регЗаписи(z)) ч.push("рег. № "+регЗаписи(z));
    return ч.filter(Boolean).join(", ");
  }).filter(Boolean);
  if(части.length>1) return части.slice(0,-1).join("; ")+" и "+части[части.length-1];
  return части[0]||"";
}
