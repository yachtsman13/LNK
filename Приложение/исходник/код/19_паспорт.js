function ширинаАльбомТабл(){ return _таблПаспорт?ПАСП_ШИРИНА_ТАБЛ:ШИРИНА_АЛЬБОМ; }
// Готовые ширины колонок (посчитаны под ШИРИНА_АЛЬБОМ) — под ширину
// таблицы паспорта, пропорционально; остаток — в последнюю колонку,
// чтобы сумма gridCol точно совпала с tblW.
function подШиринуТабл(ш){
  const всего=ширинаАльбомТабл(), сум=ш.reduce((a,b)=>a+b,0);
  const из=ш.map(x=>Math.floor(x*всего/сум));
  из[из.length-1]+=всего-из.reduce((a,b)=>a+b,0);
  return из;
}
