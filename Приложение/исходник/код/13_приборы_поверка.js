// Форма: поверка части показывается нередактируемой и подставляется из
// выбранного основного прибора сразу, ещё до сохранения — чтобы было
// видно, что именно уйдёт в карточку.
function частьВыбрана(id){
  const осн=id?S.find(x=>String(x.id)===String(id)):null;
  ПОЛЯ_ПОВЕРКИ_ЧАСТИ.forEach(к=>{
    const поле=document.getElementById("rf_"+к); if(!поле) return;
    поле.readOnly=!!осн;
    // у выпадающего списка readOnly не действует — запираю disabled
    // (значение saveRegRec читает и у запертого)
    if(поле.tagName==="SELECT" || поле.type==="checkbox") поле.disabled=!!осн;
    поле.classList.toggle("отосновного", !!осн);
    поле.title=осн?"Берётся у основного прибора, не редактируется":"";
    if(осн){ if(поле.type==="checkbox") поле.checked=!!осн[к]; else поле.value=осн[к]||""; }
  });
  ПОЛЯ_НЕ_У_ЧАСТИ.forEach(к=>{
    const поле=document.getElementById("rf_"+к); if(!поле) return;
    const строка=поле.closest("label"); if(строка) строка.style.display=осн?"none":"";
    if(!осн) return;
    // Месяцы — контейнер с вложенными списками, у него самого value нет:
    // очищаю каждый год, иначе значение уцелело бы скрытым и всплыло в
    // документах.
    if(поле.classList.contains("месгоды")) поле.querySelectorAll("select").forEach(el=>el.value="");
    else поле.value="";
  });
  // Прибор, который сам является частью другого, по умолчанию помечается
  // как не имеющий своих составных частей (указание заказчика). Только
  // если поле ещё пустое — уже выбранное значение не переписываем: у
  // датчика-комплекта свои части быть могут.
  const сост=document.getElementById("rf_составной");
  if(осн && сост && !сост.value) сост.value=СОСТАВНОЙ_НЕТ;
  const взято=[];
  if(осн) ПОЛЯ_ОТ_ОСНОВНОГО.forEach(к=>{
    const поле=document.getElementById("rf_"+к); if(!поле) return;
    if(!поле.value && осн[к]){ поле.value=осн[к]; взято.push(к); }
  });
  if(осн) toast("Поверка взята у основного прибора"+
    (взято.length?(", оттуда же подставлено: "+взято.length+" поля (можно поправить)"):"")+
    " — "+(осн.наименование||""));
}
