// ── Форма 2 (разделы V–VIII паспорта): общая часть экрана и Word ──────
// Заказчик пересмотрел вид этих таблиц и попросил впрямую:
//  • текст двух последних столбцов — в ОДНОЙ ячейке, а ниже ячейка
//    делится на два столбца (в настоящем паспорте «Редакция № 6» над
//    обеими колонками стоит буквально одна и та же длинная фраза —
//    теперь она пишется один раз, как объединённая шапка);
//  • номер столбца — цифрой, в первый раз под подписью столбца на новой
//    строке (это и есть вторая строка шапки), дальше на каждой странице
//    столбцы подписываются только цифрой;
//  • тип прибора — на отдельной строке; отметка «И» — на своей строке,
//    остальное на следующей; изготовитель, зав. №, год выпуска и ввод в
//    эксплуатацию — каждый на своей строке;
//  • ширины столбцов подобраны так, чтобы самое длинное слово помещалось
//    целиком (минимумыКолонок/разложитьШирины — замер, а не на глаз).
const ЗАГ_ОБОРУД=["№","Наименование, тип","Назначение",
  "Изготовитель, зав. №, год выпуска, ввод в эксплуатацию",
  "Технические и метрологические характеристики","Владелец, основание владения",
  "№ документа о поверке, калибровке, аттестации. Дата и срок действия "+
  "документа или отметка о техническом состоянии"];
const СПАН_ОБОРУД=[1,1,1,1,1,1,2];
const НОМЕРА_ОБОРУД=["1","2","3","4","5","6","7","8"];
// Веса — куда отдавать остаток ширины сверх минимумов: там, где реально
// бывает длинный текст (характеристики, наименование, назначение), а не
// поровну. Номер и дата длинного текста не содержат вовсе.
const ВЕСА_ОБОРУД=[0,6,6,4,8,2,2,1];
// Однотипные неотъемлемые части ОДНОГО прибора печатаются в Форме 2
// одной позицией — так было в прежнем паспорте заказчика: заводские
// номера через запятую, после типа общее количество «(2 шт.)». Из двух
// написаний, что назвал заказчик («№ 7678, № 7679» и «№№ 7678, 7679»),
// взято второе — скажете, поменяю, это одна строка.
// Объединяются только карточки, у которых СОВПАДАЕТ ВСЁ печатаемое,
// кроме заводского номера: иначе разные данные (свои характеристики,
// своя дата ввода) молча пропали бы из документа. Сводятся только
// части (`основной_ид` заполнен) — самостоятельные приборы, даже
// одноимённые, остаются каждый своей строкой, как в настоящем паспорте.
function ключОбъединения(п){
  return ["наименование","тип","назначение","характеристики","владелец","изготовитель",
          "год_выпуска","дата_ввода","исправен","свидетельство","поверка_дата","поверка_до",
          "основной_ид"]
    .map(k=>String(п[k]==null?"":п[k]).trim()).join("\u0001");
}
function объединитьОднотипные(список){
  const из=[], индекс={};
  (список||[]).forEach(п=>{
    const зав=String(п.зав||"").trim();
    if(!п.основной_ид){ из.push(п); return; }
    const к=ключОбъединения(п), б=индекс[к];
    if(б){ б._кол++; if(зав) б._зав.push(зав); return; }
    const копия=Object.assign({},п,{_кол:1,_зав:зав?[зав]:[]});
    индекс[к]=копия; из.push(копия);
  });
  return из;
}
function заводскиеНомера(s){
  const ном=(s._зав&&s._зав.length)?s._зав:(String(s.зав||"").trim()?[String(s.зав).trim()]:[]);
  if(!ном.length) return "";
  return "зав. "+(ном.length>1?"\u2116\u2116 ":"\u2116 ")+ном.join(", ");
}
// Ячейки одной строки Формы 2. Массив внутри ячейки = отдельные строки
// текста (в Word — отдельные абзацы, на экране — отдельные <div>).
function ячейкиОборудования(s, i){
  const т=типографика;
  const родитель=s.основной_ид ? найтиПоИд(S,s.основной_ид) : null;
  const кол=+(s._кол||1), шт=кол>1?(" ("+кол+" шт.)"):"";
  return [
    [String(i+1)],
    [т((s.наименование||"")+(s.тип?"":шт)), s.тип?т(вКавычках(s.тип)+шт):"",
     родитель?т("часть: "+(родитель.наименование||"")):""],
    [т(s.назначение||"")],
    [т(s.изготовитель||""), т(заводскиеНомера(s)), т(String(s.год_выпуска||"")),
     s.дата_ввода?т("введён в эксплуатацию "+ru(s.дата_ввода)):""],
    [т(s.характеристики||"")],
    [т(s.владелец||"")],
    [s.исправен==="Исправен"?"«И»":"",
     т([s.свидетельство,s.поверка_дата?ru(s.поверка_дата):""].filter(Boolean).join(", "))],
    [s.поверка_до?ru(s.поверка_до):""]
  ].map(л=>{ const ф=л.map(x=>String(x==null?"":x).trim()).filter(Boolean);
             return ф.length?ф:["—"]; });
}

// Ширины колонок Формы 2 считаются ОДИН раз на весь паспорт — по всему
// оборудованию разделов V–VIII сразу, а не по каждой таблице метода
// отдельно: иначе соседние таблицы одного раздела разъехались бы по
// колонкам, хотя форма у них одна и та же.
function шириныОборудования(мера, мераЖ, отступ, всего){
  const данные=объединитьОднотипные(приборыВДокументы()).map((s,i)=>ячейкиОборудования(s,i));
  const мин=минимумыКолонок(ЗАГ_ОБОРУД,СПАН_ОБОРУД,данные,мера,мераЖ,отступ);
  const сум=мин.reduce((a,b)=>a+b,0);
  const в=всего||Math.max(900,сум);
  return {мин:мин, всего:в, ширины:разложитьШирины(мин,ВЕСА_ОБОРУД,в)};
}

