function вСрок(з){
  if(!з.выполнено) return null;
  const план=з.срок_первый||з.срок;
  return план ? (з.выполнено<=план) : null;
}
function просроченаЗадача(з){
  if(!живаяЗадача(з) || з.статус==="закрыта") return false;
  const сегодня=new Date().toISOString().slice(0,10);
  return !!з.срок && з.срок<сегодня && з.статус!=="выполнена";
}

