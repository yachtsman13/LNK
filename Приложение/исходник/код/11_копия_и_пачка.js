// ── Резервная копия ВСЕЙ базы в файл ──────────────────────
// Копия охватывает журнал и все три справочника: с тех пор как
// справочники стали редактируемыми, копия только журнала оставляла бы
// половину работы без страховки. Восстановление — именно замена
// (в этом смысл копии), поэтому спрашивает подтверждение.
// ── База: где живут данные и чем они застрахованы ─────────
// Данных «в файле рядом с программой» не бывает: страница, открытая с
// диска, писать в свою папку сама не может. Поэтому рабочая база лежит
// в памяти браузера, а настоящая страховка — копия в файл.
//
// Замерено в этом браузере: предел памяти ~5 МБ, сейчас занято 236 КБ на
// 315 записей вместе со справочниками (~766 символов на запись) — то есть
// запас примерно на 6500 записей. Далеко, но предел молчаливый: браузер
// не предупреждает, он просто отказывает в записи, и правка пропадает.
// Поэтому ниже и счётчик заполнения, и предупреждение заранее.
const ПРЕДЕЛ_ХРАНИЛИЩА = 5 * 1024 * 1024;   // символов, проверено замером
function объёмХранилища(){
  let занято=0, по={};
  try{
    for(let i=0;i<ХР.length;i++){
      const k=ХР.key(i), v=ХР.getItem(k)||"";
      if(k.indexOf("lnk_")!==0) continue;
      по[k]=k.length+v.length; занято+=k.length+v.length;
    }
  }catch(e){}
  // До первой правки память браузера пуста: данные ещё вшиты в файл
  // программы. Считать запас по нулю нельзя — получилась бы бессмыслица
  // вроде «хватит на 103 миллиона записей». Берём то, что реально ляжет
  // в память при первом же сохранении.
  let факт=0;
  try{ факт=(JSON.stringify(J)+JSON.stringify(O)+JSON.stringify(S)+
             JSON.stringify(P)+JSON.stringify(A)+JSON.stringify(ПОДР)+
             JSON.stringify(НД)+JSON.stringify(ПОМ)+JSON.stringify(ЗАД)).length; }catch(e){}
  const всего=Math.max(занято,факт);
  const наЗапись = liveJ().length ? всего/liveJ().length : 0;
  // IndexedDB: предел — квота браузера (navigator.storage.estimate).
  // Долю считаю сверху: знак строки — не больше 2 байт; на диске выходит
  // меньше (строки там сжимаются: 20 млн знаков заняли ~2 МБ, замерено).
  // Собственный замер браузера «сколько занято» не беру: он снимается при
  // запуске и отстаёт от записей, на свежей установке показывал 1 КБ.
  if(ХР.режим()==="idb"){
    const кв=ХР.квота();
    return { всего:всего, по:по, занято:занято, idb:true, квота:кв,
             доля: кв ? всего*2/кв : 0, местаНаЗаписей:null };
  }
  return { всего:всего, по:по, занято:занято,
           доля: всего/ПРЕДЕЛ_ХРАНИЛИЩА,
           местаНаЗаписей: наЗапись>1 ? Math.round((ПРЕДЕЛ_ХРАНИЛИЩА-всего)/наЗапись) : null };
}

// Папку для копий надо запомнить между запусками, а localStorage хранит
// только строки — «ручку» на папку в него не положить. Для этого есть
// IndexedDB, она в этом браузере из file:// работает (проверено).
const ФС_БД="lnk_fs", ФС_ХР="ручки";
function идб(){
  return new Promise((ок,нет)=>{
    let r; try{ r=indexedDB.open(ФС_БД,1); }catch(e){ return нет(e); }
    r.onupgradeneeded=()=>{ try{ r.result.createObjectStore(ФС_ХР); }catch(e){} };
    r.onsuccess=()=>ок(r.result); r.onerror=()=>нет(r.error);
  });
}
function идбЗапись(ключ,знач){
  return идб().then(db=>new Promise((ок,нет)=>{
    const t=db.transaction(ФС_ХР,"readwrite");
    t.objectStore(ФС_ХР).put(знач,ключ);
    t.oncomplete=()=>{db.close();ок(true);}; t.onerror=()=>{db.close();нет(t.error);};
  })).catch(()=>false);
}
function идбЧтение(ключ){
  return идб().then(db=>new Promise((ок)=>{
    const t=db.transaction(ФС_ХР,"readonly"), z=t.objectStore(ФС_ХР).get(ключ);
    z.onsuccess=()=>{db.close();ок(z.result||null);}; z.onerror=()=>{db.close();ок(null);};
  })).catch(()=>null);
}

