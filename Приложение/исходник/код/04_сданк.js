function срокЛаб(дата){
  const d=String(дата||"").trim(); if(!d) return ["", "не указана"];
  const дней=Math.round((new Date(d+"T00:00:00")-new Date())/86400000);
  if(дней<0)  return ["bad",  "просрочено " + ru(d)];
  if(дней<=30) return ["warn", "через " + дней + " дн."];
  return ["ok", "до " + ru(d)];
}
