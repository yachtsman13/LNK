async function входТест(){
  const люди=[{id:"1",фио:"Начальник",права:"Начальник"},{id:"2",фио:"Специалист",права:"Специалист"}];
  const c=контекст({P:люди,live:a=>a,входВкл:()=>false}); выполнить(c,"23в_вход.js");
  ок(await вызвать(c,"ошибкаПароля('короткий')"),"короткий пароль отклоняется");
  ок(await вызвать(c,"ошибкаПароля('аааааааааааа')"),"повтор одного знака отклоняется");
  ок(await вызвать(c,"ошибкаПароля('123456789012')"),"предсказуемый пароль отклоняется");
  ок(await вызвать(c,"ошибкаПароля('а'.repeat(129))"),"пароль длиннее 128 знаков отклоняется");
  ок(!await вызвать(c,"ошибкаПароля('длинная фраза из нескольких слов')"),"длинная парольная фраза разрешена");
  const соль="00112233445566778899aabbccddeeff";
  const старыйХеш=await вызвать(c,"хешПароля('старыйПароль',__args[0],100000)",соль);
  c.__args=[{id:"У:1",сп:"1",соль,хеш:старыйХеш}]; vm.runInContext("ПОЛЬЗ=[__args[0]]",c);
  ок(await вызвать(c,"парольВерен('1','старыйПароль')"),"старый PBKDF2-хеш со 100000 итераций остаётся действующим");
  ок(!await вызвать(c,"парольВерен('1','неверно')"),"неверный старый пароль не проходит");
  ок(await вызвать(c,"политикаПароляУстарела('1')"),"старая запись отмечается для смены пароля");
  await вызвать(c,"записатьПароль('1','новая длинная фраза',false)");
  ок(await вызвать(c,"парольВерен('1','новая длинная фраза')"),"новый пароль проверяется с сохранёнными итерациями");
  ок(await вызвать(c,"пользСп('1').итерации")===310000&&await вызвать(c,"пользСп('1').политика")===2,"новая запись хранит 310000 итераций и версию политики");

  for(let i=1;i<=4;i++){
    const р=await вызвать(c,"отметитьНеудачуВхода('2')");
    ок(!р.до,"до пятой ошибки блокировки нет: "+i);
  }
  const пятая=await вызвать(c,"отметитьНеудачуВхода('2')");
  ок(пятая.до>Date.now(),"пятая ошибка включает блокировку");
  ок(await вызвать(c,"блокировкаВхода('2')")>0,"блокировка читается из постоянного хранилища");
  await вызвать(c,"сброситьОграничениеВхода('2')");
  ок(await вызвать(c,"блокировкаВхода('2')")===0,"успешный вход может снять блокировку");

  // Восстановление: код показывается и подтверждается, затем заменяется.
  const коды=[]; let подтвердить=true;
  c.prompt=(текст,знач)=>{
    if(текст.includes("Скопируйте код")){ коды.push(знач); return знач; }
    if(текст.includes("сохранённый код ещё раз")) return подтвердить?коды[коды.length-1]:"неверно";
    if(текст.includes("Кому выдать")) return "1";
    return знач||"";
  };
  ок(await вызвать(c,"создатьКодВосстановления(false,true)"),"код восстановления создаётся с повторным вводом");
  ок(коды.length===1&&/^ЛНК-(?:[A-Z2-9]{5}-){3}[A-Z2-9]{5}$/.test(коды[0]),"код имеет заданный случайный формат");
  const перваяЗапись=await вызвать(c,"вход().восстановление");
  ок(!JSON.stringify(перваяЗапись).includes(коды[0]),"открытый код восстановления не сохраняется");
  ок(await вызвать(c,"хешКодаВосстановления(__args[0],__args[1])",коды[0],перваяЗапись)===перваяЗапись.хеш,"правильный код восстановления подтверждается хешем");
  c.окноПароля=async()=>({значения:[коды[0]]});
  c._окноВхода=null;
  await вызвать(c,"входАварийно()");
  ок(коды.length===2,"после восстановления выдан новый одноразовый код");
  const втораяЗапись=await вызвать(c,"вход().восстановление");
  ок(втораяЗапись.хеш!==перваяЗапись.хеш,"использованный код заменён");
  ок(await вызвать(c,"хешКодаВосстановления(__args[0],__args[1])",коды[0],втораяЗапись)!==втораяЗапись.хеш,"прежний код больше не действует");
  ок(await вызвать(c,"хешКодаВосстановления(__args[0],__args[1])",коды[1],втораяЗапись)===втораяЗапись.хеш,"новый код действует");
  ок(await вызвать(c,"пользСп('1').временный")===true,"руководителю выдан временный пароль");
  ок(await вызвать(c,"вход().восстановлено.сп")==="1","событие восстановления записано без отключения входа");
  ок(!код("23в_вход.js").includes('"ВЫКЛЮЧИТЬ"'),"старого аварийного отключения по слову ВЫКЛЮЧИТЬ нет");
}

function собранныйHTMLТест(){
  const файл=path.join(КОРЕНЬ,"Приложение","ЛНК.html");
  if(process.argv.indexOf("--html")<0) return;
  const html=fs.readFileSync(файл,"utf8");
  const скрипты=[...html.matchAll(/<script([^>]*)>([\s\S]*?)<\/script>/gi)]
    .filter(m=>!(/type\s*=\s*["']application\/json/i.test(m[1])||/\bsrc\s*=/i.test(m[1])));
  ок(скрипты.length>0,"в собранном HTML найден исполняемый скрипт");
  скрипты.forEach((m,i)=>{ new Function(m[2]); проверок++; });
  ок(true,"полный скрипт собранного HTML синтаксически корректен");
  ок(html.includes('content="4.01"'),"готовый HTML имеет версию 4.01");
  ок(html.includes("const ПОДПИСЬ_ФОРМАТ=3"),"подпись пакетов включена в готовый HTML");
  const хеш=require("crypto").createHash("sha256").update(fs.readFileSync(файл)).digest("hex");
  const эталон=fs.readFileSync(файл+".sha256","utf8").trim();
  ок(хеш===эталон,"SHA-256 готового HTML совпадает с сопроводительным файлом");
}

