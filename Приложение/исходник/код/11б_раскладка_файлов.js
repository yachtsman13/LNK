// ── Разбор имён ───────────────────────────────────────────────
// Свидетельство: «Поверка <наименование> <тип> зав. №<номер> до
// ДД.ММ.ГГГГ» (формат заказчика; наименование необязательно; с 3.97 слово
// «поверка» перед «до» необязательно — прежние имена «… поверка до …»
// тоже понимаются). Так же — «Калибровка … до …» для сертификата о калибровке.
const РЕ_ПОВЕРКА=/^(поверка|калибровка)\s+(.*?)\s*зав\.?\s*№+\s*(.+?)\s+(?:(?:поверка|калибровка|действительн\S*)\s+)?до\s+(\d{1,2})[.\-_](\d{1,2})[.\-_](\d{4})/i;
function датаИз(д,м,г){
  const dt=new Date(Date.UTC(г,м-1,д));
  if(dt.getUTCFullYear()!==г || dt.getUTCMonth()!==м-1 || dt.getUTCDate()!==д || г<1990) return "";
  return dt.toISOString().slice(0,10);
}
