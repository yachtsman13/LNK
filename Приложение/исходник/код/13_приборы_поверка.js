// Разбор списка: что будет добавлено, что пропущено и почему.
// Повтор в самом списке — заводится один раз; номер, который уже есть
// у части ЭТОГО прибора, — пропускается (вторая такая же карточка — дубль);
// номер, который есть у другой карточки картотеки, — НЕ пропускается,
// только называется: у заказчика заводской номер не уникален («№ 640»
// стоит у нескольких наборов).
function частиРазбор(){
  const номера=разобратьНомераЧастей((document.getElementById("чс_номера")||{}).value);
  const свои=new Set(частиПрибора(_частиОсн).map(ч=>нормЗав(ч.зав)).filter(Boolean));
  const виденные=new Set(), добавить=[], повтор=[], уже=[], уДругих=[];
  номера.forEach(н=>{
    const к=нормЗав(н);
    if(виденные.has(к)){ повтор.push(н); return; }
    виденные.add(к);
    if(свои.has(к)){ уже.push(н); return; }
    добавить.push(н);
    if(live(S).some(x=>нормЗав(x.зав)===к && !(x.основной_ид && тотЖеИд(x.основной_ид,_частиОсн)))) уДругих.push(н);
  });
  return {добавить, повтор, уже, уДругих};
}
