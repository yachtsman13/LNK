function сегодняМестн(){ const d=new Date(), дв=x=>(x<10?"0":"")+x; return d.getFullYear()+"-"+дв(d.getMonth()+1)+"-"+дв(d.getDate()); }
// Сравнение имён: без регистра, пробелов, знаков, кавычек; русские и
// латинские буквы одного начертания («С» и «C», «М» и «M») — одно и то же:
// в типах приборов они перемешаны, а на глаз неразличимы.
const ПОХОЖИЕ_БУКВЫ={"а":"a","в":"b","е":"e","ё":"e","к":"k","м":"m","н":"h","о":"o","р":"p","с":"c","т":"t","у":"y","х":"x"};
function нормИмени(s){
  return String(s==null?"":s).toLowerCase().replace(/[авеёкмнорстух]/g,ч=>ПОХОЖИЕ_БУКВЫ[ч]).replace(/[^0-9a-zа-я]/g,"");
}
// Обозначение документа: точки и дефисы значимы (ГОСТ 8.417-2002 и
// 8.417-2024 — разные документы), «/» в имени файла невозможен — пишут «-».
function нормОбозн(s){
  return String(s==null?"":s).toLowerCase().replace(/[авеёкмнорстух]/g,ч=>ПОХОЖИЕ_БУКВЫ[ч])
    .replace(/[\/\\_–—]/g,"-").replace(/№/g,"").replace(/[^0-9a-zа-я.\-]/g,"").replace(/-+/g,"-");
}
function безРасширения(имя){ return String(имя||"").replace(/\.[^.\/]{1,6}$/,""); }
function чистыйНомер(т){ return String(т||"").replace(/\s*\([^)]*\)\s*$/,"").replace(/^\s*№+\s*/,"").trim(); }
function нормЗавФ(x){
  const t=чистыйНомер(x);
  if(/^б\s*\/?\s*н\.?$/i.test(t)) return "бн";
  return нормИмени(t);
}
function номераЗав(текст){ return String(текст||"").split(/[,;]+/).map(нормЗавФ).filter(Boolean); }
// Тип прибора: поле «Тип», а если оно пусто — то, что в кавычках в
// наименовании (так заведены все 41 прибор из книги: «Твердомер
// портативный ультразвуковой «ТКМ-459С»», поле «Тип» пусто).
function типПрибораФ(п){
  const т=String(п&&п.тип||"").trim(); if(т) return т;
  const м=/[«"“]([^»"”]+)[»"”]/.exec(String(п&&п.наименование||""));
  return м?м[1].trim():"";
}
function наименованиеБезТипа(п){
  return String(п&&п.наименование||"").replace(/[«"“][^»"”]*[»"”]/g," ").replace(/\s+/g," ").trim();
}

// ── Разбор имён ───────────────────────────────────────────────
// Свидетельство: «Поверка <наименование> <тип> зав. №<номер> поверка до
// ДД.ММ.ГГГГ» (формат заказчика; наименование необязательно). Так же —
// «Калибровка … калибровка до …» для сертификата о калибровке.
const РЕ_ПОВЕРКА=/^(поверка|калибровка)\s+(.*?)\s*зав\.?\s*№+\s*(.+?)\s+(?:поверка|калибровка|действительн\S*)\s+до\s+(\d{1,2})[.\-_](\d{1,2})[.\-_](\d{4})/i;
function датаИз(д,м,г){
  const dt=new Date(Date.UTC(г,м-1,д));
  if(dt.getUTCFullYear()!==г || dt.getUTCMonth()!==м-1 || dt.getUTCDate()!==д || г<1990) return "";
  return dt.toISOString().slice(0,10);
}
function разобратьИмяПоверки(имя){
  const б=безРасширения(имя).replace(/\s+/g," ").trim();
  const м=РЕ_ПОВЕРКА.exec(б); if(!м) return null;
  const до=датаИз(+м[4],+м[5],+м[6]); if(!до) return null;
  return {калибровка:/^к/i.test(м[1]), текст:м[2].trim(), завТекст:чистыйНомер(м[3]), зав:номераЗав(м[3]), до};
}
// Документ прибора: «<вид> <наименование> <тип> [зав. №<номер>]». Без
// заводского номера — документ на тип (руководство на все приборы типа).
function разобратьИмяДокаСИ(имя){
  const б=безРасширения(имя).replace(/\s+/g," ").trim(), н=б.toLowerCase();
  let вид=null, длина=0;
  ВИДЫ_ДОК_СИ.forEach(v=>v.п.forEach(п=>{ if((н===п || н.startsWith(п+" ")) && п.length>длина){ вид=v.в; длина=п.length; } }));
  if(!вид) return null;
  const ост=б.slice(длина).trim();
  const м=/^(.*?)\s*зав\.?\s*№+\s*(.+)$/i.exec(ост);
  return м ? {вид, текст:м[1].trim(), завТекст:чистыйНомер(м[2]), зав:номераЗав(м[2])} : {вид, текст:ост, зав:null};
}
// Редакция документа СМ: «ред. 3», «редакция 3», «ред. № 3».
function редакцияИзИмени(имя){
  const м=/ред(?:акция|\.)?\s*№?\s*(\d+)/i.exec(безРасширения(имя));
  return м?+м[1]:null;
}

// ── Какой прибор назван в имени файла ─────────────────────────
// Заводской номер — главное: тип в имени файла может быть записан не
// так, как в карточке (просьба заказчика это допускать). Тип нужен, чтобы
// развести приборы с одним номером («№ 640» у семи разных наборов) и
// найти прибор, у которого заводской номер в карточке ещё не вписан.
function совпалТип(п, текстН){
  if(!текстН) return 0;
  const т=нормИмени(типПрибораФ(п)), н=нормИмени(наименованиеБезТипа(п)||п.наименование);
  if(т && т.length>=2 && (текстН.includes(т) || (текстН.length>=3 && т.includes(текстН)))) return 2;
  if(н && н.length>=4 && текстН.includes(н)) return 1;
  return 0;
}
// Строже — для документов «на тип» без номера: «ТКМ-459» не должен
// подхватить «ТКМ-459С». Перед типом допускается только наименование.
function типТочно(п, текстН){
  if(!текстН) return false;
  const т=нормИмени(типПрибораФ(п)), н=нормИмени(наименованиеБезТипа(п));
  if(т){
    if(текстН===т) return true;
    if(текстН.endsWith(т)){ const r=текстН.slice(0,-т.length); return !!н && (н.includes(r) || r.includes(н)); }
    return false;
  }
  return текстН===нормИмени(п.наименование);
}
// режим «поверка» — только самостоятельные приборы (свидетельство на
// комплект одно, у части оно от основного); «док» — любая карточка.
function найтиПриборыФайла(р, режим){
  const все=live(S), поId={}; все.forEach(x=>{ поId[String(x.id)]=x; });
  const пул=режим==="поверка"?все.filter(п=>!п.основной_ид):все;
  const текстН=нормИмени(р.текст);
  const итог=(приборы, доп)=>Object.assign({приборы}, доп||{});
  const номер=(р.зав||[]).filter(x=>x!=="бн");
  if(номер.length){
    const поЗав=сп=>сп.filter(п=>номераЗав(п.зав).some(x=>номер.indexOf(x)>=0));
    let к=поЗав(пул);
    if(!к.length && режим==="поверка"){
      const ч=поЗав(все.filter(п=>п.основной_ид)).map(x=>корневойПрибор(x,поId)).filter(x=>x && !x.основной_ид);
      к=[...new Set(ч)];
    }
    if(к.length>1){
      const пот=к.filter(п=>совпалТип(п,текстН)>0);
      if(пот.length) к=пот;
      if(к.length>1){ const жив=к.filter(п=>!списанПрибор(п)); if(жив.length) к=жив; }
      if(к.length>1) return итог([], {неодн:к});
    }
    if(к.length===1) return итог(к, {типНеСовпал:!!типПрибораФ(к[0]) && !!текстН && !совпалТип(к[0],текстН)});
    // У карточки заводской номер не вписан: ищем по типу среди карточек без номера.
    const без=пул.filter(п=>!номераЗав(п.зав).length && совпалТип(п,текстН)===2);
    if(без.length===1) return итог(без, {вписатьЗав:р.завТекст});
    if(без.length>1) return итог([], {неодн:без});
    return итог([]);
  }
  // Без номера (документ на тип) или «б/н».
  const к=пул.filter(п=>(р.зав?номераЗав(п.зав).every(x=>x==="бн"):true) && типТочно(п,текстН));
  if(режим==="поверка"){
    if(к.length===1) return итог(к);
    return к.length>1?итог([], {неодн:к}):итог([]);
  }
  return итог(к);
}
