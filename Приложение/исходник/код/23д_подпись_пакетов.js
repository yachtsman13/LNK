// ── Подпись пакетов обмена, копии и переезда (4.01) ─────────────
// У каждого рабочего места своя пара ECDSA P-256. Закрытый ключ остаётся
// только в хранилище браузера этого места и НЕ входит в обмен, копию или
// переезд. В пакет попадают открытый ключ, его отпечаток и подпись всего
// содержимого. Первый ключ места доверяет руководитель после сверки
// отпечатка; дальше подмена ключа требует отдельного явного решения.
//
// Это защита файла от изменения после выгрузки, а не шифрование и не
// защита от человека, который получил доступ к хранилищу браузера или к
// сеансу руководителя. Старые пакеты без подписи можно принять только
// после отдельного предупреждения — для перехода с версий до 4.01.
const ПОДПИСЬ_ФОРМАТ=3, ПОДПИСЬ_АЛГ="ECDSA_P256_SHA256";
const REG_КЛЮЧ_ПАКЕТОВ="lnk_package_key", REG_ДОВЕРИЕ_ПАКЕТОВ="lnk_package_trust";
let _ключПакетовОбещ=null, _свойОтпечатокПакета="";

function сортироватьДляПодписи(v){
  if(Array.isArray(v)) return v.map(сортироватьДляПодписи);
  if(v && typeof v==="object"){
    const о={}; Object.keys(v).sort().forEach(k=>{ о[k]=сортироватьДляПодписи(v[k]); }); return о;
  }
  return v;
}
// Подписывается канонический JSON: порядок полей и пробельное
// оформление файла при проверке значения не имеют.
function текстДляПодписи(d){
  const к=JSON.parse(JSON.stringify(d));
  if(к && typeof к==="object" && !Array.isArray(к)) delete к.подпись;
  return JSON.stringify(сортироватьДляПодписи(к));
}
function байтыВ64(б){
  const a=new Uint8Array(б), части=[];
  for(let i=0;i<a.length;i+=0x8000) части.push(String.fromCharCode.apply(null,a.subarray(i,i+0x8000)));
  return btoa(части.join(""));
}
function байтыИз64(с){
  const b=atob(String(с||"")), a=new Uint8Array(b.length);
  for(let i=0;i<b.length;i++) a[i]=b.charCodeAt(i);
  return a;
}
function hexБайтов(б){ return [...new Uint8Array(б)].map(x=>x.toString(16).padStart(2,"0")).join(""); }
function открытыйКлючДляОтпечатка(k){ return {crv:k.crv,kty:k.kty,x:k.x,y:k.y}; }
function одинаковыйОткрытыйКлюч(a,b){
  return !!a&&!!b&&a.kty===b.kty&&a.crv===b.crv&&a.x===b.x&&a.y===b.y;
}
async function отпечатокОткрытогоКлюча(k){
  const б=new TextEncoder().encode(JSON.stringify(открытыйКлючДляОтпечатка(k)));
  return hexБайтов(await crypto.subtle.digest("SHA-256",б));
}
function показОтпечатка(ид){
  const с=String(ид||"");
  return (с.match(/.{1,4}/g)||[с]).join(" ").toUpperCase();
}
function доверенныеКлючиПакетов(){
  try{ const v=JSON.parse(ХР.getItem(REG_ДОВЕРИЕ_ПАКЕТОВ)||"{}"); return v&&typeof v==="object"?v:{}; }
  catch(e){ return {}; }
}
function сохранитьДоверенныеКлючи(в){ ХР.setItem(REG_ДОВЕРИЕ_ПАКЕТОВ,JSON.stringify(в)); }
function запомнитьДоверенныйКлюч(ид,ключ,место){
  const в=доверенныеКлючиПакетов();
  // У места один действующий ключ. Прежняя запись при подтверждённой
  // смене больше не нужна; сам закрытый ключ сюда никогда не пишется.
  Object.keys(в).forEach(k=>{ if(k!==ид && в[k]&&в[k].место===место) delete в[k]; });
  в[ид]={ключ:открытыйКлючДляОтпечатка(ключ),место:место||"",когда:new Date().toISOString()};
  сохранитьДоверенныеКлючи(в);
}
async function ключПакетов(){
  if(_ключПакетовОбещ) return _ключПакетовОбещ;
  _ключПакетовОбещ=(async()=>{
    if(!(window.crypto&&crypto.subtle)) throw new Error("Web Crypto API недоступен");
    let сох=null;
    try{ сох=JSON.parse(ХР.getItem(REG_КЛЮЧ_ПАКЕТОВ)||"null"); }catch(e){}
    let закрытый, открытый, jwk, ид;
    if(сох&&сох.закрытый&&сох.открытый){
      try{
        закрытый=await crypto.subtle.importKey("jwk",сох.закрытый,{name:"ECDSA",namedCurve:"P-256"},false,["sign"]);
        открытый=await crypto.subtle.importKey("jwk",сох.открытый,{name:"ECDSA",namedCurve:"P-256"},true,["verify"]);
        jwk=открытыйКлючДляОтпечатка(сох.открытый); ид=await отпечатокОткрытогоКлюча(jwk);
        if(сох.ид&&сох.ид!==ид) throw new Error("отпечаток ключа не совпал");
      }catch(e){ закрытый=null; }
    }
    if(!закрытый){
      const пара=await crypto.subtle.generateKey({name:"ECDSA",namedCurve:"P-256"},true,["sign","verify"]);
      закрытый=пара.privateKey; открытый=пара.publicKey;
      jwk=await crypto.subtle.exportKey("jwk",открытый); jwk=открытыйКлючДляОтпечатка(jwk);
      ид=await отпечатокОткрытогоКлюча(jwk);
      const закрытыйJwk=await crypto.subtle.exportKey("jwk",закрытый);
      ХР.setItem(REG_КЛЮЧ_ПАКЕТОВ,JSON.stringify({версия:1,ид,открытый:jwk,закрытый:закрытыйJwk}));
    }
    _свойОтпечатокПакета=ид;
    запомнитьДоверенныйКлюч(ид,jwk,getWS().код);
    return {закрытый,открытый,jwk,ид};
  })();
  try{ return await _ключПакетовОбещ; }
  catch(e){ _ключПакетовОбещ=null; throw e; }
}
async function подписатьПакет(исход){
  const d=JSON.parse(JSON.stringify(исход));
  delete d.подпись; d.формат=ПОДПИСЬ_ФОРМАТ;
  const к=await ключПакетов();
  const подпись=await crypto.subtle.sign({name:"ECDSA",hash:"SHA-256"},к.закрытый,
    new TextEncoder().encode(текстДляПодписи(d)));
  d.подпись={алгоритм:ПОДПИСЬ_АЛГ,ключ:к.jwk,ид:к.ид,значение:байтыВ64(подпись)};
  return d;
}
async function проверитьПодписьПакета(d){
  if(!d||typeof d!=="object"||Array.isArray(d)) return {ок:true,старый:true};
  if(!d.подпись){
    if(+(d.формат||0)>=ПОДПИСЬ_ФОРМАТ) return {ок:false,ошибка:"пакет нового формата без подписи"};
    return {ок:true,старый:true};
  }
  const п=d.подпись;
  if(п.алгоритм!==ПОДПИСЬ_АЛГ||!п.ключ||!п.ид||!п.значение)
    return {ок:false,ошибка:"неполная или неизвестная подпись"};
  try{
    const открытыйJwk=открытыйКлючДляОтпечатка(п.ключ);
    if(await отпечатокОткрытогоКлюча(открытыйJwk)!==п.ид)
      return {ок:false,ошибка:"отпечаток открытого ключа не совпал"};
    const доверенные=доверенныеКлючиПакетов(), доверенный=доверенные[п.ид];
    if(доверенный&&!одинаковыйОткрытыйКлюч(доверенный.ключ,открытыйJwk))
      return {ок:false,ошибка:"открытый ключ не совпал с доверенным"};
    const ключ=await crypto.subtle.importKey("jwk",открытыйJwk,{name:"ECDSA",namedCurve:"P-256"},false,["verify"]);
    const верно=await crypto.subtle.verify({name:"ECDSA",hash:"SHA-256"},ключ,байтыИз64(п.значение),
      new TextEncoder().encode(текстДляПодписи(d)));
    if(!верно) return {ок:false,ошибка:"подпись не совпала: содержимое изменено после выгрузки"};
    if(доверенный) return {ок:true,доверенный:true,ид:п.ид};
    // Свой ключ местом не считается: до выбора кода места он пишется с
    // кодом по умолчанию («М1»), иначе первый пакет настоящего «М1»
    // выглядел бы подменой ключа и требовал «СМЕНИТЬ».
    const прежний=Object.keys(доверенные).find(k=>k!==_свойОтпечатокПакета&&доверенные[k]&&доверенные[k].место===d.место);
    return {ок:true,новый:!прежний,смена:!!прежний,ид:п.ид,прежний};
  }catch(e){ return {ок:false,ошибка:"не удалось проверить подпись: "+(e.message||e.name||e)}; }
}
