      let d; try{ d=JSON.parse(await (await х.getFile()).text()); }
      catch(e){ плохие.push({f:{name:имя},ошибка:"не читается"}); continue; }
      if(d&&(d.тип==="резервная копия ЛНК"||d.тип===ТИП_ПЕРЕЕЗДА)){ копий++; continue; }
