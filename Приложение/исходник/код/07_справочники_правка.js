// Выбор «ближайшей» записи из списка (аттестации по методам, классность):
// сначала среди ещё действующих ищем минимальный срок, если таких нет —
// самую недавно истёкшую, чтобы запись не потерялась молча. Общая для
// ближайшаяАттестация и ближайшаяКлассность (см. ниже) — не плодил копию.
function ближайшаяЗапись(список, поле){
  const из=(список||[]).filter(x=>x[поле]);
  if(!из.length) return null;
  const сегодня=new Date().toISOString().slice(0,10);
  const будущие=из.filter(x=>x[поле]>=сегодня).sort((a,b)=>a[поле]<b[поле]?-1:1);
  return будущие.length ? будущие[0] : из.slice().sort((a,b)=>a[поле]<b[поле]?-1:1).pop();
}
