// подхватить «ТКМ-459С». Перед типом допускается только наименование.
function типТочно(п, текстН){
  if(!текстН) return false;
  const т=нормИмени(типПрибораФ(п)), н=нормИмени(наименованиеБезТипа(п));
  if(т){
    if(текстН===т) return true;
    if(текстН.endsWith(т)){ const r=текстН.slice(0,-т.length); return !!н && (н.includes(r) || r.includes(н)); }
    return false;
  }
  return текстН===нормИмени(п.наименование);
}
// режим «поверка» — только самостоятельные приборы (свидетельство на
// комплект одно, у части оно от основного); «док» — любая карточка.
function найтиПриборыФайла(р, режим){
  const все=live(S), поId={}; все.forEach(x=>{ поId[String(x.id)]=x; });
  const пул=режим==="поверка"?все.filter(п=>!п.основной_ид):все;
  const текстН=нормИмени(р.текст);
  const итог=(приборы, доп)=>Object.assign({приборы}, доп||{});
  const номер=(р.зав||[]).filter(x=>x!=="бн");
  if(номер.length){
    const поЗав=сп=>сп.filter(п=>номераЗав(п.зав).some(x=>номер.indexOf(x)>=0));
    let к=поЗав(пул);
    if(!к.length && режим==="поверка"){
      const ч=поЗав(все.filter(п=>п.основной_ид)).map(x=>корневойПрибор(x,поId)).filter(x=>x && !x.основной_ид);
      к=[...new Set(ч)];
    }
    if(к.length>1){
      const пот=к.filter(п=>совпалТип(п,текстН)>0);
      if(пот.length) к=пот;
      if(к.length>1){ const жив=к.filter(п=>!списанПрибор(п)); if(жив.length) к=жив; }
      if(к.length>1) return итог([], {неодн:к});
    }
    if(к.length===1) return итог(к, {типНеСовпал:!!типПрибораФ(к[0]) && !!текстН && !совпалТип(к[0],текстН)});
    // У карточки заводской номер не вписан: ищем по типу среди карточек без номера.
    const без=пул.filter(п=>!номераЗав(п.зав).length && совпалТип(п,текстН)===2);
    if(без.length===1) return итог(без, {вписатьЗав:р.завТекст});
    if(без.length>1) return итог([], {неодн:без});
    return итог([]);
  }
  // Без номера (документ на тип) или «б/н».
  const к=пул.filter(п=>(р.зав?номераЗав(п.зав).every(x=>x==="бн"):true) && типТочно(п,текстН));
  if(режим==="поверка"){
    if(к.length===1) return итог(к);
    return к.length>1?итог([], {неодн:к}):итог([]);
  }
  return итог(к);
}
