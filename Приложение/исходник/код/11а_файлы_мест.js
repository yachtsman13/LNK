// Взять с флешки файлы, которых на этом месте нет или которые не те.
// Берётся только версия, совпадающая с верной (реестр); своя прежняя
// уходит в «Заменённые/<дата время>/<путь>», не удаляется.
async function взятьФайлы(h, ист){
  const р={взято:[], заменено:[], нетНаФлешке:[], неТаНаФлешке:[], сбой:[]};
  let пф=null;
  try{ пф=await ист.getDirectoryHandle(ПАПКА_ФАЙЛОВ_ОБМЕНА); }catch(e){ р.нетПапки=true; }
  const пути=путиСсылок(), м=файлыМеста();
  const нужны=Object.keys(пути).filter(id=>{ const ст=состояниеФайла(пути[id]); return ст==="нет"||ст==="не тот"; });
  if(!пф){ нужны.forEach(id=>р.нетНаФлешке.push(пути[id])); return р; }
  const метка=отметкаВремениПапки();
  for(const id of нужны){
    const путь=пути[id], з=ФАЙЛЫ.find(x=>x.id===id && !x.удалено);
    let ф;
    try{ ф=await (await файлИзПапкиДок(пф, путь)).getFile(); }catch(e){ р.нетНаФлешке.push(путь); continue; }
    const данные=await ф.arrayBuffer(), отп=await отпечатокДанных(данные);
    if(з && ((з.отп && отп && з.отп!==отп) || (!(з.отп&&отп) && з.размер!=null && з.размер!==данные.byteLength))){
      р.неТаНаФлешке.push(путь); continue; }
    try{
      const л=м.ф[id];
      if(л && л.есть){
        const старое=await (await (await файлИзПапкиДок(h, путь)).getFile()).arrayBuffer();
        await записатьФайлПоПути(h, ПАПКА_ЗАМЕНЁННЫХ+"/"+метка+"/"+путь, старое);
        р.заменено.push(путь);
      }
      await записатьФайлПоПути(h, путь, данные);
      const с={есть:true, размер:данные.byteLength, мод:0, отп};
      try{ const нов=await (await файлИзПапкиДок(h, путь)).getFile(); с.мод=нов.lastModified||0; }catch(e){}
      м.ф[id]=с;
      if(!з) записатьВерсиюФайла(путь, с);
      р.взято.push(путь);
    }catch(e){ р.сбой.push(путь+": "+e.name); }
  }
  if(!м.проверено) м.проверено=new Date().toISOString();
  сохранитьФайлыМеста(м);
  return р;
}
