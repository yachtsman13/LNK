// Границы периода. Квартал и полугодие считаются от календарного года,
// неделя — с понедельника: так их и понимают в отчётности.
function границыПериода(вид, база){
  const d=база?new Date(база+"T00:00:00"):new Date();
  const г=d.getFullYear(), м=d.getMonth();
  const дата=(y,mo,day)=>new Date(Date.UTC(y,mo,day)).toISOString().slice(0,10);
  if(вид==="день")     return [дата(г,м,d.getDate()), дата(г,м,d.getDate())];
  if(вид==="неделя"){
    const дн=(d.getDay()+6)%7;                       // понедельник = 0
    const пн=new Date(d); пн.setDate(d.getDate()-дн);
    const вс=new Date(пн); вс.setDate(пн.getDate()+6);
    return [дата(пн.getFullYear(),пн.getMonth(),пн.getDate()),
            дата(вс.getFullYear(),вс.getMonth(),вс.getDate())];
  }
  if(вид==="месяц")    return [дата(г,м,1), дата(г,м+1,0)];
  if(вид==="квартал"){ const к=Math.floor(м/3); return [дата(г,к*3,1), дата(г,к*3+3,0)]; }
  if(вид==="полугодие"){ const п=м<6?0:6; return [дата(г,п,1), дата(г,п+6,0)]; }
  return [дата(г,0,1), дата(г,11,31)];               // год
}
function имяПериода(вид, база){
  const [с,по]=границыПериода(вид,база);
  const d=new Date(с+"T00:00:00"), г=d.getFullYear(), м=d.getMonth();
  if(вид==="день")      return ru(с);
  if(вид==="неделя")    return "неделя "+ru(с)+" — "+ru(по);
  if(вид==="месяц")     return МЕСЯЦЫ[м]+" "+г;
  if(вид==="квартал")   return (Math.floor(м/3)+1)+"-й квартал "+г;
  if(вид==="полугодие") return (м<6?"1":"2")+"-е полугодие "+г;
  return г+" год";
}
function вПериоде(дата, вид, база){
  const [с,по]=границыПериода(вид,база);
  const d=String(дата||""); return !!d && d>=с && d<=по;
}

// Перенос срока сохраняет первоначальную дату: без этого отчёт всегда
// показывал бы сто процентов выполнения в срок.
function перенести(id, новыйСрок, причина){
  const з=ЗАД.find(x=>x.id===id); if(!з) return;
  if(!з.срок_первый) з.срок_первый=з.срок;
  з.переносы=(з.переносы||[]).concat([{было:з.срок, стало:новыйСрок,
    причина:причина||"", когда:new Date().toISOString().slice(0,10)}]);
  з.срок=новыйСрок;
  отметитьЗадачу(з);
}
