// Отчёт за период. Форма отчёта заказчиком ещё не прислана, поэтому здесь
// внутренний вид: числа, разбивка и список невыполненного. Как пришлют
// образец — сделаю по нему, как акт.
// Дней просрочки — общая мерка и для своих задач, и для производных
// (у тех вместо статуса — просто «сделано»/срок).
function днейПросрочки(срок, сделано){
  const сегодня=new Date().toISOString().slice(0,10);
  if(сделано || !срок || срок>=сегодня) return 0;
  return Math.round((new Date(сегодня)-new Date(срок))/86400000);
}
