// Этап 2 проработки (ТЗ/Проработка_календарь_задачи.md, п. 4). Бланка
// заявки нет (ответ заказчика): работа приходит сопроводительным письмом,
// по звонку или по команде руководства. Поэтому заявка в программе — не
// форма документа, а учётная запись о поступившей работе.
//
// Номер — свой порядковый в году «З-12-2026», выдаётся сам: у звонка и
// команды своего номера нет, а ссылаться на работу как-то надо; номер
// письма хранится отдельно. Два места могут между обменами выдать один и
// тот же номер — это видно в «Проверке данных» («ошибка»), номер в заявке
// правится руками. Право выдачи (как у протоколов) сюда не заводил:
// заявок немного, а эстафета прав для них была бы тяжелее самой беды.
//
// Ход: зарегистрирована → утверждена (начальник или заместитель:
// исполнитель и срок) → в работе (записи заведены в журнал) → выполнена;
// или отклонена с причиной. Регистрирует любой.
const REG_ЗАЯВ="lnk_requests";
let ЗАЯВ=[];
const ЗАЯВ_СПОСОБЫ=[["письмо","Сопроводительное письмо"],["звонок","Звонок"],["команда","Команда руководства"]];
const ЗАЯВ_СОСТ={
  зарегистрирована:{т:"Зарегистрирована", к:"new"},
  утверждена:{т:"Утверждена", к:"work"},
  в_работе:{т:"В работе", к:"work"},
  выполнена:{т:"Выполнена", к:"ok"},
  отклонена:{т:"Отклонена", к:""}
};
function состЗаявки(з){ return (ЗАЯВ_СОСТ[з.статус]||ЗАЯВ_СОСТ.зарегистрирована); }
function заявкаОткрыта(з){ return !з.удалено && з.статус!=="выполнена" && з.статус!=="отклонена"; }
// Срок работы: назначенный при утверждении, иначе требуемый подразделением.
function срокЗаявки(з){ return з.срок_утв||з.срок||""; }
function исполнительЗаявки(з){ return String(з.исполнитель||з.исп_предложен||"").trim(); }
function подрЗаявки(з){ const п=з.подр?найтиПоИд(live(ПОДР),з.подр):null; return п?String(п.наименование||"").trim():""; }
// Объект заявки: ссылка на карточку (ид) или текст, если карточки ещё нет.
function объектЗаявкиТекст(о){
  const к=о&&о.ид!=null&&о.ид!==""?найтиПоИд(live(O),о.ид):null;
  return к?строкаОбъектаСпр(к):String((о&&о.текст)||"").trim();
}
function объектыЗаявкиТекст(з){ return (з.объекты||[]).map(объектЗаявкиТекст).filter(Boolean); }
function заявкаКратко(з){
  const о=объектыЗаявкиТекст(з);
  return (о.length?о[0]+(о.length>1?" и ещё "+(о.length-1):""):"объекты не указаны");
}
function номерЗаявки(год){
  const г=String(год||new Date().getFullYear());
  let макс=0;
  (ЗАЯВ||[]).forEach(з=>{ const m=/^З-(\d+)-(\d{4})$/.exec(String(з.номер||"").trim()); if(m && m[2]===г) макс=Math.max(макс,+m[1]); });
  return "З-"+(макс+1)+"-"+г;
}
