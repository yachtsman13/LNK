function рядыЗаявок(){
  const q=(query||"").toLowerCase();
  return live(ЗАЯВ).filter(з=>заявОтбор==="все" || заявкаОткрыта(з))
    .filter(з=>!q || [з.номер, з.письмо_номер, подрЗаявки(з), объектыЗаявкиТекст(з).join(" "), з.примечание, исполнительЗаявки(з)].join(" ").toLowerCase().includes(q))
    .sort((a,b)=>String(b.дата||"").localeCompare(String(a.дата||"")) || String(b.номер||"").localeCompare(String(a.номер||""),"ru",{numeric:true}));
}
function заявокНаУтверждение(){ return яНачальник()?live(ЗАЯВ).filter(з=>з.статус==="зарегистрирована"||!з.статус).length:0; }
function заявокПросрочено(){ const с=сегодняМестн(); return live(ЗАЯВ).filter(з=>заявкаОткрыта(з) && срокЗаявки(з) && срокЗаявки(з)<с).length; }
function способТекст(з){
  if(з.способ==="письмо") return "письмо"+(з.письмо_номер?" № "+з.письмо_номер:"")+(з.письмо_дата?" от "+ru(з.письмо_дата):"");
  if(з.способ==="звонок") return "звонок"+(з.звонил?": "+з.звонил:"")+(з.телефон?", "+з.телефон:"");
  if(з.способ==="команда") return "команда руководства"+(з.от_кого?": "+з.от_кого:"");
  return "";
}
