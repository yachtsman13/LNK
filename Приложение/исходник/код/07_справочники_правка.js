function ближайшийРабочийНазад(iso){
  let d=new Date(iso+"T00:00:00"), шагов=0;
  while(шагов<15){
    const текущий=d.toISOString().slice(0,10);
    if(!нерабочийДень(текущий)) return текущий;
    d.setDate(d.getDate()-1); шагов++;
  }
  return iso; // не нашли за две недели назад — возвращаем как есть, не зацикливаемся
}

