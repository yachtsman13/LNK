function exportЗадачиXlsx(){
  const список=(зф.источник==="система")?[]:задачиПериода();
  const произв=(зф.источник==="свои")?[]:производныеЗадачи(зф.период, зф.база);
  const листы=[{имя:"Задачи",
    строки:список.map((з,i)=>[i+1, з.срок, з.что, з.подробно, з.объект, з.исполнитель,
      (ГОРИЗОНТЫ.find(x=>x[0]===з.горизонт)||["",""])[1], состТекст(з), просроченаЗадача(з)?"да":"нет"]),
    колонки:[{з:"№",ш:6,тип:"число"},{з:"Срок",ш:13,тип:"дата"},{з:"Задача",ш:40},{з:"Подробно",ш:34},
      {з:"Объект",ш:26},{з:"Исполнитель",ш:20},{з:"Горизонт",ш:12},{з:"Состояние",ш:16},
      {з:"Просрочена",ш:11}]}];
  if(произв.length) листы.push({имя:"Из плана и сроков",
    строки:произв.map((x,i)=>[i+1, x.срок, x.что, x.источник,
      x.сделано?"выполнено":(x.срок<сегодня()?"просрочено":"по плану")]),
    колонки:[{з:"№",ш:6,тип:"число"},{з:"Срок",ш:13,тип:"дата"},{з:"Задача",ш:46},
      {з:"Источник",ш:16},{з:"Состояние",ш:16}]});
  xlsxФайл("Задачи ЛНК "+имяПериода(зф.период,зф.база)+" "+сегодня()+".xlsx", листы);
  toast("Выгружено: "+список.length+" задач"+(произв.length?(", "+произв.length+" из плана"):""));
}

// ── Круговая правка ЗАДАЧ ─────────────────────────────────
// Правила те же, что у справочников и журнала: код записи в первой
// колонке, строка с кодом ложится в СВОЮ задачу, без кода — новая,
// пустая ячейка СТИРАЕТ значение (см. стёртоТекст), чужой код пропускается и
// называется. Плюс два правила самих задач, которые файл не должен
// обходить:
//  1) ставит и правит задачи место начальника (в форме у остальных мест
//     поля заблокированы) — поэтому и выгрузка для правки, и импорт
//     доступны только ему;
//  2) новый срок — это ПЕРЕНОС: первоначальный срок сохраняется, в
//     историю переносов пишется запись, как при правке в форме. Без этого
//     отчёт засчитывал бы задачу «в срок» по перенесённой дате.
// Состояние (назначена → принята → выполнена → закрыта) из файла не
// меняется: переходы делают разные места со своими правами, а колонка
// «Состояние» идёт в файл только для справки. Заметки и история переносов
// — списки внутри задачи, в файл не идут и импортом не трогаются.
// Отметка правки у задачи — место_правки, а НЕ место: «место» у задачи —
// поле «Рабочее место исполнителя» (та же ловушка, что была у объектов).
const ЗАДАЧИ_ПОЛЯ=[
  {k:"что",l:"Что сделать",ш:44},
  {k:"подробно",l:"Подробно",ш:40},
  {k:"объект",l:"Объект",ш:30},
  {k:"срок",l:"Срок",тип:"дата",ш:13},
  {k:"приоритет",l:"Приоритет",ш:12,список:ПРИОРИТЕТЫ},
  {k:"горизонт",l:"Горизонт планирования",ш:16,список:ГОРИЗОНТЫ},
  {k:"исполнитель",l:"Исполнитель",ш:20},
  {k:"место",l:"Рабочее место исполнителя",ш:14},
  {k:"повтор",l:"Повторять",ш:18,список:ПОВТОРЫ},
  {k:"повтор_до",l:"Повторять до",тип:"дата",ш:13}
];
const ЗАДАЧИ_НЕ_СТИРАТЬ=["что","срок","горизонт"];
const ЗАДАЧИ_НЕ_В_ФАЙЛЕ="состояние задачи (меняется кнопками в задаче), заметки и история переносов";
function выгрузкаЗадачДляПравки(){
  if(!яНачальник()){ alert("Задачи ставит и правит место начальника — здесь правка задач недоступна."); return; }
  const строки=задачиПериода();   // ровно то, что видно на экране
  const колонки=[{з:КОЛ_КОД,ш:22}].concat(ЗАДАЧИ_ПОЛЯ.map(f=>({з:f.l,ш:f.ш,тип:f.тип==="дата"?"дата":undefined})))
    .concat([{з:"Состояние (из файла не меняется)",ш:22},
             {з:"Первоначальный срок (из файла не меняется)",ш:18,тип:"дата"}]);
  xlsxФайл("Правка — Задачи "+сегодня()+".xlsx",[{имя:"Задачи", колонки:колонки,
    строки:строки.map(з=>[String(з.id)].concat(ЗАДАЧИ_ПОЛЯ.map(f=>{
        const v=з[f.k];
        if(f.список) return (f.список.find(x=>x[0]===(v||""))||["",v||""])[1];
        return v==null?"":v;
      })).concat([состТекст(з), з.срок_первый||з.срок||""]))}]);
  toast(строки.length
    ? ("Выгружено для правки: "+строки.length+" (задачи текущего периода) — правьте и загружайте «Импортом из Excel»")
    : "В этом периоде задач нет — выгружена пустая форма: новые задачи можно вписать строками");
}
async function импортЗадачВыбран(input){
  const file=input.files && input.files[0];
  input.value="";
  if(!file) return;
  if(!яНачальник()){ alert("Задачи ставит и правит место начальника — здесь импорт задач недоступен."); return; }
  if(typeof DecompressionStream==="undefined"){
    alert("Браузер не умеет распаковывать .xlsx (нет DecompressionStream) — обновите браузер "+
      "(нужен современный Chrome или Edge).");
    return;
  }
  let строки;
  try{ строки=await xlsxРазобрать(file); }
  catch(e){ alert("Не удалось прочитать файл: "+e.message); return; }
  if(строки.length<2){ alert("В файле нет данных — только шапка или файл пуст."); return; }
  импортЗадачПрименить(строки);
}
function импортЗадачПрименить(строки){
  if(!яНачальник()){ alert("Задачи ставит и правит место начальника — здесь импорт задач недоступен."); return; }
  const шапка=строки[0], сопост={}; let колКода="";
  Object.keys(шапка).forEach(буква=>{
    const текст=String(шапка[буква]||"").trim().toLowerCase();
    if(текст===КОЛ_КОД.toLowerCase()){ колКода=буква; return; }
    const f=ЗАДАЧИ_ПОЛЯ.find(x=>x.l.toLowerCase()===текст);
    if(f) сопост[буква]=f;
  });
  if(!Object.values(сопост).some(f=>f.k==="что")){
    alert("Не нашёл колонку «Что сделать» — сверьте шапку файла с выгрузкой «Выгрузить для правки».");
    return;
  }
  const спецы=live(P).map(p=>p.вдок||p.фио).filter(Boolean);
  const живые=ЗАДАЧИ_живые();
  const правки=[], новые=[];
  const кодыНеНашлись=new Set(), непонятно=new Set(), чужиеИсп=new Set();
  const обязательные=new Set(), стёрто=new Map();
  let переносов=0;
  const пусто=v=>String(v==null?"":v).trim()==="";
  const такоеЖе=(a,b)=>String(a==null?"":a).trim()===String(b==null?"":b).trim();
  for(let i=1;i<строки.length;i++){
    const ряд=строки[i], знач={}, пустые=new Set();
    Object.keys(сопост).forEach(буква=>{
      const f=сопост[буква];
      let v=String(ряд[буква]||"").trim();
      if(!v){ пустые.add(f.k); return; }
      if(f.тип==="дата"){ v=значениеДаты(v); if(!v){ непонятно.add(f.l+": «"+String(ряд[буква]).trim()+"»"); return; } }
      if(f.список){
        // Список пишется словами («Неделя», «каждый месяц»); принимаю и
        // слова, и внутренние ключи. Непонятное значение не подставляю —
        // по горизонту задача отбирается в периоды, мусорное значение
        // спрятало бы её из списка.
        const н=f.список.find(x=>x[1].toLowerCase()===v.toLowerCase()||x[0]===v.toLowerCase());
        if(!н){ непонятно.add(f.l+": «"+v+"»"); return; }
        v=н[0];
      }
      if(f.k==="исполнитель" && !спецы.includes(v)){
        // В форме исполнитель выбирается из списка специалистов; опечатка
        // завела бы в отчёте «по исполнителям» несуществующего человека.
        чужиеИсп.add(v); return;
      }
      знач[f.k]=v;
    });
    const код=колКода?String(ряд[колКода]||"").trim():"";
    if(код){
      const был=живые.find(x=>String(x.id)===код);
      if(!был){ кодыНеНашлись.add(код); continue; }
      const поля=[];
      ЗАДАЧИ_ПОЛЯ.forEach(f=>{
        // Пустая ячейка стирает значение (см. стёртоТекст), кроме того,
        // без чего задачи нет: что сделать, срок, горизонт.
        if(пустые.has(f.k)){
          if(пусто(был[f.k])) return;
          if(ЗАДАЧИ_НЕ_СТИРАТЬ.includes(f.k)){ обязательные.add(f.l); return; }
          знач[f.k]=""; стёртоДоб(стёрто,f.l); поля.push(f.k); return;
        }
        if(!(f.k in знач)) return;
        if(такоеЖе(был[f.k],знач[f.k])) return;
        поля.push(f.k);
      });
      if(поля.length){ правки.push({rec:был, знач:знач, поля:поля}); if(поля.includes("срок")&&был.срок) переносов++; }
      continue;
    }
    if(пусто(знач.что)) continue;    // пустая строка — не ошибка
    новые.push(знач);
  }
  if(!новые.length && !правки.length){
    alert("Менять нечего: заполненных строк не нашлось или все значения совпадают с тем, что уже в задачах."+
      (кодыНеНашлись.size?("\n\nКоды задач, которых нет (строки пропущены): "+[...кодыНеНашлись].slice(0,10).join(", ")):"")+
      (непонятно.size?("\n\nНе разобрано: "+[...непонятно].slice(0,10).join(" | ")):"")+
      (чужиеИсп.size?("\n\nНет среди специалистов: "+[...чужиеИсп].slice(0,10).join(", ")):""));
    return;
  }
  const частей=правки.reduce((n,п)=>n+п.поля.length,0);
  const что=[
    правки.length?("обновить "+правки.length+" "+числослово(правки.length,["задачу","задачи","задач"])+
      " ("+частей+" "+числослово(частей,["поле","поля","полей"])+")"):"",
    новые.length?("поставить "+новые.length+" "+числослово(новые.length,["новую задачу","новые задачи","новых задач"])):""
  ].filter(Boolean).join(" и ");
  if(!confirm("Задачи: "+что+"?\n\n"+
    (правки.length?"Правка идёт по колонке «"+КОЛ_КОД+"»: строка ложится в свою задачу. Пустая ячейка "+
      "очищает поле; столбец, которого в файле нет, не трогается.\n":"")+
    (переносов?("\nСрок меняется у "+переносов+" — это ПЕРЕНОС: первоначальный срок сохранится, в историю "+
      "переносов ляжет запись «правка из Excel», отчёт по-прежнему считает выполнение по первому сроку.\n"):"")+
    "\nВ файле нет и потому не тронутся: "+ЗАДАЧИ_НЕ_В_ФАЙЛЕ+".\n"+
    (обязательные.size?("\nБез этого задачи нет — пустую ячейку не стираю: "+[...обязательные].join(", ")):"")+
    (кодыНеНашлись.size?("\nКодов, которых нет среди задач (строки пропущу): "+
      [...кодыНеНашлись].slice(0,10).join(", ")):"")+
    (непонятно.size?("\n\nНе разобрано, поле оставлю как было: "+[...непонятно].slice(0,10).join(" | ")):"")+
    (чужиеИсп.size?("\n\nИсполнителя нет среди специалистов, поле оставлю как было: "+
      [...чужиеИсп].slice(0,10).join(", ")):"")+
    стёртоТекст(стёрто))) return;
  отменаНачать("импорт задач", [REG_ЗАД]);
  const отметка=new Date().toISOString(), место=getWS().код, день=отметка.slice(0,10);
  правки.forEach(п=>{
    const з=п.rec;
    if(п.поля.includes("срок") && з.срок){
      if(!з.срок_первый) з.срок_первый=з.срок;
      з.переносы=(з.переносы||[]).concat([{было:з.срок, стало:п.знач.срок, причина:"правка из Excel", когда:день}]);
    }
    п.поля.forEach(k=>{ з[k]=п.знач[k]; });
    з.изменено=отметка; з.место_правки=место;   // иначе правка не уйдёт в обмен
  });
  новые.forEach(знач=>{
    // Новая задача без места исполнителя — место из карточки специалиста.
    if(!знач.место && знач.исполнитель){ const м=местоСпециалиста(знач.исполнитель); if(м) знач.место=м; }
    ЗАД.push(Object.assign({id:newId("ЗД"), статус:"назначена", горизонт:"неделя",
      постановщик:место, создано:отметка, изменено:отметка, место_правки:место}, знач));
  });
  saveReg(REG_ЗАД,ЗАД);
  отменаЗавершить();
  switchView("tasks");
  toast([правки.length?("обновлено "+правки.length):"", новые.length?("поставлено "+новые.length):""]
    .filter(Boolean).join(", "));
}
function ЗАДАЧИ_живые(){ return ЗАД.filter(з=>!з.удалено); }

