// Куски, внутри которых перенос невозможен: обычный пробел — точка
// переноса, неразрывный (\u00a0) — нет, поэтому по нему НЕ делим; после
// дефиса перенос разрешён, поэтому «55724-2013» считается двумя кусками
// («55724-» и «2013»), иначе колонка вышла бы шире нужного.
function кускиБезПереноса(t){
  const из=[];
  String(t==null?"":t).split(/[ \t\n\r]+/).forEach(сл=>{
    if(!сл) return;
    if(сл.indexOf("-")>0){
      const ч=сл.split("-");
      ч.forEach((x,i)=>{ const к=(i<ч.length-1)?(x+"-"):x; if(к) из.push(к); });
    } else из.push(сл);
  });
  return из;
}
// знач — строка или массив строк (многострочная ячейка)
function самоеДлинноеСлово(знач, мера){
  const строки=Array.isArray(знач)?знач:[знач];
  let м=0;
  строки.forEach(с=>кускиБезПереноса(с).forEach(к=>{ м=Math.max(м,мера(к)); }));
  return м;
}
// Минимум колонки — самое длинное слово шапки и данных плюс отступы
// ячейки; объединённая ячейка шапки (спан>1) меряется на группу колонок
// и её требование раскладывается поровну — слову хватит их суммы.
function минимумыКолонок(заг, спан, строки, мера, мераЖир, отступ){
  const n=спан.reduce((a,b)=>a+b,0), мин=new Array(n).fill(0);
  let к=0;
  заг.forEach((h,j)=>{ const s=спан[j]||1, w=самоеДлинноеСлово(h,мераЖир);
    for(let q=0;q<s;q++) мин[к+q]=Math.max(мин[к+q], Math.ceil(w/s));
    к+=s; });
  (строки||[]).forEach(р=>р.forEach((я,i)=>{
    if(i<n) мин[i]=Math.max(мин[i], самоеДлинноеСлово(я,мера)); }));
  // запас 3% — тот же принцип, что у ширинаДолжностей: померенная впритык
  // строка рискует перенестись из-за мелких расхождений в кернинге.
  return мин.map(v=>Math.ceil(v*1.03)+отступ);
}
// Остаток ширины сверх минимумов распределяется по весам — туда, где
// реально бывает длинный текст. Если минимумы не влезают в лист вовсе,
// ужимаются пропорционально: разорванное слово лучше, чем таблица шире
// страницы (для экрана этого не случается — там ширину задаём по сумме).
function разложитьШирины(мин, веса, всего){
  const сум=мин.reduce((a,b)=>a+b,0);
  let w;
  if(сум>=всего){ const k=всего/сум; w=мин.map(v=>Math.max(1,Math.floor(v*k))); }
  else {
    const ост=всего-сум, вс=веса.reduce((a,b)=>a+b,0)||1;
    w=мин.map((v,i)=>v+Math.floor(ост*(веса[i]||0)/вс));
  }
  const разн=всего-w.reduce((a,b)=>a+b,0);
  w[w.length-1]+=разн;
  return w;
}
function ширинаДолжностей(подписи){
  let макс=0;
  (подписи||[]).forEach(r=>{
    макс=Math.max(макс, твипыСтроки(r.д), твипыСтроки(r.орг));
  });
  if(!макс) return ПРЕДЕЛ_ДОЛЖНОСТИ;
  // Запас: без него строка, померенная впритык, рискует перенестись из-за
  // мелких расхождений в кернинге. Сдвиг центра на полмиллиметра дешевле
  // переноса, поэтому запас щедрый — 3% и не меньше 80 твипов.
  return Math.min(ПРЕДЕЛ_ДОЛЖНОСТИ, Math.ceil(макс*1.03)+80);
}

// Строка не должна заканчиваться висящим словом: однобуквенным («в», «с»,
// «и») или коротким предлогом («на», «по», «от»). Приём один — неразрывный
// пробел после такого слова: оно уезжает на следующую строку вместе со
// своим существительным.
//
// Список намеренно короткий. Чем больше неразрывных пробелов, тем сильнее
// выключка растягивает остальные — лечить надо висящие слова, а не все
// подряд.
const ВИСЯЧИЕ = ("а,и,в,к,о,с,у,я,б,ж,"+                       // однобуквенные
                 "на,по,до,из,от,за,об,во,со,ко,из-за,"+       // предлоги
                 "не,ни,но,же,ли,бы,да,то").split(",");
const ВИСЯЧИЕ_ДЛИННЫЕ = ("при,для,над,под,про,без,изо,ото,что,как,или,"+
                         "если,чем,так,перед,между,через,после").split(",");
// Организационно-правовые формы: «ООО «Константа»» не должно рваться по
// пробелу после «ООО». Порядок в наборе не важен — слово ловится по
// границе (перед ним начало строки, пробел или скобка/кавычка), поэтому
// «АО» не отщипывается от «ЗАО».
const СОКР_ЮРЛИЦА = "ООО|ОАО|ЗАО|ПАО|НАО|АО|ИП|ФГУП|ФГБУ|ФГАУ|ГУП|МУП|"+
                    "НПО|НПП|НПФ|НПЦ|АНО|ПКФ|ОКБ|КБ|ТД";
// «500л» пишется как «500 л»: между числом и единицей нужен пробел.
// Список единиц закрытый — иначе пробел влезет в марку вроде «РГС-10»
// или «АР40/160».
// Градус Цельсия — единица, перед ней пробел нужен («20 °C», ГОСТ 8.417);
// голый знак градуса (угол) пишется ВПЛОТНУЮ к числу — «90°», поэтому в
// этом списке его нет, только «°C»/«°С».
const ЕДИНИЦЫ = "мм|см|дм|км|мг|кг|т|л|г|м|шт|ч|мин|с|%|°C|°С|МПа|кгс|Н|В|А|Вт";
// Знака градуса на клавиатуре нет, а в характеристиках температур он
// нужен постоянно. Способов три, и все три равноправны: кнопка «°» под
// полем (см. рядСимволов), Alt+0176 на цифровой клавиатуре Windows и
// запись «^o» — тем же знаком «^», которым уже пишется степень. Почему
// именно буква «o»/«о»: степенью буква не бывает, поэтому подмена
// однозначна; «^0» (ноль) НЕ трогаю — это может быть настоящая нулевая
// степень. Подмена идёт до разбора степеней, поэтому «20^oC» печатается
// как «20 °C», а не надстрочной буквой.
function знакГрадуса(t){ return String(t==null?"":t).replace(/\^[oо]/g,"\u00b0"); }
function пробелПередЕдиницей(t){
  const ре=new RegExp("(\\d)("+ЕДИНИЦЫ+")(?![А-Яа-яA-Za-z0-9])","g");
  return String(t==null?"":t).replace(ре,"$1 $2");
}
// Ручная разметка во всех полях, из которых собираются документы
// (указание заказчика): «^_» — жёсткий (неразрывный) пробел, «^/» — с
// новой строки. Тем же знаком «^», что степень и градус: в поле ввода
// разметку видно, она переживает выгрузку в Excel и обратно, а сам знак
// в документ не печатается. Настоящий неразрывный пробел (Alt+0160) и
// перевод строки в многострочном поле тоже работают как есть.
function разметкаВвода(t){
  return String(t==null?"":t).replace(/\^_/g,"\u00a0").replace(/[ \t]*\^\/[ \t]*/g,"\n");
}
// Цифры в наименовании должности не отрываются от следующего за ними
// слова (указание заказчика): «инженер 2 категории».
function связатьЧисла(t){ return String(t==null?"":t).replace(/(\d)[ \t]+(?=[^\s\d])/g,"$1\u00a0"); }
function типографика(t){
  t=пробелПередЕдиницей(знакГрадуса(разметкаВвода(t)));
  let s=String(t==null?"":t);
  const набор=ВИСЯЧИЕ.concat(ВИСЯЧИЕ_ДЛИННЫЕ)
    .map(w=>w.replace(/[-]/g,"\\-")).join("|");
  // пробел после висящего слова → неразрывный. Слово ловим по границе:
  // перед ним начало строки, пробел или открывающая скобка/кавычка.
  const ре=new RegExp("(^|[\\s(«\"])((?:"+набор+"))\\s+","gi");
  s=s.replace(ре,(m,до,сл)=>до+сл+"\u00a0");
  // Число и его единица не разрываются: «40 л», «10 м3». Список единиц
  // закрытый — иначе к числу приклеивается любое следующее слово, и
  // «10 м3 РГС-10» превращалось в неразрывное «10 м3 РГС-10» целиком.
  s=s.replace(/(\d)\s+(мм|см|дм|км|мг|кг|м|л|г|т|шт|ч|мин|%|°C|°С|°|МПа|кгс)(?![А-Яа-яA-Za-z])/g,
              "$1\u00a0$2");
  // знак номера не отрывается от самого номера: «№ 5», «№ 1188/26»
  s=s.replace(/(\u2116\u2116?)\s+(?=[\dA-Za-zА-Яа-я])/g,"$1\u00a0");
  // «от 15.01.2026 г.» — «г.» не отрывается от даты
  s=s.replace(/(\d)\s+(г\.)/g,"$1\u00a0$2");
  // инициалы: «И.И. Иванов»
  s=s.replace(/([А-ЯЁ]\.[А-ЯЁ]\.)\s+/g,"$1\u00a0");
  // Организационно-правовая форма не отрывается от названия завода:
  // «ООО «Константа»», «Константа, ООО» (заказчик попросил про паспорт,
  // но правило общее — висящее «ООО» в конце строки одинаково плохо
  // везде). Список закрытый: заказчик назвал «ООО, ИП, АО и т.д.» —
  // беру общеупотребительные формы, редкие не выдумываю. Аббревиатура
  // привязывается к СЛЕДУЮЩЕМУ слову (как и просил заказчик), а если
  // стоит в конце названия — к предыдущему, иначе привязать не к чему.
  s=s.replace(new RegExp("(^|[\\s(«\"])("+СОКР_ЮРЛИЦА+")\\s+(?=[«\"'A-Za-zА-ЯЁа-яё0-9])","g"),
              "$1$2\u00a0");
  s=s.replace(new RegExp("\\s+("+СОКР_ЮРЛИЦА+")(?=\\s*$|,)","g"),"\u00a0$1");
  return s;
}

// Размерность со степенью: «10 м3» и «кгс/см2» правильно пишутся как
// м³ и см². Список единиц закрытый и короткий — гадать тут не о чем, а
// цифра после «№» или внутри марки («РГС-10 №3») под правило не попадает.
const ЕДИНИЦЫ_СО_СТЕПЕНЬЮ = "(мм|см|дм|км|м)([23])(?![0-9А-Яа-яA-Za-z])";
// Явная степень — знак «^» перед ней: «1777×10^3», «м/с^2», «мин^-1»,
// «увеличение 10^х», «90^о». Почему явно, а не «само догадается»: по
// соседству с числом степень НЕ угадывается — «×103» это с равным правом
// и «×10³», и честное «умножить на 103», а «3^2» — и «3²», и «3 в
// степени 2» из текста методики. Гадать тут нельзя, а закрытый список
// единиц (мм2 → мм²) для всего остального не годится — единиц слишком
// много, и «С2» вполне может оказаться типом датчика, а не «с²».
// Длинная степень — в фигурных скобках: «10^{-12}».
const СТЕПЕНЬ_ЯВНО = "\\^(?:\\{([^}]{1,8})\\}|(-?[0-9]+|[A-Za-zА-Яа-яёЁ°º]))";
function разбитьСтепени(t){
  const s=String(t||""), ре=new RegExp(ЕДИНИЦЫ_СО_СТЕПЕНЬЮ+"|"+СТЕПЕНЬ_ЯВНО,"g");
  const части=[]; let поз=0, m;
  while((m=ре.exec(s))!==null){
    if(m.index>поз) части.push({т:s.slice(поз,m.index)});
    if(m[1]!==undefined){            // единица со степенью: мм2, см3
      части.push({т:m[1]});
      части.push({т:m[2], степень:true});
    } else {                          // явный «^»: сам знак не печатается
      части.push({т:(m[3]!==undefined?m[3]:m[4]), степень:true});
    }
    поз=m.index+m[0].length;
  }
  if(поз<s.length) части.push({т:s.slice(поз)});
  return части.length?части:[{т:s}];
}
