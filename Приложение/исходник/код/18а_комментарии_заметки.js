function утвердитьПроект(id){
  if(!яНачальник()){ toast("Утверждают начальник и заместитель"); return; }
  const з=ЗАД.find(x=>x.id===id); if(!з || з.статус!=="проект") return;
  const поля=поляФормыЗадачи(); if(!поля) return;
  if(!поля.исполнитель || !поля.срок){ toast("Назначьте исполнителя и срок — тогда проект можно утвердить"); return; }
  Object.assign(з, поля, {статус:"назначена", постановщик:getWS().код, постановщик_ид:ктоПишет().автор_ид,
    постановщик_кто:ктоЯ(), утвердил:ктоЯ()||getWS().код, утверждено:сегодняМестн(), причина_проекта:""});
  отметитьЗадачу(з); формаСохранена(); editTask(id); toast("Проект утверждён — это задача");
}
function решитьПроект(id, статус, вопрос, начало){
  if(!яНачальник()){ toast("Решают начальник и заместитель"); return; }
  const з=ЗАД.find(x=>x.id===id); if(!з || з.статус!=="проект") return;
  const т=prompt(вопрос); if(т===null) return;
  if(!т.trim()){ toast("Напишите "+(статус==="возвращён"?"комментарий":"причину")); return; }
  const поля=поляФормыЗадачи(); if(поля) Object.assign(з, поля);
  Object.assign(з, {статус, причина_проекта:т.trim(), проект_решил:ктоЯ()||getWS().код, проект_решено:сегодняМестн()});
  отметитьЗадачу(з);
  добавитьКомментарий(id, начало+т.trim());
  формаСохранена(); editTask(id);
}
