function прибавитьМесяцы(iso, мес){
  const m=/^(\d{4})-(\d{2})-(\d{2})$/.exec(String(iso||"")); const н=parseInt(мес,10);
  if(!m || !(н>0)) return "";
  const всего=(+m[1])*12+(+m[2]-1)+н, г=Math.floor(всего/12), мс=всего%12;
  const дн=Math.min(+m[3], new Date(Date.UTC(г,мс+1,0)).getUTCDate());
  return new Date(Date.UTC(г,мс,дн)).toISOString().slice(0,10);
}
function смкСледПроверка(д){ return прибавитьМесяцы(String(д.проверено||"").trim()||String(д.дата_введения||"").trim(), д.периодичность); }
