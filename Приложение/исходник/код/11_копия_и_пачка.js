// ── Файлы в папке с документами: подпапки, выбор, проверка ──
// Имя файла в карточке может содержать подпапки: «2027/Поверка 12978.pdf»
// (раскладывать свидетельства по годам — просьба заказчика). Разделитель —
// «/» или «\\» (как пишет Проводник), оба приводятся к «/». Выйти из папки
// с документами («..») нельзя: программе разрешено только внутри неё.
function путьФайлаДок(имя){
  const ч=String(имя||"").trim().replace(/\\/g,"/").split("/").map(x=>x.trim()).filter(x=>x && x!==".");
  if(!ч.length || ч.indexOf("..")>=0) return null;
  return ч;
}
function имяБезПапок(имя){ const ч=путьФайлаДок(имя); return ч?ч[ч.length-1]:String(имя||"").trim(); }
async function файлИзПапкиДок(h, имя){
  const ч=путьФайлаДок(имя); if(!ч) throw new DOMException("неверное имя","NotFoundError");
  let д=h;
  for(let i=0;i<ч.length-1;i++) д=await д.getDirectoryHandle(ч[i]);
  return д.getFileHandle(ч[ч.length-1]);
}
