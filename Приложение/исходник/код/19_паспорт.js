let _таблПаспорт=false;
const ПАСП_КЕГЛЬ=20, ПАСП_СТРОКА=230;
const ПАСП_ШИРИНА_ТАБЛ=Math.round(25/2.54*1440);   // 25 см = 14173 твипа
function кегльТабл(){ return _таблПаспорт?ПАСП_КЕГЛЬ:24; }
function кегльТаблXml(){ const к=кегльТабл(); return '<w:sz w:val="'+к+'"/><w:szCs w:val="'+к+'"/>'; }
