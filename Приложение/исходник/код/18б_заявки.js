// «Проверка данных»: один номер у двух заявок (два места выдали между
// обменами) — ошибка; открытая заявка с прошедшим сроком — внимание.
function проверкиЗаявок(доб, сс){
  const поН={};
  live(ЗАЯВ).forEach(з=>{ const н=String(з.номер||"").trim(); if(н) (поН[н]=поН[н]||[]).push(з); });
  const дв=Object.keys(поН).filter(н=>поН[н].length>1);
  if(дв.length) доб("ошибка","Заявки подразделений",
    "Один номер у нескольких заявок: "+дв.length+" — номер выдан на двух местах между обменами; поправьте номер в одной из заявок",
    дв.flatMap(н=>поН[н].map(з=>сс(н+" — "+заявкаКратко(з)+" ("+(з.место||"")+")","request",з.id))));
  const сег=сегодняМестн();
  const прос=live(ЗАЯВ).filter(з=>заявкаОткрыта(з) && з.статус!=="зарегистрирована" && срокЗаявки(з) && срокЗаявки(з)<сег);
  if(прос.length) доб("внимание","Заявки подразделений","Утверждённые заявки с прошедшим сроком: "+прос.length,
    прос.map(з=>сс((з.номер||"")+" — срок "+ru(срокЗаявки(з))+" — "+заявкаКратко(з),"request",з.id)));
}
