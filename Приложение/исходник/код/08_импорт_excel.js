const КОЛ_КОД="Код записи (не менять)";
// ПУСТАЯ ЯЧЕЙКА СТИРАЕТ значение — выбор заказчика (версия 3.15; до неё
// пустая ячейка значение не трогала). Защиты, без которых это правило
// опасно, общие для всех круговых правок:
//  · столбца в файле нет вовсе — поле не трогается (стирает только
//    очищенная ячейка, а не удалённый столбец);
//  · обязательное поле (наименование и т.п.) не стирается — запись без
//    него стала бы безымянной; такие места называются;
//  · ячейку, которую не удалось разобрать (дата, число, ссылка на
//    карточку, значение списка), не путаю с пустой: поле остаётся как было;
//  · в подтверждении отдельной строкой — сколько значений и в каких полях
//    будет стёрто.
// стёрто — Map «подпись поля» → число записей.
function стёртоТекст(стёрто){
  const всего=[...стёрто.values()].reduce((a,b)=>a+b,0);
  if(!всего) return "";
  return "\n\n⚠ БУДЕТ СТЁРТО значений: "+всего+" — "+
    [...стёрто].map(([л,n])=>"«"+л+"»: "+n).join(", ")+
    ".\nПустая ячейка очищает поле. Если столбец очищен случайно — нажмите «Отмена».";
}
function стёртоДоб(стёрто,л){ стёрто.set(л,(стёрто.get(л)||0)+1); }
