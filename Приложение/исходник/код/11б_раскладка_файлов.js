// ── Обход папки ───────────────────────────────────────────────
async function обойтиПапкуДок(д, путь, вАрхиве, из, глубина){
  if(глубина>8) return;
  for await (const [имя, h] of д.entries()){
    if(/^(~\$|\.)/.test(имя) || /^desktop\.ini$|^thumbs\.db$/i.test(имя)) continue;
    if(h.kind==="directory") await обойтиПапкуДок(h, путь.concat(имя), вАрхиве || имя===ПАПКА_АРХИВ, из, глубина+1);
    else из.push({путь:путь.concat(имя).join("/"), имя, вАрхиве, отн:путь.slice(1), _h:h});
  }
}
async function файлыКорня(h, корень){
  let д; try{ д=await h.getDirectoryHandle(корень); }catch(e){ return null; }
  const из=[]; await обойтиПапкуДок(д, [корень], false, из, 0); return из;
}
