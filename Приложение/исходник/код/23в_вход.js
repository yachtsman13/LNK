function setПраваСпец(ид, права){
  if(!можноУправлятьВходом()){ toast("Права меняют только начальник и заместитель"); return; }
  const сп=найтиПоИд(P, ид); if(!сп) return;
  if(входВкл() && String(сп.id)===String(_я) && !руководитель({права, должность:""}) &&
     !live(P).some(x=>String(x.id)!==String(_я) && руководитель(x) && состояниеПароля(x.id)!=="не выдан")){
    toast("Нельзя снять права с себя: других руководителей с паролем нет"); renderLab(); return; }
  сп.права=права; сп.изменено=new Date().toISOString(); сп.место=getWS().код;
  saveReg(REG_PPL, P); toast("Права: "+(сп.фио||"")+" — "+права.toLowerCase());
  if(curView==="lab") renderLab(); обновитьШапкуВхода();
}
async function выдатьПароль(ид){
  if(!можноУправлятьВходом()){ toast("Пароли выдают только начальник и заместитель"); return; }
  const сп=найтиПоИд(live(P), ид); if(!сп) return;
  const я=входВкл() && String(ид)===String(_я);
  if(я){ await сменитьПарольОкно(false); if(curView==="lab") renderLab(); return; }
  const р=await окноПароля((состояниеПароля(ид)==="не выдан"?"Выдать":"Сбросить")+" пароль: "+(сп.фио||""),
    [{л:"Временный пароль ("+ПАРОЛЬ_МИН+"–"+ПАРОЛЬ_МАКС+" знаков)", тип:"text", з:временныйПароль()}],
    "Сообщите пароль специалисту: при первом входе программа попросит заменить его своим.");
  if(!р) return;
  const пароль=р.значения[0], ош=ошибкаПароля(пароль); if(ош){ alert(ош); return; }
  await записатьПароль(сп.id, пароль, true);
  toast("Временный пароль выдан: "+(сп.фио||""));
  if(curView==="lab") renderLab();
}
async function включитьВход(){
  if(входВкл()) return;
  const рук=live(P).filter(руководитель);
  if(!рук.length){ alert("В справочнике нет ни начальника, ни заместителя. Отметьте права в таблице «Вход в программу и права»."); return; }
  // Включает руководитель: выбирает себя и вводит (или задаёт) свой пароль.
  const выбор=рук.map((x,i)=>(i+1)+". "+(x.фио||x.вдок||"")+" — "+праваСпец(x).toLowerCase()).join("\n");
  const н=prompt("Кто включает вход? Впишите номер:\n\n"+выбор, "1"); if(н==null) return;
  const сп=рук[parseInt(н,10)-1]; if(!сп){ alert("Нет такого номера"); return; }
  if(состояниеПароля(сп.id)==="свой"){
    const р=await окноПароля("Ваш пароль: "+(сп.фио||""),[{л:"Пароль"}]); if(!р) return;
    if(!(await парольВерен(сп.id, р.значения[0]))){ alert("Неверный пароль"); return; }
  } else {
    const р=await окноПароля("Задайте свой пароль: "+(сп.фио||""),[{л:"Пароль ("+ПАРОЛЬ_МИН+"–"+ПАРОЛЬ_МАКС+" знаков)"},{л:"Ещё раз"}]);
    if(!р) return;
    const [п1,п2]=р.значения, ош=ошибкаПароля(п1)||(п1!==п2?"Пароль и повтор не совпадают":"");
    if(ош){ alert(ош); return; }
    await записатьПароль(сп.id, п1, false);
  }
  const без=live(P).filter(x=>состояниеПароля(x.id)==="не выдан").length;
  if(!confirm("Включить вход по паролю?\n\nПосле обмена он включится на всех местах. "+
    (без?"Паролей ещё нет у "+без+" специалистов — они не смогут войти, пока вы не выдадите им временные.":"Пароли есть у всех."))) return;
  _я=String(сп.id); _последнийВошёл=_я; _последнееДействие=Date.now();
  const о=вход(); о.вкл=true; о.сброшен=null; сохранитьВход(о);
  обновитьШапкуВхода(); setChrome(); if(curView==="lab") renderLab();
  toast("Вход включён. Вы вошли: "+фамилияИО(сп));
}
function выключитьВход(){
  if(!входВкл()) return;
  if(!яНачальник()){ toast("Выключают вход только начальник и заместитель"); return; }
  if(!confirm("Выключить вход по паролю на всех местах (после обмена)? Пароли сохранятся — включить можно снова.")) return;
  const о=вход(); о.вкл=false; сохранитьВход(о); _я=null;
  обновитьШапкуВхода(); setChrome(); if(curView==="lab") renderLab();
  toast("Вход выключен");
}
