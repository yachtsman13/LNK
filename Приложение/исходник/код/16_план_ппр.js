// wТаблШапка() паспорта считает ширину таблицы по ШИРИНА_ТЕКСТА (книжная
// страница) — плану нужна альбомная, поэтому берём ту же вёрстку ячеек,
// но с суммой ширин по ШИРИНА_АЛЬБОМ.
// tblW — ширинаАльбомТабл(): у паспорта 25 см и таблица по центру (jc
// стоит сразу после tblW — порядок CT_TblPr), у остальных — как было.
function tblWАльбом(){
  return '<w:tblW w:w="'+ширинаАльбомТабл()+'" w:type="dxa"/>'+(_таблПаспорт?'<w:jc w:val="center"/>':'');
}
function wТаблШапкаШир(шапка, ширины, строки, центр, серый){
  const grid=ширины.map(ш=>'<w:gridCol w:w="'+ш+'"/>').join('');
  let из='<w:tbl><w:tblPr>'+tblWАльбом()+
    '<w:tblBorders>'+wГраницыТабл()+'</w:tblBorders>'+
    '<w:tblLayout w:type="fixed"/>'+
    '<w:tblCellMar><w:left w:w="60" w:type="dxa"/><w:right w:w="60" w:type="dxa"/></w:tblCellMar>'+
    '</w:tblPr><w:tblGrid>'+grid+'</w:tblGrid>';
  из+=wСтрокаТабл(шапка,ширины,true,центр,серый);
  строки.forEach(р=>из+=wСтрокаТабл(р,ширины,false,центр,серый));
  из+='</w:tbl>';
  return из;
}

// Каркас альбомной таблицы (те же свойства, что у wТаблШапкаШир) с
// готовыми строками: нужен Форме 2 паспорта, где шапка и тело — ДВЕ
// отдельные таблицы, см. wРазделительТаблиц.
function wКаркасАльбом(ширины, строкиXml){
  const grid=ширины.map(ш=>'<w:gridCol w:w="'+ш+'"/>').join('');
  return '<w:tbl><w:tblPr>'+tblWАльбом()+
    '<w:tblBorders>'+wГраницыТабл()+'</w:tblBorders>'+
    '<w:tblLayout w:type="fixed"/>'+
    '<w:tblCellMar><w:left w:w="60" w:type="dxa"/><w:right w:w="60" w:type="dxa"/></w:tblCellMar>'+
    '</w:tblPr><w:tblGrid>'+grid+'</w:tblGrid>'+строкиXml+'</w:tbl>';
}
// Заказчик просил: на каждой странице столбцы подписываются ТОЛЬКО
// цифрой, а подпись столбца с номером под ней — один раз, в первый раз.
// Одной таблицей это невыразимо: w:tblHeader повторяет только строки,
// идущие подряд ОТ ПЕРВОЙ, поэтому пометить одну строку номеров нельзя —
// Word её проигнорирует. Поэтому таблицы две: подписи (не повторяется) и
// номера с данными (строка номеров помечена w:tblHeader и повторяется).
// Между ними обязан стоять абзац: ДВЕ СОСЕДНИЕ таблицы без абзаца Word
// сшивает в одну, и повторение строки номеров молча пропало бы. Абзац —
// минимально возможный: кегль 1 пт, интервалы 0, точная высота строки
// 20 твипов (1 пт); keepNext не даёт подписям оторваться от таблицы.
// Порядок в CT_PPr строгий: keepNext ИДЁТ ПЕРЕД spacing.
function wРазделительТаблиц(){
  return '<w:p><w:pPr><w:keepNext/>'+
    '<w:spacing w:before="0" w:after="0" w:line="20" w:lineRule="exact"/>'+
    '<w:rPr>'+ФОНТ+'<w:sz w:val="2"/><w:szCs w:val="2"/></w:rPr></w:pPr></w:p>';
}

