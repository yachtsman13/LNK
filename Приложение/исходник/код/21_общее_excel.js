// ── Выгрузка в Excel (.xlsx) ──────────────────────────────
// Раньше выгружался CSV. В Office 2016 это лотерея: разделитель столбцов
// CSV берёт из региональных настроек Windows, и на другой машине файл
// открывается одной колонкой. Плюс даты и числа приезжают текстом.
// Настоящий .xlsx — это тот же ZIP, что и .docx, писать его умеем.
//
// Строки кладём прямо в ячейки (inlineStr), без общей таблицы строк:
// файл чуть больше, зато собирается в один проход и не может разъехаться.
const XL_ЭПОХА = Date.UTC(1899,11,30);          // Excel считает дни от 30.12.1899
function xlДата(iso){
  const m=/^(\d{4})-(\d{2})-(\d{2})/.exec(String(iso||"")); if(!m) return null;
  return Math.round((Date.UTC(+m[1],+m[2]-1,+m[3])-XL_ЭПОХА)/86400000);
}
function xlБуква(n){                             // 1 → A, 27 → AA
  let s=""; while(n>0){ const о=(n-1)%26; s=String.fromCharCode(65+о)+s; n=(n-о-1)/26; }
  return s;
}
function xlЯчейка(адрес, знач, тип){
  if(знач==null || знач==="") return "";
  if(тип==="дата"){
    const д=xlДата(знач);
    if(д!=null) return '<c r="'+адрес+'" s="2"><v>'+д+'</v></c>';
  }
  if(тип==="число"){
    const ч=Number(String(знач).replace(",","."));
    if(isFinite(ч) && String(знач).trim()!=="") return '<c r="'+адрес+'"><v>'+ч+'</v></c>';
  }
  return '<c r="'+адрес+'" t="inlineStr"><is><t xml:space="preserve">'+X(знач)+'</t></is></c>';
}
function xlЛист(лист){
  const кол=лист.колонки, N=кол.length, M=лист.строки.length;
  let xml='<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'+
    '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">'+
    '<dimension ref="A1:'+xlБуква(N)+Math.max(1,M+1)+'"/>'+
    // шапка закреплена — иначе на 315 строках непонятно, что за столбец
    '<sheetViews><sheetView workbookViewId="0">'+
    '<pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/>'+
    '</sheetView></sheetViews>'+
    '<sheetFormatPr defaultRowHeight="15"/><cols>';
  кол.forEach((к,i)=>{ xml+='<col min="'+(i+1)+'" max="'+(i+1)+'" width="'+(к.ш||16)+'" customWidth="1"/>'; });
  xml+='</cols><sheetData><row r="1">';
  кол.forEach((к,i)=>{ xml+='<c r="'+xlБуква(i+1)+'1" t="inlineStr" s="1"><is><t>'+X(к.з)+'</t></is></c>'; });
  xml+='</row>';
  лист.строки.forEach((стр,ri)=>{
    const r=ri+2; xml+='<row r="'+r+'">';
    стр.forEach((v,ci)=>{ xml+=xlЯчейка(xlБуква(ci+1)+r, v, кол[ci].тип); });
    xml+='</row>';
  });
  xml+='</sheetData>';
  // По схеме autoFilter идёт ПОСЛЕ sheetData, а не до — иначе Excel
  // объявит книгу повреждённой (та же строгость, что и в Word).
  if(M) xml+='<autoFilter ref="A1:'+xlБуква(N)+(M+1)+'"/>';
  return xml+'</worksheet>';
}
