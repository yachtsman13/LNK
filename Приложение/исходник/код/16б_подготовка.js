// Какие измерения — у ВД из карточки учёта вибрации.
function измеренияРаботы(р){
  if(р.ист!=="ПГ") return "";
  if(р.вид==="ВД"){
    if(!р.карта) return "карточка учёта вибрации не связана — точки неизвестны";
    const оп=опорыКарты(р.карта), пр=порогиКарты(р.карта), зам=замерыКарты(р.карта.id), посл=зам[зам.length-1];
    return "СКЗ виброскорости (мм/с) и виброускорение (дБ), направления В / Г / О, точки: "+оп.join("; ")+
      (пр.предел?"; предел "+пр.предел.v+" мм/с":"")+(пр.пред?", предупредительное "+пр.пред.v:"")+
      (посл?"; прошлый замер "+ru(посл.дата):"; замеров ещё нет");
  }
  return "";
}
function подготовкаСводка(вид, база){
  const [с,по]=границыПериода(вид, база);
  const работы=работыПодготовки(с,по);
  const ппр=ппрПриборовПериода(с,по);
  const методы=[...new Set(работы.filter(р=>!р.сделано).flatMap(р=>р.методы))].sort((a,b)=>METHODS.indexOf(a)-METHODS.indexOf(b));
  const поМетодам=методы.map(м=>Object.assign(подсказкиМетода(м,с,по,ппр), {работ:работы.filter(р=>!р.сделано && р.методы.indexOf(м)>=0).length}));
  let ппрРабот=[];
  if(позицииППР().length) месяцыПериода(с,по).forEach(ym=>{ const [г,м]=ym.split("-").map(Number);
    работыМесяца(г,м).forEach(р=>ппрРабот.push({ym, р})); });
  return {с, по, имя:имяПериода(вид, база), работы, поМетодам, ппрРабот};
}
