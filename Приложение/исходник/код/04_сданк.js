// Номер по классификатору СДАНК для готового значения из л.область_объекты/
// л.область_методы (формат значения — см. деревоСДАНК ниже). Нужен, чтобы
// в паспорте (разделы III, IV) показать те же номера «N»/«N.M», что и в
// самой карточке лаборатории у области аттестации — не выдумывать заново
// нумерацию, а искать её в том же СДАНК_ОБЪЕКТЫ/СДАНК_МЕТОДЫ. Значение,
// вписанное когда-то вручную и не совпадающее ни с одним пунктом
// справочника (например, старые данные до этого поля) — просто без номера.
function номерСДАНК(список, значение){
  for(const к of список){
    if(!к.под.length){ if(к.имя===значение) return к.н; continue; }
    for(const п of к.под){ if(к.имя+" — "+п.т===значение) return п.н; }
  }
  return null;
}
// Дерево флажков для классификатора СДАНК: верхняя категория + подпункты.
// Значение подпункта хранится как «Категория — Подпункт», чтобы в паспорте
// однозначно читалось, к какой категории он относится. У категории без
// подпунктов (напр. «Оборудование электроэнергетики») флажок — сама категория.
// Номера — те же, что в тексте СДАНК-01-2020 (Приложение 1 и раздел 4):
// у категории свой «N», у подпункта «N.M» (а где в тексте было ещё на
// уровень глубже — например 2.1.1 у газопроводов — номер вписан как есть,
// без выдумывания промежуточного уровня вложенности в самом дереве).
// Флажок — ПЕРЕД номером, номер — перед текстом: «[ ] 1.9. Сосуды…».
function деревоСДАНК(список, выбрано, класс){
  выбрано=выбрано||[];
  return список.map(к=>{
    if(!к.под.length){
      const отм=выбрано.indexOf(к.имя)>=0;
      return `<label class="сд-верх"><input type="checkbox" class="${класс}"
        value="${esc(к.имя)}" ${отм?"checked":""}> ${esc(к.н)}. ${esc(к.имя)}</label>`;
    }
    return `<div class="сд-группа"><div class="сд-верх-имя">${esc(к.н)}. ${esc(к.имя)}</div>`+
      к.под.map(п=>{
        const зн=к.имя+" — "+п.т, отм=выбрано.indexOf(зн)>=0;
        return `<label class="сд-под"><input type="checkbox" class="${класс}"
          value="${esc(зн)}" ${отм?"checked":""}> ${esc(п.н)}. ${esc(п.т)}</label>`;
      }).join("")+`</div>`;
  }).join("");
}
