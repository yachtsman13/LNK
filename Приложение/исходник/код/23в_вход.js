// ── Вход в программу по паролю, права у человека (3.86, защита 4.01) ──
// Входят только специалисты из справочника; права — начальник /
// заместитель / специалист — у человека. Автовыход — настройка компьютера.
// Пароль хранится только как PBKDF2-SHA-256 с отдельной солью. В 4.01:
//   • новые пароли — 4–128 знаков, без обязательного набора «букв и цифр»:
//     длинная фраза разрешена, явно слабые и повторённые значения — нет;
//   • у хеша сохраняются его итерации, поэтому пароли версий 3.86–4.0
//     проверяются по-прежнему, но при первом входе просят задать новый;
//   • пять неудачных попыток за 15 минут закрывают вход этому специалисту
//     на этом компьютере на 15 минут; ограничение сохраняется при
//     перезагрузке страницы;
//   • аварийный доступ НЕ выключает вход на всех местах: одноразовый код
//     восстановления выдаёт временный пароль руководителю и заменяется.
//
// Программа — один файл без сервера: это защита от случайного человека и
// перебора через штатное окно, но не от владельца браузера и его данных.
