    // ── 7. Резервная копия ───────────────────────────────────
    раздел("7. Резервная копия");
    const до = await p.evaluate(() => ({ ж: liveJ().length, о: live(O).length, п: live(S).length, нд: live(НД).length,
      прим: live(S)[0].примечание }));
