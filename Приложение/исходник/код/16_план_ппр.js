function работыМесяца(год,мес){
  const из=[];
  позицииППР().forEach(п=>{
    const ч=((п.план||{})[String(год)]||{})[String(мес)];
    if(ч) из.push({поз:п, часы:ч, отм:отметка(п,год,мес)});
  });
  return из;
}
function итогиГода(год){
  let работ=0, часы=0, сделано=0, часовСделано=0;
  for(let м=1;м<=12;м++){
    работыМесяца(год,м).forEach(р=>{
      работ++; часы+=р.часы;
      if(р.отм){ сделано++; часовСделано+=р.часы; }
    });
  }
  return {работ, часы:+часы.toFixed(2), сделано,
          часовСделано:+часовСделано.toFixed(2),
          доля: работ?сделано/работ:0};
}
// Один источник правды о «сейчас»: и подсветка ячеек, и счёт просроченного
// должны считать прошедшим одно и то же, иначе цифра и цвет разойдутся.
// Год и месяц приводим к числу явно. Сегодня сюда приходят числа
// (годПлана() делает +г, месяц — счётчик цикла), но строка из HTML-
// атрибута сломала бы обе функции молча: «2026»===2026 ложно, и
// «прошедший» на прошлом месяце возвращал бы false. Тот же класс, что и
// разнобой типов id, — проверено подстановкой строк.
function прошедший(год,мес){
  const н=new Date(), тг=н.getFullYear(), тм=н.getMonth()+1;
  const г=+год, м=+мес;
  return г<тг || (г===тг && м<тм);
}
function текущийМесяц(год,мес){
  const н=new Date(); return +год===н.getFullYear() && +мес===н.getMonth()+1;
}
// Просрочено — запланированное на прошедшие месяцы и не отмеченное.
// Текущий месяц не в счёт: он ещё идёт.
function просрочено(год){
  const тг=new Date().getFullYear();
  if(год>тг) return [];
  const до = (год<тг) ? 12 : new Date().getMonth();
  const из=[];
  for(let м=1;м<=до;м++)
    работыМесяца(год,м).forEach(р=>{ if(!р.отм) из.push({мес:м, поз:р.поз, часы:р.часы}); });
  return из;
}

// Что по ППР приходится на текущий месяц — для пульта.
function ппрМесяца(){
  const н=new Date(), год=н.getFullYear(), мес=н.getMonth()+1;
  const р=работыМесяца(год,мес);
  const осталось=р.filter(x=>!x.отм);
  return {год, мес, имя:МЕСЯЦЫ[мес-1], всего:р.length,
          сделано:р.length-осталось.length, осталось:осталось.length,
          список:осталось};
}
