// Ширина колонки должностей — по САМОЙ ШИРОКОЙ строке в ней, а не всегда
// по максимуму. Левый край этой строки приходится на левую границу поля,
// остальные должности центрируются по её ширине. Предел — 8 см от левой
// границы листа: при листе 11906 твипов и левом поле 1559 это 2977 твипов.
//
// Ширину считать по числу букв нельзя: в Times New Roman «ш» шире «і» в
// несколько раз. Поэтому строка реально измеряется шрифтом документа
// через canvas — на машине, где документ и составляется, то есть настоящим
// Times New Roman.
// Предел — 8 см ШИРИНЫ колонки должностей. Сначала я понял «не более
// 8 см от левой границы листа» как «правый край колонки на 8 см от края
// листа», то есть 5,25 см ширины при левом поле 2,75 см. При таком пределе
// «Заместитель начальника ЛНК» (6,27 см) не помещался и переносился на
// вторую строку, хотя в 8 см укладывается свободно.
const ПРЕДЕЛ_ДОЛЖНОСТИ = 4536;      // 8 см
const ШИРИНА_ТЕКСТА    = 9071;      // 11906 − 1559 − 1276
