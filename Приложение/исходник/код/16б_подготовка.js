function имяСпец(сп){ return String(сп.вдок||сп.фио||"").trim(); }
// Назначенный исполнитель допущен? null — судить не по чему.
function допускИсполнителя(р){
  if(!р.исп || !р.методы.length) return null;
  const сп=специалистПоИмени(р.исп);
  if(!сп) return {ок:false, т:"нет в справочнике специалистов"};
  if(!аттестации(сп).length) return null;
  const нет=р.методы.map(м=>({м, к:допускКлетка(сп,м,р.срок)})).filter(x=>!x.к.ок);
  return нет.length?{ок:false, т:нет.map(x=>x.м+": "+x.к.т).join("; ")}:{ок:true, т:"допущен"};
}
