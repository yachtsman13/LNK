function правитьКомментарий(кид){
  const к=найтиПоИд(КОММ,кид); if(!к || !своёЗаписи(к,true)) return;
  const т=prompt("Комментарий:", к.текст||""); if(т===null) return;
  if(!т.trim()){ удалитьКомментарий(кид); return; }
  if(т.trim()===к.текст) return;
  const now=new Date().toISOString();
  к.текст=т.trim(); к.правлен=now; к.изменено=now; к.место=getWS().код;
  saveReg(REG_КОММ,КОММ); перерисоватьКомментарии(к.ид);
}
function удалитьКомментарий(кид){
  const к=найтиПоИд(КОММ,кид); if(!к || !своёЗаписи(к,true)) return;
  if(!confirm("Удалить комментарий?")) return;
  к.удалено=new Date().toISOString(); к.изменено=к.удалено;
  saveReg(REG_КОММ,КОММ); перерисоватьКомментарии(к.ид);
}
// Заметки задач до 3.88 (з.заметки — список внутри задачи) переносятся в
// комментарии без потерь. id выводится из задачи и номера заметки — у
// одной и той же заметки он одинаков на всех местах, поэтому перенос,
// сделанный каждым местом у себя, при обмене не двоится. Сами з.заметки
// не стираются (запись задачи не трогается — иначе это была бы её
// «правка»), просто больше не показываются; перенос повторяется при
// загрузке и после приёма обмена — заметка, дописанная старой версией,
// тоже переедет. Перенесённые не считаются «новыми».
function перенестиЗаметкиЗадач(){
  let н=0;
  (ЗАД||[]).forEach(з=>{
    if(!Array.isArray(з.заметки)) return;
    з.заметки.forEach((x,i)=>{
      const id="КМ-"+з.id+"-"+(i+1);
      if(КОММ.some(к=>к.id===id) || !String(x&&x.текст||"").trim()) return;
      КОММ.push({id, ид:String(з.id), текст:String(x.текст).trim(), автор:x.место||"", автор_ид:"", место:x.место||"",
        создано:(x.когда||"")+"T00:00:00", изменено:"", перенесено:1});
      н++;
    });
  });
  if(н) saveReg(REG_КОММ,КОММ);
  return н;
}

