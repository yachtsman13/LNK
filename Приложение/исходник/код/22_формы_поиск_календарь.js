// списка нет — это тот же расчёт, что у производных задач
// (производныеЗадачи), плюс свои задачи и окончание аттестаций по методам
// (их в задачах нет: там это «Прогноз аттестации»).
// Виды — день, неделя, месяц, квартал, год (просьба заказчика). Дела на
// одну дату — в порядке, указанном заказчиком: сначала работы по
// планам-графикам, затем задачи (по приоритету), затем прочие сроки, в
// конце обслуживание оборудования по ППР (ПОРЯДОК_ИСТОЧНИКОВ).
// Щелчок по дню — список дел этого дня, по делу — его карточка.
// Два состояния (3.91): раздел «Календарь сроков» (по умолчанию месяц) и
// календарь на пульте (по умолчанию неделя). Все функции календаря
// работают с «кал» — renderКалендарь переключает его по открытому виду.
// Отбор (типы, «только моё») — общий: помнится одной настройкой места.
const калКаленд={база:"", день:"", источник:"", вид:"месяц", типы:null, моё:false, ранее:false};
const калПульт={база:"", день:"", источник:"", вид:"неделя", типы:null, моё:false, ранее:false};
let кал=калКаленд;
const КАЛ_ВИДЫ=[["день","День"],["неделя","Неделя"],["месяц","Месяц"],["квартал","Квартал"],["год","Год"]];
// «Список» (повестка): дела недели по дням, без сетки — удобно на неделю и
// для печати листом. Период у него — неделя.
const КАЛ_ВИДЫ_КАЛ=КАЛ_ВИДЫ.concat([["список","Список"]]);
function периодВида(в){ return в==="список"?"неделя":(в||"месяц"); }
// Чем меньше — тем выше в списке дел одной даты. «План-график» — место
// под работы по планам-графикам (их в программе ещё нет: заказчик пришлёт
// образцы); неизвестный источник — между задачами и ППР.
const ПОРЯДОК_ИСТОЧНИКОВ={"План-график":0, "Внеплановые работы":0.5, "Задачи":1, "ППР":9};
function весДела(x){ const в=ПОРЯДОК_ИСТОЧНИКОВ[x.источник]; return в==null?5:в; }
function порядокДел(a,b){
  return String(a.срок).localeCompare(String(b.срок)) || весДела(a)-весДела(b) ||
    (a.приоритет==null?1:a.приоритет)-(b.приоритет==null?1:b.приоритет) ||
    String(a.что).localeCompare(String(b.что),"ru");
}
// Типы дел (3.90, п. 2 проработки, решено с заказчиком): шесть групп, по
// которым смотрят календарь. Внутри типа остаются подробные источники —
// по ним работают переход к карточке и порядок дел на дату. У каждого типа
// свой цвет (метка у дела и в легенде), отбор — флажками, несколько сразу.
const ТИПЫ_ДЕЛ=[["заметки","Заметки"],["мои","Мои задачи"],["общие","Общие задачи"],
  ["план","Работы по плану"],["внеплан","Внеплановые работы"],["сроки","Сроки"]];
function типДела(x){
  switch(x.источник){
    case "Заметки": return "заметки";
    case "Задачи": return x.моя?"мои":"общие";
    case "План-график": case "ППР": case "Представление на поверку": return "план";
    case "Внеплановые работы": return "внеплан";
    default: return "сроки";     // поверка (окончание), аттестация, ПБ, допуски, лаборатория
  }
}
// диап — [с, по] вместо периода: так считается «просрочено ранее».
function календарьДела(база, вид, диап){
  вид=вид||"месяц";
  const [с,по]=диап||границыПериода(вид, база);
  const из=производныеЗадачи(вид, база, [с,по]).map(x=>Object.assign({}, x));
  // работа плана-графика «моя» — если назначена вошедшему специалисту
  из.forEach(x=>{ if(x.источник==="План-график") x.моя=входВкл() && !!x.исп && яИсполнитель({исполнитель:x.исп}); });
  ЗАД.filter(з=>живаяЗадача(з) && з.срок && з.срок>=с && з.срок<=по).forEach(з=>из.push({
    ид:"ЗД|"+з.id, источник:"Задачи", что:з.что+(з.исполнитель?(" — "+з.исполнитель):""),
    срок:з.срок, сделано:з.статус==="выполнена"||з.статус==="закрыта", куда:"tasks",
    приоритет:весПриоритета(з), приоритетТ:приоритетЗадачи(з),
    моя:мояЗадача(з), статус:з.статус, нов:новыхКомментариев(з.id), постановщик:яПостановщик(з)}));
  // Заявки подразделений (3.89) — тип «Внеплановые работы», по сроку
  делаЗаявок(с,по).forEach(з=>из.push({ид:"ЗВ|"+з.id, источник:"Внеплановые работы",
    что:"Заявка "+(з.номер||"")+": "+заявкаКратко(з)+((з.методы||[]).length?" ("+з.методы.join(", ")+")":"")+(исполнительЗаявки(з)?" — "+исполнительЗаявки(з):""),
    срок:срокЗаявки(з), сделано:з.статус==="выполнена", куда:"requests", исп:исполнительЗаявки(з),
    моя:входВкл() && яИсполнитель({исполнитель:исполнительЗаявки(з)}), нов:новыхКомментариев(з.id)}));
  // Заметки со сроком (3.88) — те, что видны этому человеку (месту)
  видимыеЗаметки().filter(з=>з.срок && з.срок>=с && з.срок<=по).forEach(з=>из.push({
    ид:"ЗМ|"+з.id, источник:"Заметки", что:String(з.текст||"").split("\n")[0].slice(0,120)+(з.видимость==="всем"?"":" 🔒"),
    срок:з.срок, сделано:!!з.сделано, когда:з.сделано||"", куда:"tasks", моя:своёЗаписи(з)}));
  live(P).forEach(c=>аттестации(c).forEach(а=>{
    if(!а.до || а.до<с || а.до>по) return;
    из.push({ид:"АТТ|"+c.id+"|"+а.метод+"|"+а.до, источник:"Аттестация",
      что:"Истекает аттестация "+[а.метод,а.уровень].filter(Boolean).join(" ")+": "+(c.вдок||c.фио),
      срок:а.до, сделано:false, куда:"people"});
  }));
  // Представление на поверку (3.90) — работа по плану: месяц представления
  // (тот же, что в заявке и плане-графике поверки: расчёт от даты окончания
  // или вписанный руками), срок — последний день месяца. Сделано — когда в
  // карточке дата поверки не раньше этого месяца (прибор поверен заново).
  const гС=Math.max(+с.slice(0,4), new Date().getFullYear()-3), гП=+по.slice(0,4);
  приборыДляЗаявки().forEach(п=>{
    for(let г=гС; г<=гП; г++){
      const мi=МЕСЯЦЫ.indexOf(месяцПрибора(п,г)); if(мi<0) continue;
      const ym=г+"-"+String(мi+1).padStart(2,"0"), срок=ymПосл(ym);
      if(срок<с || срок>по) continue;
      const сд=!!п.поверка_дата && п.поверка_дата>=ym+"-01";
      из.push({ид:"ПРЕДСТ|"+п.id+"|"+ym, источник:"Представление на поверку",
        что:"Представить на поверку: "+имяПрибораДок(п)+(п.зав?(", зав. № "+п.зав):""),
        срок, сделано:сд, когда:сд?п.поверка_дата:"", куда:"si"});
    }
  });
  из.forEach(x=>{ x.тип=типДела(x); });
  return из.sort(порядокДел);
}
