// Коды мест для выбора: М1…М6, своё место, места из файлов обмена и уже
// вписанные у специалистов и в задачах (иначе выбранное раньше пропало бы
// из списка и стёрлось при сохранении карточки).
function кодыМестДляВыбора(){
  const н=new Set(КОДЫ_МЕСТ);
  try{ н.add(getWS().код); }catch(e){}
  try{ занятыеМеста().forEach(к=>н.add(к)); }catch(e){}
  live(P).forEach(p=>{ if(p.рабочее_место) н.add(String(p.рабочее_место).trim()); });
  (typeof ЗАД!=="undefined"?ЗАД:[]).forEach(з=>{ if(з.место) н.add(String(з.место).trim()); });
  return [...н].filter(Boolean).sort((a,b)=>a.localeCompare(b,"ru",{numeric:true}));
}
function мояЗадача(з){ return !!кодМеста(з.место) && кодМеста(з.место)===кодМеста(getWS().код); }
function задачиМоегоМеста(){
  const я=кодМеста(getWS().код), поСроку=(a,b)=>String(a.срок||"9").localeCompare(String(b.срок||"9"));
  const живые=(ЗАД||[]).filter(живаяЗадача);
  const исполнить=живые.filter(з=>мояЗадача(з) && МОИ_ИСПОЛНИТЬ.indexOf(з.статус)>=0).sort(поСроку);
  const проверить=живые.filter(з=>з.статус==="выполнена" && кодМеста(ставитель(з))===я).sort(поСроку);
  return {исполнить, проверить, всего:исполнить.length+проверить.length,
    просрочено:исполнить.filter(просроченаЗадача).length,
    вернули:исполнить.filter(з=>з.статус==="доработка").length,
    новых:исполнить.filter(з=>з.статус==="назначена").length};
}
