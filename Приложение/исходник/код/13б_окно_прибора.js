// Работы ППР по прибору в году: позиции плана, связанные номером карточки.
function ппрПрибора(п, год){
  const мои=карточкиПозиции(п.карточка)||[]; if(!мои.length) return [];
  return позицииППР().filter(поз=>(карточкиПозиции(поз.карточка)||[]).some(н=>мои.indexOf(н)>=0)).map(поз=>{
    const мес=Object.keys((поз.план||{})[год]||{}).map(Number).sort((a,b)=>a-b).map(м=>{
      const о=отметка(поз,год,м);
      return {м, о, просрочено:!о && прошедший(год,м)};
    });
    const все=live(ОТМ).filter(о=>String(о.поз||"")===String(поз.id) || String(о.id).indexOf(поз.id+"|")===0);
    const посл=все.map(о=>о.выполнено||"").filter(Boolean).sort().pop()||"";
    return {поз, мес, посл};
  });
}
