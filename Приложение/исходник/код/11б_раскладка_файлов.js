// ── Узнать файл по имени ──────────────────────────────────────
// Форматы, кроме свидетельства о поверке, — моё предложение, одобренное
// заказчиком (ТЗ/Проработка_папки_НОАЛ.md, п. 2).
const РЕ_ПУНКТ=/^(\d{1,2}(?:\.\d{1,2})?)\.?\s+(.*)$/;
const РЕ_УДОСТ=/^удостоверение\s+(.+?)\s*№\s*(.+?)(?:\s+от\s+(\d{1,2})[.\-_](\d{1,2})[.\-_](\d{4}))?$/i;
const РЕ_ПБ=/^пб\s+(.+?)(?:\s*№\s*(.+))?$/i;
const РЕ_А1=/^[аa]\.?\s?1(?=[\s.]|$)\.?\s*(.*)$/i;
const РЕ_СВИДЛНК=/^свидетельство\s+(?:лнк|об\s+аттестации(?:\s+лнк)?)(?=[\s,.№]|$)(.*)$/i;
const РЕ_ПРОТ=/^(?:протокол|заключение|акт)\s+(?:№\s*)?(\d+)-(\d{4})-([А-ЯЁA-Zа-яё]+)/i;
function пунктИзИмени(н, т){
  if(н==="3.5"){
    if(/поверк|калибр/i.test(т)) return "3.5п";
    if(/обслуживан|техническ/i.test(т) || /(^|\s)(ТО|ППР)(?=[\s\-\d]|$)/.test(т)) return "3.5т";
    return "";
  }
  return пунктНОАЛ(н)?н:"";
}
function распознатьФайл(имя){
  const б=безРасширения(имя).replace(/\s+/g," ").trim();
  let м;
  if((м=РЕ_ПУНКТ.exec(б))){
    if(м[1]==="3.5" || пунктНОАЛ(м[1])) return {тип:"пункт", н:м[1], к:пунктИзИмени(м[1], м[2])};
  }
  const пов=разобратьИмяПоверки(имя); if(пов) return Object.assign({тип:"поверка"}, пов);
  if((м=РЕ_УДОСТ.exec(б))) return {тип:"удост", кто:м[1].trim(), номер:чистыйНомер(м[2]), дата:м[3]?датаИз(+м[5],+м[4],+м[3]):""};
  if((м=РЕ_ПБ.exec(б))) return {тип:"пб", кто:м[1].trim(), номер:чистыйНомер(м[2]||"")};
  if((м=РЕ_А1.exec(б))) return {тип:"а1", кто:м[1].trim()};
  if((м=РЕ_СВИДЛНК.exec(б))) return {тип:"свид", ост:м[1]};
  if((м=РЕ_ПРОТ.exec(б))) return {тип:"прот", н:+м[1], г:м[2], м:м[3].toUpperCase()};
  const д=разобратьИмяДокаСИ(имя); if(д) return Object.assign({тип:"докСИ"}, д);
  return null;
}
