// «Раз в месяц сверять журнал с архивом» — заводить двенадцать раз незачем.
// Следующая задача с тем же текстом и сдвинутым сроком появляется по
// расписанию (догнатьПовторы) и при приёме работы (продолжитьПовтор).
const ПОВТОРЫ=[["","не повторять"],["неделя","каждую неделю"],["месяц","каждый месяц"],
               ["квартал","каждый квартал"],["полугодие","каждое полугодие"],["год","каждый год"]];
function сдвинутьДату(дата, шаг){
  const d=new Date(дата+"T00:00:00");
  if(шаг==="неделя")         d.setDate(d.getDate()+7);
  else if(шаг==="месяц")     d.setMonth(d.getMonth()+1);
  else if(шаг==="квартал")   d.setMonth(d.getMonth()+3);
  else if(шаг==="полугодие") d.setMonth(d.getMonth()+6);
  else if(шаг==="год")       d.setFullYear(d.getFullYear()+1);
  else return "";
  return new Date(Date.UTC(d.getFullYear(),d.getMonth(),d.getDate())).toISOString().slice(0,10);
}
// Срок по расписанию: перенос срока одной задачи расписание серии не
// сдвигает (иначе «каждую пятницу» после одного переноса на понедельник
// навсегда уехало бы на понедельник).
function срокПоРасписанию(з){ return з.срок_первый||з.срок||""; }
function корень(з){ return з.родитель||з.id; }
// Следующая задача серии. id не случайный, а из корня серии и срока:
// следующую создают и сама программа (догон по расписанию), и приём
// работы, причём на любом рабочем месте, — с одинаковым id обмен сольёт
// их в одну, а не заведёт две «подготовки итогов» на одну неделю.
function новаяВСерии(обр, срок){
  const ид=корень(обр)+"~"+срок;
  if(ЗАД.some(x=>x.id===ид || (корень(x)===корень(обр) && срокПоРасписанию(x)===срок))) return null;
  const нов=Object.assign({}, обр, {
    id:ид, срок:срок, статус:"назначена",
    родитель:корень(обр),
    принято:"", выполнено:"", проверено:"", причина_возврата:"",
    срок_первый:"", переносы:[], заметки:[],
    создано:new Date().toISOString(), изменено:new Date().toISOString(),
    место_правки:getWS().код, удалено:""
  });
  delete нов.база;
  ЗАД.push(нов);
  return нов;
}
function продолжитьПовтор(з){
  if(!з.повтор || !срокПоРасписанию(з)) return null;
  const след=сдвинутьДату(срокПоРасписанию(з), з.повтор);
  if(!след) return null;
  if(з.повтор_до && след>з.повтор_до) return null;
  const нов=новаяВСерии(з, след);
  if(нов) saveReg(REG_ЗАД,ЗАД);
  return нов;
}
// Догон по расписанию. Раньше следующая задача серии появлялась только
// когда ПРИНИМАЛИ предыдущую: не подвели итоги недели — новых «итогов
// недели» не было вовсе, серия стояла (замечание заказчика). Теперь у
// каждой серии всегда есть задача с ещё не прошедшим сроком: прошёл срок
// последней — заводится следующая, сделана прежняя или нет. Невыполненная
// остаётся просроченной сама по себе, её никто не закрывает и не двигает.
// Пропущенные периоды (программу не открывали месяц) заводятся каждый
// своей задачей — каждый такой период и правда не отработан.
// Образец следующей — последняя по сроку НЕудалённая задача серии: снять у
// неё «Повторять» — серия остановится. Удалённая задача серии — пропуск
// одного раза: её срок считается занятым, заново она не появится.
function догнатьПовторы(){
  const сегодня=new Date().toISOString().slice(0,10), серии={};
  ЗАД.forEach(x=>{ (серии[корень(x)]=серии[корень(x)]||[]).push(x); });
  let создано=0;
  Object.values(серии).forEach(сп=>{
    const живые=сп.filter(x=>!x.удалено); if(!живые.length) return;
    const по=(a,b)=>срокПоРасписанию(a)<срокПоРасписанию(b)?-1:1;
    const обр=живые.slice().sort(по).pop();
    if(!обр.повтор) return;
    let посл=сп.map(срокПоРасписанию).filter(Boolean).sort().pop();
    for(let i=0; посл && посл<сегодня && i<120; i++){
      const след=сдвинутьДату(посл, обр.повтор);
      if(!след || (обр.повтор_до && след>обр.повтор_до)) break;
      if(новаяВСерии(обр, след)) создано++;
      посл=след;
    }
  });
  if(создано) saveReg(REG_ЗАД,ЗАД);
  return создано;
}

