      да(к.рЛаб && к.рЛаб.some(x => x.поле === "Телефон" && x.осталось === "222-22" && x.отброшено === "111-11"),
        "разница по карточке лаборатории — поле «Телефон» с обоими значениями", JSON.stringify(к.рЛаб));
