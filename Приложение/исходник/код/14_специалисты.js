// Единица счёта — «метод в записи журнала»: запись, где один человек
// сделал ВИК и УЗТ, — две работы; отдельно показано, во скольких
// записях он участвовал. Период — по дате контроля записи; запись без
// даты в период не попадает (их число показано, не пропадают молча).
// Отчёт внутренний: формы такого отчёта у заказчика не было, поэтому он
// не выдаётся за официальный документ.
const нагрузка={год:new Date().getFullYear(), период:"год"};
function периодНагрузки(год,период){
  const г=String(год);
  if(период==="год") return [г+"-01-01", г+"-12-31"];
  const посл=(м)=>new Date(Date.UTC(+год,м,0)).toISOString().slice(0,10);
  const пп=м=>String(м).padStart(2,"0");
  if(/^к[1-4]$/.test(период)){ const к=+период[1], с=(к-1)*3+1; return [г+"-"+пп(с)+"-01", посл(с+2)]; }
  if(/^м\d{1,2}$/.test(период)){ const м=+период.slice(1); return [г+"-"+пп(м)+"-01", посл(м)]; }
  return [г+"-01-01", г+"-12-31"];
}
function подписьПериодаНагрузки(год,период){
  if(период==="год") return год+" год";
  if(период[0]==="к") return ["I","II","III","IV"][+период[1]-1]+" квартал "+год+" г.";
  return МЕСЯЦЫ[+период.slice(1)-1]+" "+год+" г.";
}
function нагрузкаСводка(год,период){
  const [с,по]=периодНагрузки(год,период);
  const ряды={}, методы=new Set(); let безДаты=0;
  liveJ().forEach(z=>{
    const мм=methodsOf(z); if(!мм.length) return;
    if(!z.дата){ безДаты++; return; }
    if(z.дата<с || z.дата>по) return;
    const вЗаписи=new Set();
    мм.forEach(м=>{
      const и=String((z.методы[м]||{}).исп||"").trim()||"(без исполнителя)";
      const р=ряды[и]=ряды[и]||{исп:и, поМетодам:{}, работ:0, записей:0};
      р.поМетодам[м]=(р.поМетодам[м]||0)+1; р.работ++; методы.add(м);
      вЗаписи.add(и);
    });
    вЗаписи.forEach(и=>ряды[и].записей++);
  });
  const список=Object.values(ряды).map(р=>{
    const сп=р.исп==="(без исполнителя)"?null:специалистПоИмени(р.исп);
    return Object.assign(р,{спец:сп});
  }).sort((a,b)=>b.работ-a.работ || a.исп.localeCompare(b.исп,"ru"));
  const порядок=METHODS.filter(м=>методы.has(м)).concat([...методы].filter(м=>METHODS.indexOf(м)<0));
  return {ряды:список, методы:порядок, безДаты, с, по,
    всего:список.reduce((n,р)=>n+р.работ,0)};
}
