# -*- coding: utf-8 -*-
"""Планы-графики заказчика → Приложение/планы.json (вшивается в ЛНК.html).

Источник — три книги из ТЗ/образцы, присланные заказчиком:
  План-график ВД 2027.xlsx       (вибродиагностический контроль, 186 строк)
  План-график ТК 2026-2027.xlsx  (тепловой контроль, 17 строк)
  План-график НК 2027.xlsx       (неразрушающий контроль, 54 строки)

Ничего не досочиняется: значения берутся из ячеек как есть (у формул —
сохранённое Excel значение). Отметки месяцев «+» в плане ВД — формулы от
периодичности (столбец T, доля года) и месяца первого измерения (U);
скрипт пересчитывает их тем же правилом и останавливается, если хоть
одна строка не сходится, — значит, файл устроен иначе, чем я понял.

id позиций и карточек вибрации постоянные («ПГП-ВД-2027-001»,
«ВК-ВД27-001») — одинаковы на всех рабочих местах, обмен их не двоит.

Запуск:  python3 scripts/export_pg.py
"""
import io, json, os, re, sys, datetime
import openpyxl

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ОБРАЗЦЫ = os.path.join(ROOT, "ТЗ", "образцы")
ИТОГ = os.path.join(ROOT, "Приложение", "планы.json")
МЕСЯЦЫ = ["январь", "февраль", "март", "апрель", "май", "июнь", "июль",
          "август", "сентябрь", "октябрь", "ноябрь", "декабрь"]

# Вид оборудования в родительном падеже — для заголовка карточки
# («Карточка учёта вибрации электровентилятора»). Падежи программа сама
# не склоняет; здесь — закрытый список ровно тех пяти начал наименования,
# что встречаются в плане ВД 2027. Другое начало — поле остаётся пустым.
РОДИТЕЛЬНЫЙ = [("Электровентилятор", "электровентилятора"),
               ("Электронасосный агрегат", "электронасосного агрегата"),
               ("Вентиляционная установка", "вентиляционной установки"),
               ("Вентилятор", "вентилятора"),
               ("Насос", "насоса")]


def текст(v):
    """Значение ячейки строкой, как его видно в Excel; пусто — ''."""
    if v is None:
        return ""
    if isinstance(v, float):
        if v.is_integer():
            return str(int(v))
        return ("%s" % v).replace(".", ",")
    if isinstance(v, (datetime.datetime, datetime.date)):
        return v.strftime("%Y-%m-%d")
    return str(v).strip()


def одной_строкой(т):
    return re.sub(r"\s+", " ", т).strip()


def книга(имя):
    п = os.path.join(ОБРАЗЦЫ, имя)
    if not os.path.exists(п):
        raise SystemExit("Нет файла: %s" % п)
    return openpyxl.load_workbook(п, data_only=True).active


def колонки_шапки(ws, ряд):
    """Заголовок → номер столбца. Повтор заголовка берётся ПЕРВЫЙ: в плане
    ВД месяцы стоят дважды — отметки (E…P) и трудозатраты по месяцам
    (AF…AQ)."""
    ш = {}
    for к in range(1, ws.max_column + 1):
        v = ws.cell(ряд, к).value
        if v is None:
            continue
        з = v.strip() if isinstance(v, str) else v
        ш.setdefault(з, к)
    return ш


def месяцы_по_правилу(доля, первый):
    """Правило формул книги ВД: первый месяц, затем шаг round(доля*12)."""
    шаг = int(round(доля * 12))
    if not шаг or not первый:
        return []
    из, м = [], int(первый)
    while м <= 12:
        из.append(м)
        м += шаг
    return из


def план_вд():
    ws = книга("План-график ВД 2027.xlsx")
    год = int(re.search(r"(\d{4})", ws["A2"].value).group(1))
    ш = колонки_шапки(ws, 4)
    мес_кол = [ш[М.capitalize()] for М in МЕСЯЦЫ]   # «Декабрь2/3» — служебные, не берём
    пг = "ПГ-ВД-%d" % год
    позиции, карты = [], []
    # № п/п в книге — формула =SUBTOTAL(103,$B$6:Bn), то есть порядковый
    # номер строки с наименованием. В трёх строках она сбита (в 147-й
    # ссылается на B159 и даёт 154, в 164-й и 165-й вместо формулы вписаны
    # числа 28 и 30) — номера повторяются. Берём то, что считает формула:
    # порядок строки; расхождения печатаются, заказчику сказано.
    нп = 0
    for р in range(6, ws.max_row + 1):
        наим_сыр = текст(ws.cell(р, ш["Наименование технических средств"]).value)
        if not наим_сыр:
            continue
        нп += 1
        в_книге = ws.cell(р, ш["№ п/п"]).value
        if в_книге != нп:
            print("ВД, строка %d: в книге № %s, по порядку %d" % (р, в_книге, нп))
        доля = float(ws.cell(р, ш["Периодичность2"]).value)
        первый = int(ws.cell(р, ш["Месяц первого измерения"]).value)
        плюсы = [i + 1 for i, к in enumerate(мес_кол) if текст(ws.cell(р, к).value) == "+"]
        if плюсы != месяцы_по_правилу(доля, первый):
            raise SystemExit("ВД, строка %d: «+» %s не сходятся с правилом %s" %
                             (р, плюсы, месяцы_по_правилу(доля, первый)))
        н = "%03d" % int(нп)
        кид = "ВК-ВД%02d-%s" % (год % 100, н)
        наим = одной_строкой(наим_сыр)
        # В карточке вид стоит в заголовке («Карточка учёта вибрации
        # электровентилятора»), поэтому наименование — без него: «ВМ 40/750».
        вид, тип = "", наим
        for нач, род in РОДИТЕЛЬНЫЙ:
            if наим.startswith(нач) and наим[len(нач):].strip():
                вид, тип = род, наим[len(нач):].strip()
                break
        тех = lambda заг: текст(ws.cell(р, ш[заг]).value)
        карты.append({
            "id": кид, "номер": str(int(нп)), "вид": вид, "наименование": тип,
            "подразделение": "", "изготовитель": тех("Данные о производителе"),
            "год_выпуска": тех("Год выпуска"), "мощность": тех("Мощность, кВт"),
            "подшипники": тех("Количество и тип подшипников"),
            "лопасти": тех("Количество лопастей рабочих колес"),
            "колёса": тех("Количество рабочих колес"),
            "обороты": тех("f вращения вала ЭД"),
            "обороты_рк": тех("f вращения вала рабочего колеса"),
            "моточасы": тех("Количество моточасов")})
        позиции.append({
            "id": "ПГП-ВД-%d-%s" % (год, н), "пг": пг, "нп": int(нп),
            "наименование": наим, "подразделение": "", "количество": "",
            "доля": доля, "мес_первый": первый,
            "трудозатраты": тех("Трудозатраты"), "причина": тех("Причина"),
            "карта_ид": кид,
            "месяцы": {"%d-%02d" % (год, м): "" for м in плюсы}})
    график = {"id": пг, "вид": "ВД", "с": "%d-01" % год, "по": "%d-12" % год,
              "источник": "План-график ВД %d.xlsx" % год}
    return график, позиции, карты


def план_тк():
    ws = книга("План-график ТК 2026-2027.xlsx")
    # Год над месяцами — объединённая ячейка во 2-й строке («2026 г.» над
    # ноябрём и декабрём); месяц справа от неё берёт её год.
    ш = колонки_шапки(ws, 3)
    столбцы = []
    год = None
    for к in range(1, ws.max_column + 1):
        г = ws.cell(2, к).value
        if isinstance(г, str) and re.search(r"\d{4}", г):
            год = int(re.search(r"(\d{4})", г).group(1))
        загол = ws.cell(3, к).value
        if isinstance(загол, str) and загол.strip().lower() in МЕСЯЦЫ:
            if год is None:
                raise SystemExit("ТК: у месяца в столбце %d нет года" % к)
            столбцы.append((к, "%d-%02d" % (год, МЕСЯЦЫ.index(загол.strip().lower()) + 1)))
    с, по = столбцы[0][1], столбцы[-1][1]
    пг = "ПГ-ТК-%s" % с[:4]
    позиции = []
    for р in range(5, ws.max_row + 1):
        нп = ws.cell(р, ш["№ п/п"]).value
        if нп is None:
            continue
        позиции.append({
            "id": "ПГП-ТК-%s-%03d" % (с[:4], int(нп)), "пг": пг, "нп": int(нп),
            "наименование": одной_строкой(текст(ws.cell(р, ш["Наименованиеобъекта контроля"]).value)),
            "подразделение": "", "количество": текст(ws.cell(р, ш["Количество"]).value),
            "месяцы": {ym: "" for к, ym in столбцы if текст(ws.cell(р, к).value) == "+"}})
    return {"id": пг, "вид": "ТК", "с": с, "по": по,
            "источник": "План-график ТК 2026-2027.xlsx"}, позиции


def план_нк():
    ws = книга("План-график НК 2027.xlsx")
    год = int(re.search(r"на (\d{4}) г", ws["B1"].value).group(1))
    ш = колонки_шапки(ws, 3)
    мес_кол = [ш[М.capitalize()] for М in МЕСЯЦЫ]
    кол_мет = [к for з, к in ш.items() if isinstance(з, str) and з.startswith("Методы контроля")][0]
    пг = "ПГ-НК-%d" % год
    позиции = []
    for р in range(5, ws.max_row + 1):
        нп = ws.cell(р, ш["№ п/п"]).value
        if нп is None:
            continue
        позиции.append({
            "id": "ПГП-НК-%d-%03d" % (год, int(нп)), "пг": пг, "нп": int(нп),
            "наименование": одной_строкой(текст(ws.cell(р, ш["Наименование и тип объекта контроля"]).value)),
            "подразделение": "", "методы": текст(ws.cell(р, кол_мет).value),
            "количество": текст(ws.cell(р, ш["Количество"]).value),
            # обычно дата; у одной строки книги 2027 там текст — как есть
            "срок_службы": одной_строкой(текст(ws.cell(р, ш["Дата окончания срока службы"]).value)),
            "примечание": одной_строкой(текст(ws.cell(р, ш["Примечание"]).value)),
            "месяцы": {"%d-%02d" % (год, i + 1): "" for i, к in enumerate(мес_кол)
                       if текст(ws.cell(р, к).value) == "+"}})
    return {"id": пг, "вид": "НК", "с": "%d-01" % год, "по": "%d-12" % год,
            "источник": "План-график НК %d.xlsx" % год}, позиции


def main():
    гвд, пвд, карты = план_вд()
    гтк, птк = план_тк()
    гнк, пнк = план_нк()
    д = {"графики": [гвд, гтк, гнк], "позиции": пвд + птк + пнк, "карты": карты}
    with io.open(ИТОГ, "w", encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False, indent=0)
    for г, п in ((гвд, пвд), (гтк, птк), (гнк, пнк)):
        print("%s %s…%s: позиций %d, работ %d" % (г["вид"], г["с"], г["по"], len(п),
              sum(len(x["месяцы"]) for x in п)))
    print("карточек вибрации: %d → %s" % (len(карты), ИТОГ))
    return 0


if __name__ == "__main__":
    sys.exit(main())
