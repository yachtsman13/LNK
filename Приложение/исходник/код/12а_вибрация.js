// Оценка одного значения: "прев" — выше максимального, "пред" — выше
// предупредительного, "" — в норме или сравнивать не с чем.
function оценкаV(v, п){
  if(v==null || isNaN(v)) return "";
  if(п.предел && v>п.предел.v) return "прев";
  if(п.пред && v>п.пред.v) return "пред";
  return "";
}
function оценкаA(a, п){ return (a!=null && !isNaN(a) && п.уск && a>п.уск.v) ? "прев" : ""; }
