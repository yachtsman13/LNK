// Дата окончания поверки: дата + N месяцев − 1 день. Если такого числа в
// месяце нет (31-е, 29 февраля), годовщиной считается 1-е число
// следующего месяца — значит, действует по последний день месяца
// (моё правило для крайнего случая: в примере заказчика его нет).
function поверкаДоРасчёт(дата, мес){
  const m=/^(\d{4})-(\d{2})-(\d{2})$/.exec(String(дата||""));
  const н=parseInt(String(мес==null?"":мес).replace(/[^0-9]/g,""),10);
  if(!m || !(н>0) || +m[1]<1900) return "";
  const всего=(+m[1])*12+(+m[2]-1)+н, г=Math.floor(всего/12), мс=всего%12;
  const днейВМесяце=new Date(Date.UTC(г,мс+1,0)).getUTCDate();
  const год=(+m[3]<=днейВМесяце) ? new Date(Date.UTC(г,мс,+m[3])) : new Date(Date.UTC(г,мс+1,1));
  год.setUTCDate(год.getUTCDate()-1);
  return год.toISOString().slice(0,10);
}
// Пересчёт «до» — при каждой смене даты поверки или интервала (новая
// поверка — новая дата окончания). Поправленное руками «до» остаётся, пока
// не изменят дату или интервал. Интервал не вписан — берётся тот, что
// выходил из прежней пары дат этой карточки (подсказка в поле).
function поверкаДоПересчёт(){
  const д=document.getElementById("rf_поверка_дата"), п=document.getElementById("rf_периодичность"),
        до=document.getElementById("rf_поверка_до");
  if(!д||!п||!до||до.readOnly) return;
  const расч=поверкаДоРасчёт(д.value, п.value||п.getAttribute("data-по-датам")||"");
  if(!расч) return;   // неполная дата (ещё печатают год) или нет интервала — не трогаю
  if(до.value!==расч){ до.value=расч; до.dispatchEvent(new Event("input",{bubbles:true})); }
}
