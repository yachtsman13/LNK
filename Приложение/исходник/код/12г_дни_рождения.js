// ── Расчёт ─────────────────────────────────────────────────
function високосный(г){ return (г%4===0 && г%100!==0) || г%400===0; }
// День рождения в данном году: «ГГГГ-ММ-ДД» (год рождения не важен).
function деньРожденияВГоду(iso, год){
  const м=/^\d{4}-(\d{2})-(\d{2})$/.exec(String(iso||"")); if(!м) return "";
  const д=(м[1]==="02" && м[2]==="29" && !високосный(год)) ? "28" : м[2];
  return год+"-"+м[1]+"-"+д;
}
function числоМесяц(iso){
  const м=/^\d{4}-(\d{2})-(\d{2})$/.exec(String(iso||"")); if(!м) return "";
  return (+м[2])+" "+МЕСЯЦЫ_РОД[+м[1]-1];
}
// Все, у кого внесена дата рождения: специалисты ЛНК и контакты.
function людиСДнёмРождения(){
  return live(P).filter(p=>p.дата_рождения).map(p=>({вид:"ppl", id:p.id, фио:p.фио||p.вдок||"",
      должность:p.должность||"", где:"ЛНК", дата:p.дата_рождения}))
    .concat(live(КОНТ).filter(к=>к.дата_рождения).map(к=>({вид:"kont", id:к.id, фио:к.фио||"",
      должность:к.должность||"", где:к.подразделение||"смежное подразделение", дата:к.дата_рождения})));
}
// Дни рождения с с по по (включительно). Прошедшие — «сделано», чтобы не
// считаться просроченными; годы раньше прошлого не перебираются (туда
// календарь заглядывает только за просроченным, а здесь его не бывает).
function днейРожденияВПериоде(с, по){
  const из=[], сег=сегодняМестн();
  const гС=Math.max(+String(с).slice(0,4), new Date().getFullYear()-1), гП=+String(по).slice(0,4);
  людиСДнёмРождения().forEach(ч=>{
    for(let г=гС; г<=гП; г++){
      const д=деньРожденияВГоду(ч.дата, г); if(!д || д<с || д>по) continue;
      из.push({ид:"ДР|"+ч.вид+"|"+ч.id+"|"+д, источник:"Дни рождения", событие:true,
        что:"🎂 День рождения: "+ч.фио+" ("+[ч.где, ч.должность].filter(Boolean).join(", ")+")",
        срок:д, сделано:д<сег, куда:ч.вид==="ppl"?"people":"podr", фио:ч.фио, где:ч.где});
    }
  });
  return из;
}
