async function хешПароля(пароль,соль,итерации){
  const enc=new TextEncoder();
  const ключ=await crypto.subtle.importKey("raw",enc.encode(String(пароль)),"PBKDF2",false,["deriveBits"]);
  const б=await crypto.subtle.deriveBits({name:"PBKDF2",salt:enc.encode(соль),
    iterations:итерации||ПАРОЛЬ_ИТЕРАЦИЙ,hash:"SHA-256"},ключ,256);
  return [...new Uint8Array(б)].map(x=>x.toString(16).padStart(2,"0")).join("");
}
function новаяСоль(){ return [...crypto.getRandomValues(new Uint8Array(16))].map(x=>x.toString(16).padStart(2,"0")).join(""); }
function ошибкаПароля(пароль){
  const п=String(пароль||"");
  if(п.length<ПАРОЛЬ_МИН) return "Пароль — не меньше "+ПАРОЛЬ_МИН+" знаков";
  if(п.length>ПАРОЛЬ_МАКС) return "Пароль — не больше "+ПАРОЛЬ_МАКС+" знаков";
  if(/^(.)\1+$/.test(п)) return "Пароль не должен состоять из повторов одного знака";
  const н=п.toLowerCase().replace(/\s+/g,"");
  const слабые=["123456789012","1234567890123","qwerty123456","qwertyuiop12","password1234",
    "password12345","пароль123456","пароль1234567","admin1234567","administrator","111111111111",
    "йцукенгшщзхъ","фываолджэ12","abcdefghijkl","abcdefgh1234"];
  if(слабые.indexOf(н)>=0||/^(?:0123456789|1234567890)+$/.test(н))
    return "Этот пароль слишком предсказуем — задайте другой";
  return "";
}
