// Замечания уровней «внимание» и «наблюдение» бывают нормой (две записи
// по одному баку, у которого двойник под той же строкой; объект без
// подразделения, которое у вас не ведётся). Разобранное и признанное
// верным мешает видеть новое — поэтому его можно убрать в свёрнутый блок.
// Принятие привязано к СОСТАВУ замечания: теме, тексту (в нём число) и
// строкам подробностей. Изменился состав — например, появилась ещё одна
// такая запись — отпечаток другой, и замечание возвращается само.
// Ошибки так не убираются: «так быть не может» по определению.
// Хранится у этого места (в обмен не идёт): что принято на одном месте,
// на другом могут ещё не видеть.
const REG_ПРИНЯТО="lnk_check_ok";
function принятыеПроверки(){ try{ return JSON.parse(ХР.getItem(REG_ПРИНЯТО)||"{}")||{}; }catch(e){ return {}; } }
function сохранитьПринятые(о){ try{ ХР.setItem(REG_ПРИНЯТО,JSON.stringify(о)); }catch(e){ toast("Не удалось сохранить: память браузера недоступна"); } }
function отпечатокПроверки(x){
  const с=[x.ур,x.тема,x.текст].concat((x.подробно||[]).map(t=>typeof t==="string"?t:t.т)).join("\u0001");
  let h=5381; for(let i=0;i<с.length;i++) h=((h*33)^с.charCodeAt(i))>>>0;
  return h.toString(36)+"-"+с.length.toString(36);
}
function проверкиРазобрать(){
  const пр=принятыеПроверки(), все=проверки(), действ=[], принятые=[];
  все.forEach(x=>{ x.отп=отпечатокПроверки(x);
    if(x.ур!=="ошибка" && пр[x.отп]){ x.принято=пр[x.отп]; принятые.push(x); } else действ.push(x); });
  return {действ, принятые, пр};
}
function проверкиДействующие(){ return проверкиРазобрать().действ; }
function принятьПроверку(отп){
  const x=проверки().find(y=>отпечатокПроверки(y)===отп); if(!x || x.ур==="ошибка") return;
  // Принятия, чьих замечаний уже нет, убираю: иначе они копились бы.
  const живые=new Set(проверки().map(отпечатокПроверки)), пр=принятыеПроверки();
  Object.keys(пр).forEach(k=>{ if(!живые.has(k)) delete пр[k]; });
  пр[отп]={когда:new Date().toISOString(), место:getWS().код, тема:x.тема, текст:x.текст};
  сохранитьПринятые(пр); renderCheck(); setChrome();
  toast("Принято. Изменится состав замечания — оно вернётся само");
}
function вернутьПроверку(отп){
  const пр=принятыеПроверки(); delete пр[отп]; сохранитьПринятые(пр); renderCheck(); setChrome();
}

