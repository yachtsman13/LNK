// ── Файлы документов на всех местах (3.76, п. 11 списка задач) ──
// Сеть между местами есть не всегда, поэтому у каждого места СВОЯ
// локальная папка с документами, а недостающие файлы переезжают на
// флешке вместе с файлом обмена (подпапка «Файлы ЛНК» рядом с ним).
// Решение заказчика: схема — эта; старая версия файла, заменённая новой,
// уходит в подпапку «Заменённые»; у файлов, прикреплённых раньше,
// отпечаток берётся при первой проверке с того места, где файл нашёлся,
// а разные файлы под одним именем на разных местах показываются на
// решение (программа сама не выбирает).
//
// Как отличить «не тот файл»: при прикреплении и при проверке программа
// запоминает размер и отпечаток содержимого (SHA-256). Реестр ФАЙЛЫ —
// ДАННЫЕ: по записи на путь файла (id — путь в нижнем регистре: Windows
// имён по регистру не различает), с верной версией; ходит в обмене и в
// копии. Что лежит в СВОЕЙ папке — настройка места (lnk_files_local), что
// лежит у других мест — из их файлов обмена (lnk_files_places).
