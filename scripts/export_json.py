# -*- coding: utf-8 -*-
"""Выгрузка книги данных в JSON для браузерного приложения.

Книга собирается openpyxl, а он формулы пишет, но не считает: у формульных
ячеек нет сохранённого результата, и прочитать его нельзя ничем — там пусто
в самом файле. Поэтому те несколько полей, что в книге считаются формулой
(год, заводской и регистрационный номера объекта, порядковый номер),
здесь считаются заново на Python — по тем же правилам, что и в книге.

Запуск:  python3 scripts/export_json.py
Итог:    Приложение/данные.json
"""
import io, json, os, re, sys, datetime
import openpyxl

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
КНИГА = os.path.join(ROOT, "Реестры", "ЛНК_Данные.xlsx")
ИТОГ = os.path.join(ROOT, "Приложение", "данные.json")

МЕТОДЫ = ["ВИК", "УЗД", "УЗТ", "АЭ", "ТВ", "ТК", "ВД", "МК"]
СТРОКА_ЗАГОЛОВКОВ = 3
ПЕРВАЯ = 4


def заголовки(ws):
    """Имя колонки → номер. Переносы в шапке схлопываются в пробел."""
    из = {}
    for c in range(1, ws.max_column + 1):
        v = ws.cell(СТРОКА_ЗАГОЛОВКОВ, c).value
        if v:
            из[" ".join(str(v).split())] = c
    return из


def значение(ws, r, c):
    """Пусто, прочерк и формула — всё это «ничего»."""
    if not c:
        return ""
    v = ws.cell(r, c).value
    if v is None:
        return ""
    if isinstance(v, datetime.datetime):
        return v.strftime("%Y-%m-%d")
    if isinstance(v, datetime.date):
        return v.strftime("%Y-%m-%d")
    s = str(v).strip()
    if s.startswith("="):          # формула без сохранённого результата
        return ""
    if s in ("—", "-", "–"):       # их способ писать «пусто»
        return ""
    return " ".join(s.split()) if "\n" not in s else s.strip()


def строки(ws, ключевая):
    return [r for r in range(ПЕРВАЯ, ws.max_row + 1)
            if значение(ws, r, ключевая)]


def собрать_объекты(wb):
    ws = wb["Объекты"]
    H = заголовки(ws)
    к = H["Каноническое наименование"]
    поля = [
        ("наименование", "Каноническое наименование"), ("зав", "Заводской №"),
        ("рег", "Регистрационный №"), ("учет", "Учётный №"),
        ("инв", "Инвентарный №"), ("тип", "Тип / группа"),
        ("расположение", "Место расположения"), ("изготовитель", "Изготовитель"),
        ("паспорт", "Номер паспорта"), ("материал", "Марка материала"),
        ("объем", "Объём"), ("толщины", "Толщины"),
        ("мин_толщина", "Мин. допустимая толщина, мм"),
        ("твердость", "Допустимая твёрдость, НВ"),
        ("давление", "Рабочее давление"), ("среда", "Рабочая среда"),
        ("примечание", "Примечание"),
    ]
    из = []
    for i, r in enumerate(строки(ws, к), 1):
        o = {"id": i}
        for имя, колонка in поля:
            o[имя] = значение(ws, r, H.get(колонка))
        из.append(o)
    return из


ЗАВ = re.compile(r"зав\.?\s*№\s*([^,;]+)", re.I)
РЕГ = re.compile(r"рег\.?\s*№\s*([^,;]+)", re.I)


def разобрать_объект(строка):
    """«Баллон (хладон) V=40 л, зав. № 57544» → имя, заводской, регистрационный.

    В книге объект выбирают одной строкой, и заводской номер часто вклеен
    прямо в неё. Поиск по такой строке в справочнике не находил ничего —
    поэтому 22 записи акта 28-2026 оставались без заводских номеров, хотя
    в акте они есть. Здесь строка разбирается на части.
    """
    строка = строка or ""
    зав = ЗАВ.search(строка)
    рег = РЕГ.search(строка)
    имя = re.sub(r",?\s*(зав|рег)\.?\s*№.*$", "", строка, flags=re.I).strip()
    return имя, (зав.group(1).strip() if зав else ""), (рег.group(1).strip() if рег else "")


def карточка_по_строке(объекты, имя, зав, рег):
    """Карточка по наименованию, затем заводскому, затем регистрационному номеру.

    У однотипных аппаратов («теплообменник 273ТНГ», 12 карточек) заводского
    номера нет, различает их регистрационный. Поиск только по имени и
    заводскому отдавал всем одну карточку. Каждый шаг сужает, только если
    что-то остаётся. Та же логика, что у карточкаПоСтроке в шаблоне.
    """
    c = [o for o in объекты if (o.get("наименование") or "").strip() == имя]
    if not c:
        return None
    def сузить(c, поле, v):
        f = [o for o in c if str(o.get(поле) or "").strip() == v]
        return f or c
    c = сузить(c, "зав", зав) if зав else сузить(c, "зав", "")
    if рег:
        c = сузить(c, "рег", рег)
    return c[0]


def собрать_журнал(wb, объекты):
    ws = wb["Журнал"]
    H = заголовки(ws)
    к = H["Дата контроля"]
    # заводской и регистрационный номера в книге подтягиваются формулой из
    # справочника по наименованию — здесь тот же поиск, только на Python.
    # Имя объекта повторяется у десятков баллонов, поэтому по одному имени
    # искать нельзя: ключ — имя вместе с заводским номером.
    по_имени = {}
    по_имени_зав = {}
    for o in объекты:
        по_имени.setdefault(o["наименование"], o)
        по_имени_зав[(o["наименование"], o["зав"])] = o

    из = []
    for n, r in enumerate(строки(ws, к), 1):
        дата = значение(ws, r, к)
        объект = значение(ws, r, H.get("Объект контроля (выбор из справочника)"))
        имя_об, зав_об, рег_об = разобрать_объект(объект)
        спр = карточка_по_строке(объекты, имя_об, зав_об, рег_об) or по_имени.get(объект) or {}
        # Дефект переноса: у 22 записей в «№ акта» стоял номер протокола
        # (01-2026-ТК). Он уже есть в колонке своего метода, а для ТК и ВД
        # акт не оформляется — поле лишнее. Подтверждено заказчиком.
        акт = значение(ws, r, H.get("№ акта"))
        if re.fullmatch(r"\d+-\d{4}-[А-Я]{2}", акт or ""):
            акт = ""
        зап = {
            "id": значение(ws, r, H.get("ID записи")) or ("З-%04d" % n),
            "нп": n,
            "статус": значение(ws, r, H.get("Статус")),
            "акт": акт,
            "дата": дата,
            "год": дата[:4] if дата else "",
            "подразделение": значение(ws, r, H.get("Заказывающее подразделение")),
            "объект": объект,
            "объект_ид": спр.get("id", ""),
            "наименование": значение(ws, r, H.get("Наименование объекта в документе")) or имя_об,
            "зав": зав_об or спр.get("зав", ""),
            "рег": рег_об or спр.get("рег", ""),
            "архив": значение(ws, r, H.get("№ экз., дата передачи в архив ЛНК")),
            "исходящий": значение(ws, r, H.get("№ экз., исходящий, дата отправки")),
            "отправитель": значение(ws, r, H.get("Отправитель")),
            "примечание": значение(ws, r, H.get("Примечание")),
            "методы": {},
        }
        for м in МЕТОДЫ:
            номер = значение(ws, r, H.get(м + " №"))
            исп = значение(ws, r, H.get(м + " исполнитель"))
            if номер or исп:
                зап["методы"][м] = {"н": номер, "исп": исп}
        из.append(зап)
    return из


def собрать_си(wb):
    ws = wb["СИ"]
    H = заголовки(ws)
    к = H["Наименование"]
    поля = [("наименование", "Наименование"), ("тип", "Тип / обозначение"),
            ("зав", "Заводской №"), ("инв", "Инвентарный №"),
            ("метод", "Метод контроля"), ("назначение", "Назначение"),
            ("поверка_до", "Действительно до"), ("свидетельство", "№ свидетельства"),
            ("периодичность", "Периодичность поверки, мес."),
            ("хранение", "Место хранения / нахождения"), ("состояние", "Состояние")]
    из = []
    for i, r in enumerate(строки(ws, к), 1):
        s = {"id": i}
        for имя, колонка in поля:
            s[имя] = значение(ws, r, H.get(колонка))
        из.append(s)
    return из


def собрать_специалистов(wb):
    ws = wb["Специалисты"]
    H = заголовки(ws)
    к = H["ФИО полностью"]
    поля = [("фио", "ФИО полностью"), ("вдок", "ФИО в документах"),
            ("должность", "Должность"), ("функции", "Функции в ЛНК"),
            ("стаж", "Стаж по НК с")]
    из = []
    for i, r in enumerate(строки(ws, к), 1):
        s = {"id": i}
        for имя, колонка in поля:
            s[имя] = значение(ws, r, H.get(колонка))
        из.append(s)
    return из


def main():
    if not os.path.exists(КНИГА):
        raise SystemExit("Не найдена книга: %s" % КНИГА)
    wb = openpyxl.load_workbook(КНИГА)

    объекты = собрать_объекты(wb)
    данные = {
        "версия": "3.23",
        "собрано": datetime.date.today().isoformat(),
        "методы": МЕТОДЫ,
        "объекты": объекты,
        "журнал": собрать_журнал(wb, объекты),
        "си": собрать_си(wb),
        "специалисты": собрать_специалистов(wb),
    }

    os.makedirs(os.path.dirname(ИТОГ), exist_ok=True)
    with io.open(ИТОГ, "w", encoding="utf-8") as f:
        json.dump(данные, f, ensure_ascii=False, separators=(",", ":"))

    размер = os.path.getsize(ИТОГ) / 1024.0
    print("Записано: %s (%.0f КБ)" % (ИТОГ, размер))
    for имя in ("журнал", "объекты", "си", "специалисты"):
        print("  %-14s %4d" % (имя, len(данные[имя])))
    сметодами = sum(1 for з in данные["журнал"] if з["методы"])
    print("  записей с методами %d из %d" % (сметодами, len(данные["журнал"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
