// Принять с флешки: файлы обмена из выбранной папки (по одному, самому
// свежему, от каждого места; свой пропускается) и затем — недостающие
// файлы документов из подпапки «Файлы ЛНК».
async function обменСФайламиПринять(папка){
  if(!ЕСТЬ_ПАПКИ){ toast("Этот браузер не умеет читать выбранную папку — так умеют Chrome и Edge"); return; }
  const h=await папкаДок();
  if(h && await правоНаПапкуДок(true)!=="есть"){ toast("Нет разрешения на папку с документами"); return; }
  const ист=папка||await выбратьФлешку(false); if(!ист) return;
  if(!папка && typeof запомнитьПапкуОбмена==="function") await запомнитьПапкуОбмена(ист);
  const прогр=typeof найтиВерсиюПрограммы==="function"?await найтиВерсиюПрограммы(ист):null;
  const новаяПрогр=прогр && верс(прогр.версия)>верс(DB.версия)?прогр:null;
  const предложитьОбновить=async()=>{ if(новаяПрогр && confirm("В папке «"+ист.name+"» новая версия программы "+новаяПрогр.версия+
      " («"+новаяПрогр.имя+"»), у вас "+DB.версия+".\n\nОбновить программу на этом компьютере сейчас?")) await обновитьПрограмму(новаяПрогр); };
  const я=getWS().код, поМесту={}, плохие=[]; let своих=0, копий=0;
  try{
    for await (const [имя, х] of ист.entries()){
      if(х.kind!=="file" || !/\.json$/i.test(имя)) continue;
      let d; try{ d=JSON.parse(await (await х.getFile()).text()); }catch(e){ плохие.push({f:{name:имя}, ошибка:"не читается"}); continue; }
      if(d && (d.тип==="резервная копия ЛНК" || d.тип===ТИП_ПЕРЕЕЗДА)){ копий++; continue; }
      if(!d || d.тип!=="обмен ЛНК") continue;
      if(d.место===я){ своих++; continue; }
      const к=d.место||имя;
      if(!поМесту[к] || String(d.выгружено||"")>String(поМесту[к].d.выгружено||"")) поМесту[к]={f:{name:имя}, d};
    }
  }catch(e){ alert("Не удалось прочитать папку «"+ист.name+"»: "+e.name); return; }
  const годные=Object.keys(поМесту).map(к=>поМесту[к]);
  if(годные.length){
    const принято=принятьПрочитанныеОбмены(годные, плохие);
    if(!принято) return;
  } else if(!h){
    alert("В папке «"+ист.name+"» нет файлов обмена других мест"+(своих?" (есть только выгруженный этим местом)":"")+"."+
      (копий?"\n\nРезервные копии и файлы переезда отсюда не принимаются — для них «Ещё» → «Принять файл…».":""));
    await предложитьОбновить(); return;
  }
  if(!h){ alert("Обмен принят. Файлы документов не взяты: на этом месте не выбрана папка с документами "+
    "(«Обмен файлами» → «Папка с документами»)."); await предложитьОбновить(); return; }
  await сверитьФайлы(h);
  const р=await взятьФайлы(h, ист);
  обновитьОбменИлиМастер(); setChrome();
  alert((годные.length?"":"Файлов обмена других мест в папке нет"+(своих?" (только выгруженный этим местом)":"")+" — беру только файлы документов.\n\n")+
    текстВзятых(р)+(копий&&!годные.length?"\n\nРезервные копии и файлы переезда отсюда не принимаются — для них «Ещё» → «Принять файл…».":""));
  await предложитьОбновить();
}

