// ── Импорт из Excel (справочники объектов и приборов) ──────
// Свой минимальный разбор .xlsx: ZIP-каталог читаю вручную по сигнатурам
// PK (как zipStore пишет), а распаковку DEFLATE делает браузер
// (DecompressionStream) — свой инфлейт не пишу, риск ошибиться на
// реальном файле. Библиотек не подключаю: программа остаётся одним
// файлом без сети (см. CLAUDE.md). Формат — только СВОЙ шаблон-таблица
// (кнопка «Шаблон для импорта» рядом), не исходная книга заказчика: там
// формулы и разметка, которые я не разбираю и разбирать не буду —
// смешивать со сборкой книги через scripts/export_json.py нельзя.

// N-1-2 склонение счётного слова — единственное место в программе, где
// это нужно динамически (текст диалога подтверждения импорта).
function числослово(n, формы){
  const n10=n%10, n100=n%100;
  if(n100>=11 && n100<=14) return формы[2];
  if(n10===1) return формы[0];
  if(n10>=2 && n10<=4) return формы[1];
  return формы[2];
}

function excelСерийДата(serial){
  // Excel считает 1900 год високосным (унаследованная ошибка Lotus
  // 1-2-3) — день 0 это 30.12.1899, и это учтено в константе 25569
  // (число дней от 30.12.1899 до 01.01.1970).
  const мс = Math.round((serial - 25569) * 86400 * 1000);
  return new Date(мс).toISOString().slice(0,10);
}
function значениеДаты(raw){
  const s=String(raw||"").trim();
  if(!s) return "";
  if(/^\d+(\.\d+)?$/.test(s)) return excelСерийДата(+s);
  // Дата должна существовать: «31.13.2027» или «30.02.2026» — не дата,
  // а не «2027-13-31» (такое молча ложилось в карточку).
  const есть=(г,м,д)=>{ const x=new Date(Date.UTC(+г,+м-1,+д));
    return x.getUTCFullYear()===+г && x.getUTCMonth()===+м-1 && x.getUTCDate()===+д; };
  let m=/^(\d{1,2})\.(\d{1,2})\.(\d{4})$/.exec(s);
  if(m) return есть(m[3],m[2],m[1]) ? m[3]+"-"+m[2].padStart(2,"0")+"-"+m[1].padStart(2,"0") : "";
  m=/^(\d{4})-(\d{2})-(\d{2})/.exec(s);
  if(m) return есть(m[1],m[2],m[3]) ? m[0].slice(0,10) : "";
  return "";
}

function zipЧитать(buf){
  const dv=new DataView(buf.buffer,buf.byteOffset,buf.byteLength);
  let eocd=-1;
  const низ=Math.max(0, buf.length-22-65557);
  for(let i=buf.length-22; i>=низ; i--){
    if(dv.getUint32(i,true)===0x06054b50){ eocd=i; break; }
  }
  if(eocd<0) throw new Error("это не .xlsx (нет конца ZIP-архива)");
  const кол=dv.getUint16(eocd+10,true);
  const смещЦентр=dv.getUint32(eocd+16,true);
  const записи={};
  let p=смещЦентр;
  for(let i=0; i<кол; i++){
    if(dv.getUint32(p,true)!==0x02014b50) throw new Error("повреждён архив (каталог)");
    const метод=dv.getUint16(p+10,true);
    const сжРазм=dv.getUint32(p+20,true);
    const имяДл=dv.getUint16(p+28,true);
    const допДл=dv.getUint16(p+30,true);
    const коммДл=dv.getUint16(p+32,true);
    const смещЛок=dv.getUint32(p+42,true);
    const имя=new TextDecoder("utf-8").decode(buf.subarray(p+46,p+46+имяДл));
    записи[имя]={метод,сжРазм,смещЛок};
    p+=46+имяДл+допДл+коммДл;
  }
  return {buf,dv,записи};
}
async function zipТекст(zip,имя){
  const e=zip.записи[имя];
  if(!e) return "";
  const dv=zip.dv, p=e.смещЛок;
  if(dv.getUint32(p,true)!==0x04034b50) throw new Error("повреждён архив (файл "+имя+")");
  const имяДл=dv.getUint16(p+26,true), допДл=dv.getUint16(p+28,true);
  const начало=p+30+имяДл+допДл;
  const сжатые=zip.buf.subarray(начало,начало+e.сжРазм);
  let байты;
  if(e.метод===0) байты=сжатые;
  else if(e.метод===8){
    const поток=new Blob([сжатые]).stream().pipeThrough(new DecompressionStream("deflate-raw"));
    байты=new Uint8Array(await new Response(поток).arrayBuffer());
  } else throw new Error("неизвестный способ сжатия ("+имя+")");
  return new TextDecoder("utf-8").decode(байты);
}
function деэскейпXML(s){
  // Числовые ссылки на символы (&#1053; / &#x41B;) — так openpyxl (и не
  // только он) кодирует кириллицу вместо сырого UTF-8. Без этой замены
  // русский текст в заголовках и ячейках приходит нечитаемым.
  return s.replace(/&#x([0-9a-fA-F]+);/g,(_,h)=>String.fromCodePoint(parseInt(h,16)))
    .replace(/&#(\d+);/g,(_,d)=>String.fromCodePoint(parseInt(d,10)))
    .replace(/&lt;/g,"<").replace(/&gt;/g,">").replace(/&quot;/g,'"')
    .replace(/&apos;/g,"'").replace(/&amp;/g,"&");
}
function sharedStringsРазобрать(xml){
  if(!xml) return [];
  const из=[]; const siRe=/<si>([\s\S]*?)<\/si>/g; let m;
  while((m=siRe.exec(xml))){
    let текст=""; const tRe=/<t[^>]*>([\s\S]*?)<\/t>/g; let tm;
    while((tm=tRe.exec(m[1]))) текст+=деэскейпXML(tm[1]);
    из.push(текст);
  }
  return из;
}
function листРазобрать(xml, shared){
  const строки=[];
  const rowRe=/<row[^>]*>([\s\S]*?)<\/row>/g; let rm;
  while((rm=rowRe.exec(xml))){
    const ряд={};
    const cellRe=/<c\s+r="([A-Z]+)\d+"([^>]*?)(?:\/>|>([\s\S]*?)<\/c>)/g; let cm;
    while((cm=cellRe.exec(rm[1]))){
      const столб=cm[1], атр=cm[2]||"", тело=cm[3]||"";
      const tМ=/\st="([a-zA-Z]+)"/.exec(атр);
      const тип=tМ?tМ[1]:"n";
      let значение="";
      if(тип==="s"){ const vm=/<v>([\s\S]*?)<\/v>/.exec(тело); значение=vm?(shared[+vm[1]]||""):""; }
      else if(тип==="inlineStr"){ const tm=/<t[^>]*>([\s\S]*?)<\/t>/.exec(тело); значение=tm?деэскейпXML(tm[1]):""; }
      else { const vm=/<v>([\s\S]*?)<\/v>/.exec(тело); значение=vm?деэскейпXML(vm[1]):""; }
      ряд[столб]=значение;
    }
    строки.push(ряд);
  }
  return строки;
}
async function xlsxРазобрать(file){
  const buf=new Uint8Array(await file.arrayBuffer());
  const zip=zipЧитать(buf);
  let sheetPath="xl/worksheets/sheet1.xml";
  const workbookXml=await zipТекст(zip,"xl/workbook.xml");
  const relsXml=await zipТекст(zip,"xl/_rels/workbook.xml.rels");
  const sheetM=/<sheet\b[^>]*\br:id="([^"]+)"[^>]*\/?>/.exec(workbookXml||"");
  if(sheetM && relsXml){
    const relM=new RegExp('<Relationship\\b[^>]*\\bId="'+sheetM[1]+'"[^>]*\\bTarget="([^"]+)"').exec(relsXml);
    if(relM){ const t=relM[1]; sheetPath = t.charAt(0)==="/" ? t.slice(1) : "xl/"+t; }
  }
  const sheetXml=await zipТекст(zip,sheetPath);
  if(!sheetXml) throw new Error("в файле не нашёлся лист с данными");
  const sharedXml=await zipТекст(zip,"xl/sharedStrings.xml");
  return листРазобрать(sheetXml, sharedStringsРазобрать(sharedXml));
}

