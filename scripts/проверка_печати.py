# -*- coding: utf-8 -*-
"""Проверка постраничной вёрстки акта по готовому PDF.

Два правила заказчика проверяются не по флагам в разметке, а по тому,
что реально получилось на страницах:

  1. Не должно быть листа, где одни подписи без текста о номерах
     протоколов.
  2. Раздел результатов работ не должен разрываться между страницами:
     номера одного метода обязаны уместиться на одной странице.
  3. Строка не должна заканчиваться висящим словом — однобуквенным
     («в», «с», «и») или коротким предлогом («на», «по», «от»).

Наличие keepNext/keepLines в файле ничего из этого не доказывает —
поэтому проверяем итог.

Запуск:  python3 scripts/проверка_печати.py путь.pdf
"""
import re
import sys
import collections

try:
    import pymupdf
except ImportError:  # старое имя пакета
    import fitz as pymupdf

НОМЕР = re.compile(r"\d+-20\d\d-([А-Я]{2,3})")
ВИСЯЧИЕ = set(("а и в к о с у я б ж на по до из от за об во со ко "
               "не ни но же ли бы да то при для над под про без изо ото "
               "что как или если чем так перед между через после").split())
ПОДПИСЬ = re.compile(r"(Генеральный директор|Начальник ЛНК|Специалист ЛНК|"
                     r"Заместитель начальника)")


def проверить(путь):
    книга = pymupdf.open(путь)
    беды = []
    страницы = []
    методы = collections.defaultdict(set)

    for i, стр in enumerate(книга, 1):
        текст = стр.get_text()
        есть_номера = bool(НОМЕР.search(текст))
        есть_подписи = bool(ПОДПИСЬ.search(текст))
        страницы.append((i, есть_номера, есть_подписи))
        for м in НОМЕР.findall(текст):
            методы[м].add(i)
        if есть_подписи and not есть_номера:
            беды.append("страница %d: одни подписи, без текста о номерах протоколов" % i)

        # Строки собираются по ПОЛОЖЕНИЮ слов на странице, а не по переводам
        # строки в тексте PDF: строку, растянутую по ширине, браузер пишет в
        # PDF каждым словом отдельно, и разбор текста по «\n» принимал каждое
        # слово за отдельную строку — «по», «в» в середине строки выглядели
        # висящими (ложная тревога, поймана сверкой с координатами слов).
        # Слова одной строки — на одной базовой линии (допуск 2 pt), по
        # порядку слева направо. Проверять разметку бессмысленно: там
        # неразрывные пробелы, а важен итог на странице.
        строки = []
        for w in sorted(стр.get_text("words"), key=lambda w: (round(w[3], 1), w[0])):
            if строки and abs(строки[-1][0] - w[3]) <= 2:
                строки[-1][1].append(w)
            else:
                строки.append([w[3], [w]])
        строки = [" ".join(x[4] for x in sorted(ws, key=lambda w: w[0])) for _, ws in строки]
        for н, строка in enumerate(строки):
            слова = строка.split()
            if not слова or н == len(строки) - 1:
                continue
            последнее = слова[-1].strip(",.;:()«»\"").lower()
            if последнее in ВИСЯЧИЕ:
                беды.append("страница %d: строка кончается висящим словом «%s» — …%s"
                            % (i, последнее, строка[-46:]))

    for м, стрн in sorted(методы.items()):
        if len(стрн) > 1:
            беды.append("раздел %s разорван между страницами %s"
                        % (м, ", ".join(str(x) for x in sorted(стрн))))

    return беды, страницы, методы


def main():
    if len(sys.argv) < 2:
        raise SystemExit("Укажите путь к PDF")
    беды, страницы, методы = проверить(sys.argv[1])

    print("Страниц: %d" % len(страницы))
    for i, ном, под in страницы:
        print("  стр.%d: номера протоколов — %s, подписи — %s"
              % (i, "да" if ном else "нет", "да" if под else "нет"))
    if методы:
        print("Разделы по страницам: %s"
              % ", ".join("%s → %s" % (м, sorted(с)) for м, с in sorted(методы.items())))

    if беды:
        print("\nНАЙДЕНЫ НАРУШЕНИЯ (%d):" % len(беды))
        for б in беды:
            print("  ✗", б)
        return 1
    print("\nПроверка пройдена: листа с одними подписями нет, "
          "разделы не разорваны между страницами.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
