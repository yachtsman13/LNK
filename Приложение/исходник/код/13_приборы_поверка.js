// Оборудование из паспорта «Редакция № 6» (см. ОБОРУДОВАНИЕ_ИЗ_ПАСПОРТА_2026_10).
// Каждый запуск: у заведённой карточки — только пустые поля; новой
// позиции — карточка «СИП-<позиция>», если её ещё нет (удалённую не
// возвращает). Перед тем как заводить, ищет, не завёл ли её уже кто-то
// руками: то же наименование (с типом или без) и, если номер есть у обеих,
// тот же заводской номер — тогда заполняет её, а не заводит вторую.
// Отметку «изменено» не ставит: на каждом месте получается одно и то же.
function оборудованиеИзПаспорта(){
  const норм=t=>String(t||"").toLowerCase().replace(/ё/g,"е").replace(/[^a-zа-я0-9]/g,"");
  const ПОСЛЕ={71:"21",73:"15",74:"СИП-073"};
  // карточка 21 называлась просто «ступенька» — теперь их две, Сталь Д и
  // Сталь 38ХА; переименовывается, только если имя прежнее, слово в слово
  const ПЕРЕИМЕНОВАТЬ={"21":["Настроечный образец ступенька","Настроечный образец ступенька Сталь Д"]};
  const занятые=new Set(ОБОРУДОВАНИЕ_ИЗ_ПАСПОРТА_2026_10.filter(п=>п.ид).map(п=>п.ид));
  let изм=false;
  ОБОРУДОВАНИЕ_ИЗ_ПАСПОРТА_2026_10.forEach(п=>{
    const д=Object.assign({},п); delete д.поз; delete д.ид;
    let к;
    if(п.ид){
      к=S.find(x=>String(x.id)===п.ид); if(!к || к.удалено) return;
      const пер=ПЕРЕИМЕНОВАТЬ[п.ид];
      if(пер && к.наименование===пер[0]){ к.наименование=пер[1]; изм=true; }
    } else {
      const ид="СИП-"+String(п.поз).padStart(3,"0");
      к=S.find(x=>String(x.id)===ид);
      if(к && к.удалено) return;
      if(!к){
        const имя=норм(д.наименование), сТипом=норм(д.наименование+(д.тип||""));
        const зав=String(д.зав||"").trim();
        const кан=live(S).filter(x=>!занятые.has(String(x.id)) && !/^СИП-/.test(String(x.id)) &&
          [норм(x.наименование), норм((x.наименование||"")+(x.тип||""))].some(н=>н===имя||н===сТипом) &&
          (!зав || безНомера(зав) || !String(x.зав||"").trim() || String(x.зав).trim()===зав));
        if(кан.length===1) к=кан[0];
        else {
          к={id:ид, состояние:"В работе"};
          const после=ПОСЛЕ[п.поз], i=после?S.findIndex(x=>String(x.id)===после):-1;
          if(i>=0) S.splice(i+1,0,к); else S.push(к);
          изм=true;
        }
      }
    }
    занятые.add(String(к.id));
    Object.keys(д).forEach(k=>{ if(д[k] && !String(к[k]==null?"":к[k]).trim()){ к[k]=д[k]; изм=true; } });
  });
  return изм;
}
