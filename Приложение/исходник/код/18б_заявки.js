// Акт по записям заявки — формой «по дополнительной заявке» (образец
// «00-2026», 3.70) и с подразделением заявки. Только при первом открытии:
// выбранное потом руками не трогается (вид_авто).
function автовидАкта(ключ, zs){
  const a=актЗапись(ключ,false);
  if(a.вид_авто || !zs.length || !zs.every(z=>z.заявка)) return;
  if(!a.вид) saveАкт(ключ,"вид","заявка");
  if(!a.подр){ const п=[...new Set(zs.map(z=>{ const зв=найтиПоИд(ЗАЯВ,z.заявка); return зв&&зв.подр?String(зв.подр):""; }))];
    if(п.length===1 && п[0]) saveАкт(ключ,"подр",п[0]); }
  saveАкт(ключ,"вид_авто","1");
}
