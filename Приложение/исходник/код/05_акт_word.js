// ── Выгрузка акта в Word (.docx) ──────────────────────────
// Печать в PDF документ закрывает, а перед подписанием формулировку
// обычно правят. Поэтому акт выгружается настоящим .docx: Word откроет
// его как свой, без предупреждений о формате.
//
// Библиотек нет и быть не может (программа — один файл, без сети),
// поэтому .docx собирается здесь: это ZIP, и он пишется без сжатия
// (метод «store») — так архив укладывается в полсотни строк, а Word
// такие файлы принимает наравне со сжатыми.
function crc32(buf){
  let tbl=crc32.t;
  if(!tbl){ tbl=crc32.t=new Int32Array(256);
    for(let n=0;n<256;n++){ let c=n;
      for(let k=0;k<8;k++) c=(c&1)?(0xEDB88320^(c>>>1)):(c>>>1);
      tbl[n]=c; } }
  let crc=-1;
  for(let i=0;i<buf.length;i++) crc=(crc>>>8)^tbl[(crc^buf[i])&0xFF];
  return (crc^-1)>>>0;
}
function zipStore(файлы){
  const enc=new TextEncoder(), куски=[], центр=[];
  let смещение=0;
  файлы.forEach(f=>{
    const имя=enc.encode(f.имя);
    const d=(typeof f.данные==="string")?enc.encode(f.данные):f.данные;
    const c=crc32(d);
    const lf=new Uint8Array(30+имя.length), lv=new DataView(lf.buffer);
    lv.setUint32(0,0x04034b50,true); lv.setUint16(4,20,true);
    lv.setUint16(6,0x0800,true);            // имена в UTF-8
    lv.setUint16(8,0,true);                 // без сжатия
    lv.setUint32(14,c,true); lv.setUint32(18,d.length,true); lv.setUint32(22,d.length,true);
    lv.setUint16(26,имя.length,true);
    lf.set(имя,30);
    куски.push(lf,d);

    const cd=new Uint8Array(46+имя.length), cv=new DataView(cd.buffer);
    cv.setUint32(0,0x02014b50,true); cv.setUint16(4,20,true); cv.setUint16(6,20,true);
    cv.setUint16(8,0x0800,true); cv.setUint16(10,0,true);
    cv.setUint32(16,c,true); cv.setUint32(20,d.length,true); cv.setUint32(24,d.length,true);
    cv.setUint16(28,имя.length,true); cv.setUint32(42,смещение,true);
    cd.set(имя,46);
    центр.push(cd);
    смещение+=lf.length+d.length;
  });
  const размерЦентра=центр.reduce((a,x)=>a+x.length,0);
  const eocd=new Uint8Array(22), ev=new DataView(eocd.buffer);
  ev.setUint32(0,0x06054b50,true);
  ev.setUint16(8,файлы.length,true); ev.setUint16(10,файлы.length,true);
  ev.setUint32(12,размерЦентра,true); ev.setUint32(16,смещение,true);
  return new Blob(куски.concat(центр,[eocd]),
    {type:"application/vnd.openxmlformats-officedocument.wordprocessingml.document"});
}
function dlBlob(имя, blob){
  const url=URL.createObjectURL(blob);
  const a=document.createElement("a"); a.href=url; a.download=имя;
  document.body.appendChild(a); a.click();
  setTimeout(()=>{ URL.revokeObjectURL(url); a.remove(); }, 400);
}

// Разметка взята из вашего акта: Times New Roman 14 пт (sz 28 полупунктов),
// межстрочный ровно 18 пт (line 360 exact), абзацный отступ 1,25 см (709),
// выключка по ширине, А4 с вашими полями, отдельная шапка первой страницы.
const X = s => String(s==null?"":s)
  .replace(/&/g,"&amp;").replace(/</g,"&lt;").replace(/>/g,"&gt;")
  .replace(/"/g,"&quot;").replace(/'/g,"&apos;");
// Перевод строки в тексте документа — разрыв строки Word (w:br) внутри
// того же абзаца: и введённый в многострочном поле, и записанный знаком
// «^/» (см. разметкаВвода).
const XT = s => X(s).replace(/\n/g,'</w:t><w:br/><w:t xml:space="preserve">');
const ФОНТ='<w:rFonts w:ascii="Times New Roman" w:hAnsi="Times New Roman" w:cs="Times New Roman"/>';
const КЕГЛЬ='<w:sz w:val="28"/><w:szCs w:val="28"/>';
function rPr(жирный){ return '<w:rPr>'+ФОНТ+(жирный?'<w:b/>':'')+КЕГЛЬ+'</w:rPr>'; }
const ШР=ФОНТ+КЕГЛЬ;
function wRun(t,жирный){
  return '<w:r>'+rPr(жирный)+'<w:t xml:space="preserve">'+XT(t)+'</w:t></w:r>';
}
// Интервал строк акта. Основная форма (акты 28-2026, 35-2026) — точно
// 18 пт; акт по дополнительной заявке (образец «00-2026») — одинарный.
// _актЗаявка включает актВWord на время сборки такого акта.
let _актЗаявка=false;
function интервалАкта(){ return _актЗаявка?'<w:spacing w:after="0" w:line="240" w:lineRule="auto"/>':'<w:spacing w:after="0" w:line="360" w:lineRule="exact"/>'; }
function wP(t,вид){
  вид=вид||{};
  const jc=вид.jc||"both";
  const ind=вид.отступ===false?'':'<w:ind w:firstLine="709"/>';
  // keepNext держит абзац вместе со следующим: так таблица подписей не
  // уезжает на отдельный лист без текста о номерах протоколов.
  const держать=вид.держать?'<w:keepNext/>':'';
  const курсив=вид.курсив?'<w:i/>':'';
  return '<w:p><w:pPr>'+держать+интервалАкта()+
    ind+'<w:jc w:val="'+jc+'"/>'+rPrПолный(вид)+'</w:pPr>'+
    (t?wRunВид(t,вид):'')+'</w:p>';
}
// Заголовок раздела паспорта: римские номера (по прямому указанию
// заказчика, не из образца), отступ 12 пт = 240 твипов и до, и после
// заголовка — отдельный абзац, не полагается на «пустые строки»-разделители
// между разделами (те убраны рядом с каждым вызовом, иначе отступ бы удвоился).
// По центру — тоже прямое указание заказчика (было «both», по ширине).
const ПАС_РИМ=["I","II","III","IV","V","VI","VII","VIII","IX","X","XI"];
// Кегль — 16 пт (sz 32), как стиль заголовка разделов в бланке «Редакция
// № 6» и по указанию заказчика; лист ознакомления в бланке — 14 пт, его
// вызов передаёт свой кегль. keepNext — заголовок не остаётся внизу
// страницы один, без своего раздела.
function wПасРаздел(текст, кегль){
  const вид={жирный:true, кегль:кегль||32};
  return '<w:p><w:pPr><w:keepNext/><w:spacing w:before="240" w:after="240" w:line="400" w:lineRule="atLeast"/>'+
    '<w:jc w:val="center"/>'+rPrПолный(вид)+'</w:pPr>'+wRunВид(текст,вид)+'</w:p>';
}
function rPrПолный(вид){
  // Кегль по умолчанию общий для документов программы; вид.кегль нужен
  // подстрочным пояснениям в заявке на поверку («(подпись, И.О. фамилия)»
  // и т.п. — в образце они заметно мельче основного текста). Порядок
  // элементов CT_RPr: rFonts → b → i → sz → szCs, иначе Word объявит
  // файл повреждённым.
  const кг=вид.кегль?('<w:sz w:val="'+вид.кегль+'"/><w:szCs w:val="'+вид.кегль+'"/>'):КЕГЛЬ;
  return '<w:rPr>'+ФОНТ+(вид.жирный?'<w:b/>':'')+(вид.курсив?'<w:i/>':'')+кг+'</w:rPr>';
}
function wRunВид(t,вид){
  return '<w:r>'+rPrПолный(вид)+'<w:t xml:space="preserve">'+XT(t)+'</w:t></w:r>';
}
// Номер протокола «121-2026-ВИК» Word разорвал бы по дефисам. Неразрывный
// дефис (w:noBreakHyphen) — штатный для этого элемент, не подделка
// пробелами: номер остаётся целым при любой выключке.
function wНомер(об){
  const части=String(об).split("-");
  let из='';
  части.forEach((ч,i)=>{
    if(i) из+='<w:r>'+rPr(false)+'<w:noBreakHyphen/></w:r>';
    из+='<w:r>'+rPr(false)+'<w:t xml:space="preserve">'+X(ч)+'</w:t></w:r>';
  });
  return из;
}
// Абзац перечня: «1. Название №№ номер, номер.» — знак № приклеен к
// первому номеру неразрывным пробелом.
// После номера раздела — табуляция с жёсткой позицией: тогда текст всех
// разделов начинается с одного места и нумерация выглядит одинаково,
// сколько бы разделов ни было — и при двузначных номерах тоже.
const ТАБ_РАЗДЕЛА = 1134;                 // 2 см от левого поля
function wПеречень(н, имя, номера, держать){
  const один=(номера.length===1);
  // keepLines не даёт разорвать раздел между страницами: не помещается —
  // Word целиком переносит его на следующую. Это прямее, чем подгонять
  // пустые строки между разделами, и не зависит от того, сколько их.
  let из='<w:p><w:pPr>'+(держать?'<w:keepNext/>':'')+'<w:keepLines/>'+
    '<w:tabs><w:tab w:val="left" w:pos="'+ТАБ_РАЗДЕЛА+'"/></w:tabs>'+
    интервалАкта()+
    '<w:ind w:firstLine="709"/><w:jc w:val="both"/>'+
    rPr(false)+'</w:pPr>';
  из+=wRun(н+".");
  из+='<w:r>'+rPr(false)+'<w:tab/></w:r>';
  из+=wТекстСоСтепенями(типографика(имя));
  из+='<w:r>'+rPr(false)+'<w:t xml:space="preserve"> '+
      (один?"\u2116":"\u2116\u2116")+'\u00a0</w:t></w:r>';
  номера.forEach((об,i)=>{
    if(i) из+=wRun(", ");
    из+=wНомер(об);
  });
  из+=wRun(".");
  return из+'</w:p>';
}
function актВWord(ключ, вернуть){
  const zs=записиАкта(ключ);
  if(!zs.length){ toast("По акту "+ключ+" записей нет"); return; }
  if(!вернуть){
    const ош=готовностьАкта(ключ).filter(x=>x.ур==="ошибка");
    if(ош.length && !confirm("Акт не готов к выдаче — ошибок: "+ош.length+"\n\n"+
      ош.slice(0,8).map(x=>"· "+x.т).join("\n")+(ош.length>8?"\n… и ещё "+(ош.length-8):"")+
      "\n\nВсё равно выгрузить в Word (например, как черновик)?")) return;
  }
  const a=актЗапись(ключ,false);
  _актЗаявка=(a.вид==="заявка");
  try{ return актВWordТело(ключ, вернуть, zs, a); } finally { _актЗаявка=false; }
}
