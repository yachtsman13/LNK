// Через разбор степеней — поэтому надстрочные работают в ЛЮБОЙ таблице
// документа (паспорт, план ППР, заявка на поверку), а не только там, где
// это вспомнили вызвать. Без степеней разбор возвращает один кусок, то
// есть ровно прежний единственный ран. Порядок элементов CT_RPr:
