function случайныеЗнаки(алфавит,n){
  const из=[]; let нужно=n;
  while(нужно>0){
    const a=crypto.getRandomValues(new Uint8Array(нужно*2));
    for(const б of a){ if(б>=Math.floor(256/алфавит.length)*алфавит.length) continue;
      из.push(алфавит[б%алфавит.length]); нужно--; if(!нужно) break; }
  }
  return из.join("");
}
