// Дни отсутствия: календарные и рабочие (праздники и переносы — из
// карточки лаборатории, как у сроков инструктажа).
function рабочихДней(с, по){
  if(!с || !по || по<с) return 0;
  const пр=new Map((getЛаб().праздники||[]).map(x=>[x.дата, x.вид]));
  let н=0;
  for(let d=new Date(с+"T00:00:00"); калISO(d)<=по; d.setDate(d.getDate()+1)){
    const iso=калISO(d), п=пр.get(iso), дн=d.getDay();
    if(п ? п!=="нерабочий" : (дн!==0 && дн!==6)) н++;
  }
  return н;
}
function днейОтс(x, с, по){            // в пределах [с, по], календарных
  const а=x.с>с?x.с:с, б=x.по<по?x.по:по;
  return б<а?0:днейМежду(а,б)+1;
}

