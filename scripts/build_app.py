# -*- coding: utf-8 -*-
"""Сборка браузерного приложения: шаблон + данные → один файл ЛНК.html.

Данные вшиваются внутрь HTML (в тег <script type="application/json">), а не
лежат рядом отдельным файлом. Причина: когда книгу открывают двойным щелчком
с флешки, адрес у страницы file://, и по этому адресу браузер из соображений
безопасности не даёт странице читать соседние файлы. Значит, всё, что нужно
приложению, должно быть внутри него самого — тогда достаточно одного файла.

Запуск:  python3 scripts/export_json.py && python3 scripts/build_app.py
Итог:    Приложение/ЛНК.html
"""
import io, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ШАБЛОН = os.path.join(ROOT, "Приложение", "шаблон.html")
ДАННЫЕ = os.path.join(ROOT, "Приложение", "данные.json")
ИТОГ = os.path.join(ROOT, "Приложение", "ЛНК.html")
МЕТКА = "/*ДАННЫЕ*/"


def main():
    for п in (ШАБЛОН, ДАННЫЕ):
        if not os.path.exists(п):
            raise SystemExit("Нет файла: %s" % п)

    шаблон = io.open(ШАБЛОН, encoding="utf-8").read()
    данные = io.open(ДАННЫЕ, encoding="utf-8").read()

    if МЕТКА not in шаблон:
        raise SystemExit("В шаблоне нет метки %s — некуда вставлять данные." % МЕТКА)
    if шаблон.count(МЕТКА) != 1:
        raise SystemExit("Метка %s встречается не один раз." % МЕТКА)

    # </script> в данных разорвал бы тег-контейнер и сломал бы страницу.
    # В JSON прямой косой черты быть не должно, но подстрахуемся: экранируем
    # так, что для JSON.parse строка не меняется, а тег закрыться не может.
    данные = данные.replace("</", "<\\/")

    готово = шаблон.replace(МЕТКА, данные)

    with io.open(ИТОГ, "w", encoding="utf-8") as f:
        f.write(готово)

    # Проверка: получившийся файл самодостаточен (без внешних ссылок).
    import re
    внешние = re.findall(r'(src\s*=\s*["\']https?:|href\s*=\s*["\']https?:|@import)', готово)
    if внешние:
        raise SystemExit("В сборке есть внешние ссылки — офлайн не откроется: %s" % внешние[:3])

    print("Собрано: %s (%.0f КБ)" % (ИТОГ, os.path.getsize(ИТОГ) / 1024.0))
    print("  внешних ссылок нет — откроется без сети")
    return 0


if __name__ == "__main__":
    sys.exit(main())
