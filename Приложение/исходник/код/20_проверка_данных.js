function реестрыМимоКопии(){
  let вКопии={};
  try{ вКопии=всеДанные(); }catch(e){ return []; }
  const мимо=[];
  try{
    for(let i=0;i<ХР.length;i++){
      const k=ХР.key(i);
      if(!k || k.indexOf("lnk_")!==0) continue;
      if(КЛЮЧИ_НАСТРОЕК.indexOf(k)>=0) continue;
      const поле=КЛЮЧИ_ДАННЫХ[k];
      if(поле && вКопии[поле]!==undefined) continue;
      // ключ журнала хранится отдельно и кладётся в копию своим полем
      if(k===STORE_KEY && вКопии["записи"]!==undefined) continue;
      мимо.push(k);
    }
  }catch(e){}
  return мимо;
}
