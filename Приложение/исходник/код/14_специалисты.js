// Как «История контроля» у объекта, только с другой стороны: что человек
// делал. Нужна прежде всего при продлении аттестации — видно, работал ли
// он по методу и когда в последний раз. Исполнитель в журнале вписан
// текстом, поэтому совпадение — с «в документах» или с ФИО карточки (тот
// же признак, что у нагрузки и подписей акта). Порога «перерыва» нет —
// его в присланных документах нет, показываю только даты.
const РАБОТ_В_КАРТОЧКЕ=30;
function работыСпециалиста(p){
  const имена=[p.вдок,p.фио].map(x=>String(x||"").trim()).filter(Boolean);
  const из=[];
  liveJ().forEach(z=>methodsOf(z).forEach(м=>{
    const и=String(((z.методы||{})[м]||{}).исп||"").trim();
    if(и && имена.indexOf(и)>=0) из.push({z, м, как:и});
  }));
  return из.sort((a,b)=>String(b.z.дата||"").localeCompare(String(a.z.дата||"")));
}
