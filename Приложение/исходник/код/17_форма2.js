// ── Форма 2 (разделы V–VIII паспорта): общая часть экрана и Word ──────
// Заказчик пересмотрел вид этих таблиц и попросил впрямую:
//  • текст двух последних столбцов — в ОДНОЙ ячейке, а ниже ячейка
//    делится на два столбца (в настоящем паспорте «Редакция № 6» над
//    обеими колонками стоит буквально одна и та же длинная фраза —
//    теперь она пишется один раз, как объединённая шапка);
//  • номер столбца — цифрой, в первый раз под подписью столбца на новой
//    строке (это и есть вторая строка шапки), дальше на каждой странице
//    столбцы подписываются только цифрой;
//  • тип прибора — на отдельной строке; отметка «И» — на своей строке,
//    остальное на следующей; изготовитель, зав. №, год выпуска и ввод в
//    эксплуатацию — каждый на своей строке;
//  • ширины столбцов подобраны так, чтобы самое длинное слово помещалось
//    целиком (минимумыКолонок/разложитьШирины — замер, а не на глаз).
const ЗАГ_ОБОРУД=["№","Наименование, тип","Назначение",
  "Изготовитель, зав. №, год выпуска, ввод в эксплуатацию",
  "Технические и метрологические характеристики","Владелец, основание владения",
  "№ документа о поверке, калибровке, аттестации. Дата и срок действия "+
  "документа или отметка о техническом состоянии"];
const СПАН_ОБОРУД=[1,1,1,1,1,1,2];
const НОМЕРА_ОБОРУД=["1","2","3","4","5","6","7","8"];
// Веса — куда отдавать остаток ширины сверх минимумов: там, где реально
// бывает длинный текст (характеристики, наименование, назначение), а не
// поровну. Номер и дата длинного текста не содержат вовсе.
const ВЕСА_ОБОРУД=[0,6,6,4,8,2,2,1];
// Однотипные неотъемлемые части ОДНОГО прибора печатаются в Форме 2
// одной позицией — так было в прежнем паспорте заказчика: заводские
// номера через запятую, после типа общее количество «(2 шт.)». Из двух
// написаний, что назвал заказчик («№ 7678, № 7679» и «№№ 7678, 7679»),
// взято второе — скажете, поменяю, это одна строка.
// Объединяются только карточки, у которых СОВПАДАЕТ ВСЁ печатаемое,
// кроме заводского номера: иначе разные данные (свои характеристики,
// своя дата ввода) молча пропали бы из документа. Сводятся только
// части (`основной_ид` заполнен) — самостоятельные приборы, даже
// одноимённые, остаются каждый своей строкой, как в настоящем паспорте.
function текстСокращённой(п){
  const о=String((п&&п.объём_поверки)||"").trim().replace(/\s+/g," ");
  return "сокращённая поверка"+(о?": "+о:"");
}
function ключОбъединения(п){
  return ["наименование","тип","назначение","характеристики","владелец","изготовитель",
          "год_выпуска","дата_ввода","исправен","свидетельство","сокращённая","объём_поверки","калибровка",
          "поверка_дата","поверка_до",
          "основной_ид"]
    .map(k=>String(п[k]==null?"":п[k]).trim()).join("\u0001");
}
function объединитьОднотипные(список){
  const из=[], индекс={};
  (список||[]).forEach(п=>{
    const зав=String(п.зав||"").trim();
    if(!п.основной_ид){ из.push(п); return; }
    const к=ключОбъединения(п), б=индекс[к];
    if(б){ б._кол++; if(зав) б._зав.push(зав); return; }
    const копия=Object.assign({},п,{_кол:1,_зав:зав?[зав]:[]});
    индекс[к]=копия; из.push(копия);
  });
  return из;
}
function безНомера(зав){ return /^б\s*\/\s*н\.?$/i.test(String(зав||"").trim()); }
function заводскиеНомера(s){
  // В одной карточке может быть несколько номеров через запятую (несколько
  // одинаковых предметов, см. поле «Количество») — тогда «№№»; «б/н» —
  // как в паспорте, без «зав. №».
  const свои=String(s.зав||"").split(/\s*,\s*/).map(x=>x.trim()).filter(Boolean);
  const ном=(s._зав&&s._зав.length)?s._зав:свои;
  if(!ном.length) return "";
  if(ном.length===1 && безНомера(ном[0])) return "б/н";
  return "зав. "+(ном.length>1?"\u2116\u2116 ":"\u2116 ")+ном.join(", ");
}
// Столбец 7 Формы 2 (указание заказчика):
//   «И»,
//   свидетельство о поверке        ← у калибровки: сертификат о калибровке
//   № 12345, <сокращённая поверка: …>, 29.08.2024
// Перед номером — знак № и неразрывный пробел (номер, уже записанный со
// знаком №, второго знака не получает). Запятая после «И» — только если
// ниже что-то есть.
function строкиДокументаПоверки(s){
  const т=типографика;
  const ном=String(s.свидетельство||"").trim().replace(/^№+\s*/,"");
  const ниже=[ном?"\u2116\u00a0"+ном:"", сокращённаяПоверка(s)?текстСокращённой(s):"",
    s.поверка_дата?ru(s.поверка_дата):""].filter(Boolean).join(", ");
  const и=s.исправен==="Исправен";
  return [и?("«И»"+(ниже?",":"")):"",
    ниже?(s.калибровка?"сертификат о калибровке":"свидетельство о поверке"):"",
    т(ниже)];
}
// Ячейки одной строки Формы 2. Массив внутри ячейки = отдельные строки
// текста (в Word — отдельные абзацы, на экране — отдельные <div>).
function ячейкиОборудования(s, i){
  const т=типографика;
  const кол=+(s._кол>1?s._кол:(parseInt(s.количество,10)||1)), шт=кол>1?(" ("+кол+" шт.)"):"";
  return [
    [String(i+1)],
    // Отметки «часть: …» нет — заказчик сказал, что она не нужна: часть
    // и так стоит в таблице сразу после своего прибора (порядокСЧастями).
    [т((s.наименование||"")+(s.тип?"":шт)), s.тип?т(вКавычках(s.тип)+шт):""],
    [т(s.назначение||"")],
    // Год выпуска, после него запятая и с новой строки дата ввода в
    // эксплуатацию — одной датой, без слов «введён в эксплуатацию»
    // (указание заказчика). Нет даты — нет и запятой.
    [т(s.изготовитель||""), т(заводскиеНомера(s)),
     т(String(s.год_выпуска||"").trim()+(String(s.год_выпуска||"").trim()&&s.дата_ввода?",":"")),
     s.дата_ввода?ru(s.дата_ввода):""],
    [т(s.характеристики||"")],
    [т(s.владелец||"")],
    строкиДокументаПоверки(s),
    [s.поверка_до?ru(s.поверка_до):""]
  ].map(л=>{ const ф=л.map(x=>String(x==null?"":x).trim()).filter(Boolean);
             return ф.length?ф:["—"]; });
}

// Ширины колонок Формы 2 считаются ОДИН раз на весь паспорт — по всему
// оборудованию разделов V–VIII сразу, а не по каждой таблице метода
// отдельно: иначе соседние таблицы одного раздела разъехались бы по
// колонкам, хотя форма у них одна и та же.
function шириныОборудования(мера, мераЖ, отступ, всего){
  const данные=объединитьОднотипные(приборыВДокументы()).map((s,i)=>ячейкиОборудования(s,i));
  const мин=минимумыКолонок(ЗАГ_ОБОРУД,СПАН_ОБОРУД,данные,мера,мераЖ,отступ);
  const сум=мин.reduce((a,b)=>a+b,0);
  const в=всего||Math.max(900,сум);
  return {мин:мин, всего:в, ширины:разложитьШирины(мин,ВЕСА_ОБОРУД,в)};
}


// ── Порядок оборудования в разделах V–VIII ───────────────────────────
// Неотъемлемая часть печатается СРАЗУ ПОСЛЕ своего прибора (указание
// заказчика). Поэтому раздел и метод у части — те же, что у её прибора
// (корня цепочки «часть → основной прибор»), даже если в карточке части
// стоят другие: иначе часть уехала бы в другую группу или другой раздел
// и оторвалась от прибора. Если основного прибора в документе нет
// (списан или удалён), часть стоит сама по себе по своим полям.
function корневойПрибор(x, поId){
  let к=x; const был=new Set();
  while(к && к.основной_ид){
    const р=поId[String(к.основной_ид)];
    if(!р || был.has(String(р.id))) break;
    был.add(String(к.id)); к=р;
  }
  return к;
}
// Список в порядке картотеки → самостоятельные приборы, и за каждым
// сразу его части (и части частей), тоже в порядке картотеки.
function порядокСЧастями(список){
  const поId={}, дети={};
  список.forEach(x=>{ поId[String(x.id)]=x; });
  const верх=[];
  список.forEach(x=>{
    const р=x.основной_ид?поId[String(x.основной_ид)]:null;
    if(р && р!==x) (дети[String(р.id)]=дети[String(р.id)]||[]).push(x); else верх.push(x);
  });
  const из=[], был=new Set();
  const обход=x=>{ if(был.has(String(x.id))) return; был.add(String(x.id)); из.push(x);
    (дети[String(x.id)]||[]).forEach(обход); };
  верх.forEach(обход);
  список.forEach(x=>{ if(!был.has(String(x.id))) обход(x); });   // кольцо ссылок — не теряем
  return из;
}
// Полные названия методов для строк-разделов Формы 2. Где в присланном
// паспорте («Редакция № 6») есть группа с таким методом — формулировка
// оттуда дословно (те же, что у групп норм. документов, НД_КАТЕГОРИИ);
// у УЗД и УЗТ — общая формулировка паспорта плюс подпункт СДАНК-01-2020
// (в журнале это разные методы, в паспорте — один «Ультразвуковой»);
// МК — по тому же образцу из классификатора СДАНК; ТВ — словами
// заказчика («ТВ это твердометрия»).
const МЕТОДЫ_ПОЛНО={
  ВИК:"Визуальный и измерительный метод контроля",
  УЗД:"Ультразвуковой метод контроля (ультразвуковая дефектоскопия)",
  УЗТ:"Ультразвуковой метод контроля (ультразвуковая толщинометрия)",
  АЭ:"Акустико-эмиссионный метод контроля",
  ТВ:"Твердометрия",
  ТК:"Тепловой метод неразрушающего контроля",
  ВД:"Вибродиагностический метод контроля",
  МК:"Магнитопорошковый метод контроля" };
function полноеИмяМетода(м){ return м ? (МЕТОДЫ_ПОЛНО[м]||м) : "Метод контроля не указан"; }
// Строки одного раздела паспорта (V–VIII): {раздел:"…"} — строка-заголовок
// метода, {ячейки:[…]} — прибор. Номер сквозной по разделу.
function строкиРазделаОборудования(список){
  const все=порядокСЧастями(список), поId={};
  все.forEach(x=>{ поId[String(x.id)]=x; });
  const сМетодом=все.map(x=>Object.assign({},x,{_метод:корневойПрибор(x,поId).метод}));
  const из=[]; let n=0;
  const группы=группыПоМетоду(сМетодом,"_метод");
  группы.forEach(([метод,строки])=>{
    // Если метод не указан ни у одного прибора раздела (так сейчас во всей
    // картотеке), строка-раздел ничего не сообщает — её нет. Если есть и
    // с методом, и без — у последних своя строка, иначе они выглядели бы
    // частью предыдущего метода.
    if(метод || группы.length>1) из.push({раздел:полноеИмяМетода(метод)});
    объединитьОднотипные(строки).forEach(s=>из.push({ячейки:ячейкиОборудования(s,n++)}));
  });
  return из;
}
