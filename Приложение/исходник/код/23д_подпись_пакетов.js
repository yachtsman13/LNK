async function подтвердитьДовериеПакета(d,проверка,имя){
  if(!проверка||!проверка.ок) return false;
  if(проверка.доверенный) return true;
  if(проверка.старый)
    return confirm("Файл «"+имя+"» сохранён старой версией и НЕ имеет подписи.\n\n"+
      "Принимайте его, только если он получен из известного источника и вы не ждёте подписанный файл. Продолжить?");
  if(!можноДоверятьКлючиПакетов()){
    alert("Новый или сменившийся ключ подписи может доверить только начальник или заместитель."); return false;
  }
  const место=d.место||"—", отп=показОтпечатка(проверка.ид);
  if(проверка.смена){
    const ответ=prompt("Место «"+место+"» прислало пакет с НОВЫМ ключом подписи.\n\n"+
      "Прежний отпечаток:\n"+показОтпечатка(проверка.прежний)+"\n\nНовый отпечаток:\n"+отп+"\n\n"+
      "Это нормально после очистки хранилища или переезда на другой компьютер, но может означать подмену файла. "+
      "Сверьте новый отпечаток на экране «Обмен» места «"+место+"».\n\nДля смены доверенного ключа впишите СМЕНИТЬ:","");
    if(String(ответ||"").trim().toUpperCase()!=="СМЕНИТЬ") return false;
  }else if(!confirm("Первый подписанный пакет от места «"+место+"».\n\nОтпечаток ключа:\n"+отп+
    "\n\nСверьте его с экраном «Обмен» на месте «"+место+"». Доверить этот ключ для следующих пакетов?")) return false;
  запомнитьДоверенныйКлюч(проверка.ид,d.подпись.ключ,место);
  return true;
}
async function подготовитьПакетыОбмена(годные,плохие){
  const принять=[], отклонить=(плохие||[]).slice();
  for(const x of годные){
    const п=x.проверка||await проверитьПодписьПакета(x.d), имя=x.f&&x.f.name||"файл";
    if(!п.ок){ отклонить.push({f:x.f,ошибка:п.ошибка}); continue; }
    if(!await подтвердитьДовериеПакета(x.d,п,имя)){
      отклонить.push({f:x.f,ошибка:п.старый?"старый файл без подписи не подтверждён":"ключ подписи не доверен"}); continue;
    }
    принять.push(x);
  }
  return {принять,отклонить};
}

// Приём обмена: сначала криптографическая проверка и доверие к ключу,
// затем прежний предпросмотр и слияние. В базу попадают только проверенные.
async function принятьПрочитанныеОбмены(годные,плохие){
  const подг=await подготовитьПакетыОбмена(годные,плохие);
  if(!подг.принять.length){
    alert("Принять нечего:\n\n"+подг.отклонить.map(x=>(x.f&&x.f.name||"файл")+": "+x.ошибка).join("\n")); return false;
  }
  годные=подг.принять; плохие=подг.отклонить;
  const текст=годные.map(x=>текстПредпросмотра(x.f.name,x.d,предпросмотрОбмена(x.d))).join("\n\n");
  if(!confirm("Принять файл"+(годные.length>1?"ы":"")+" обмена?\n\n"+текст+
    (плохие.length?("\n\nНе будут приняты: "+плохие.map(x=>x.f.name+": "+x.ошибка).join("\n")):"")+
    (годные.length>1?"\n\n(по каждому файлу — относительно базы, какая она сейчас)":"")+
    "\n\nОтменить приём потом нельзя — сомневаетесь, сначала сохраните резервную копию.")){
    toast("Файлы не приняты — база не изменилась"); return false;
  }
  _новыхКонфликтов=0;
  const tot={j:0,o:0,s:0,p:0}, отчёт=плохие.map(x=>x.f.name+": ошибка — "+x.ошибка);
  годные.forEach(x=>{
    try{ отчёт.push(принятьФайлОбмена(x.d,x.f.name,tot)); }
    catch(err){ отчёт.push(x.f.name+": ошибка — "+err.message); }
  });
  try{ ХР.setItem("lnk_last_import",new Date().toISOString()); }catch(e){}
  обновитьОбменИлиМастер();
  const столк=проверитьСтолкновения();
  if(столк.length) alert("ВНИМАНИЕ: одинаковые номера у разных записей.\n\n"+столк.slice(0,12).join("\n")+
    (столк.length>12?("\n… всего "+столк.length):"")+"\n\nИсправьте номера вручную в записях журнала.");
  alert("Принято файлов: "+годные.length+"\n\n"+отчёт.join("\n")+
    "\n\nВсего изменений: журнал "+tot.j+", объекты "+tot.o+", приборы "+tot.s+", специалисты "+tot.p+
    ".\n(в записи «+новых/обновлено»)"+(_новыхКонфликтов?("\n\nОдни и те же записи правили на двух местах: "+_новыхКонфликтов+
      ". Отброшенные версии сохранены для разбора."):""));
  toast("Обмен принят"); setChrome(); автоСверкаФайлов(); return true;
}
