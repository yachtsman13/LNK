function проверкиСМК(доб, сс){
  const д=live(СМК).filter(x=>!смкУтратил(x));
  const просроч=д.filter(x=>{ const с=смкСледПроверка(x); return с && с<сегодняМестн() && String(x.статус||"").trim()!=="На пересмотре"; });
  if(просроч.length) доб("ошибка","Система менеджмента","Документов СМ с просроченной проверкой: "+просроч.length,
    просроч.slice(0,10).map(x=>сс((x.номер||"")+" "+(x.наименование||"")+" — проверка была нужна "+ru(смкСледПроверка(x)),"smk",x.id)));
  const безДаты=д.filter(x=>String(x.редакция||"").trim() && !String(x.дата_введения||"").trim());
  if(безДаты.length) доб("внимание","Система менеджмента","Редакция без даты введения в действие: "+безДаты.length,
    безДаты.slice(0,10).map(x=>сс((x.номер||"")+" "+(x.наименование||"")+", ред. "+x.редакция,"smk",x.id)));
  const безФ=д.filter(x=>!String(x.файл||"").trim());
  if(безФ.length && live(СМК).some(x=>String(x.файл||"").trim())) доб("внимание","Система менеджмента","Документов СМ без файла: "+безФ.length,
    безФ.slice(0,10).map(x=>сс((x.номер||"")+" "+(x.наименование||""),"smk",x.id)));
}
