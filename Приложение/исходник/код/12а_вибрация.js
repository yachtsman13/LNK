// Прогноз по тренду: для каждой точки (опора × направление) — прямая по
// последним до 6 замерам виброскорости (не меньше трёх, с датами); если
// растёт и дойдёт до предела в пределах горизонта — «возможное превышение».
function прогнозКарты(к){
  const п=порогиКарты(к); if(!п.предел) return [];
  const зам=замерыКарты(к.id).filter(з=>/^\d{4}-\d{2}-\d{2}$/.test(з.дата||""));
  const из=[]; const сегодня=new Date().toISOString().slice(0,10), гор=горизонтВибр();
  опорыКарты(к).forEach((оп,i)=>ВИБ_НАПР.forEach(([н])=>{
    const ряд=зам.map(з=>({t:Date.parse(з.дата+"T00:00:00")/86400000, v:числоВибр(((з.з||{})[i+н]||{}).v)}))
      .filter(x=>x.v!=null && !isNaN(x.v)).slice(-6);
    if(ряд.length<3) return;
    const посл=ряд[ряд.length-1]; if(посл.v>п.предел.v) return;      // уже превышение — это не прогноз
    const n=ряд.length, ст=ряд.reduce((s,x)=>s+x.t,0)/n, sv=ряд.reduce((s,x)=>s+x.v,0)/n;
    const dd=ряд.reduce((s,x)=>s+(x.t-ст)*(x.t-ст),0); if(!dd) return;
    const k=ряд.reduce((s,x)=>s+(x.t-ст)*(x.v-sv),0)/dd;               // мм/с в сутки
    if(!(k>0)) return;
    const vПосл=sv+k*(посл.t-ст);                                        // по прямой на дату последнего замера
    const дней=(п.предел.v-vПосл)/k;
    const когда=new Date((посл.t+Math.max(0,дней))*86400000).toISOString().slice(0,10);
    if(когда<=new Date(Date.now()+гор*86400000).toISOString().slice(0,10))
      из.push({оп, н, когда, рост:k*30.436875, посл:посл.v, раньше:когда<сегодня});
  }));
  return из.sort((a,b)=>a.когда.localeCompare(b.когда));
}
// Состояние карточки для списка, пульта и проверки.
function состояниеКарты(к){
  const зам=замерыКарты(к.id), посл=зам[зам.length-1];
  const п=порогиКарты(к);
  if(!посл) return {к, посл:null, ур:"нет", т:"замеров нет", п};
  const о=оценкаЗамера(посл,к), прог=прогнозКарты(к);
  const ур=о.худ==="прев"?"прев":(о.худ==="пред"?"пред":(прог.length?"прог":(п.предел?"ok":"непред")));
  const т={прев:"превышение", пред:"выше предупредительного", прог:"возможное превышение к "+(прог[0]?ru(прог[0].когда):""),
           ok:"в норме", непред:"не с чем сравнить — нет предела"}[ур];
  return {к, посл, ур, т, о, прог, п};
}
