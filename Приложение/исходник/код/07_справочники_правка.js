// Место хранения в карточке прибора — ссылка на помещение; на экране и
// в выгрузке показываем его идентификацию, а не внутренний id. Значение,
// которому карточка не нашлась (старый текст или удалённое помещение),
// возвращаем как есть — терять введённое нельзя.
function помещениеТекст(ссылка){
  const v=String(ссылка||"").trim(); if(!v) return "";
  const п=ПОМ && ПОМ.find(x=>String(x.id)===v);
  return п ? String(п.идентификация||"").trim() : v;
}
// Номер карточки учёта в книге ППР бывает не одним числом: «1…9»,
// «37..45, 61», «30..32». Разбираем только однозначные формы — число,
// перечисление через запятую, диапазон через «..», «…» или «-».
// Не разобралось — возвращаем null, и позиция считается непонятной:
// такую из плана не убираем, гадать по тексту не буду.
function карточкиПозиции(текст){
  const t=String(текст||"").trim(); if(!t) return null;
  const из=[];
  for(const кусок of t.split(",")){
    const ч=кусок.trim(); if(!ч) continue;
    const диап=/^(\d+)\s*(?:\.\.|…|-|—)\s*(\d+)$/.exec(ч);
    if(диап){
      const a=+диап[1], b=+диап[2]; if(a>b || b-a>500) return null;
      for(let i=a;i<=b;i++) из.push(String(i));
      continue;
    }
    if(/^\d+$/.test(ч)){ из.push(String(+ч)); continue; }
    return null;                       // непонятная форма — не гадаем
  }
  return из.length?из:null;
}
// Позиция плана ППР относится к списанному прибору, если ВСЕ её номера
// карточек принадлежат списанным приборам (и хотя бы один нашёлся).
// Позиция, номера которой не разобрались или не нашлись в картотеке,
// остаётся в плане: без связи с карточкой убирать её не из чего.
function позицияСписана(поз){
  const номера=карточкиПозиции(поз && поз.карточка); if(!номера) return false;
  const списанные=new Set(), живые=new Set();
  live(S).forEach(п=>{
    const к=карточкиПозиции(п.карточка); if(!к) return;
    к.forEach(н=>(списанПрибор(п)?списанные:живые).add(н));
  });
  let нашлось=false;
  for(const н of номера){
    if(живые.has(н)) return false;     // хоть один живой — позиция нужна
    if(списанные.has(н)) нашлось=true;
  }
  return нашлось;
}
// Позиции плана, которые реально планируются: без позиций списанных
// приборов. Через неё идут все перечисления плана (список, пульт,
// задачи, выгрузка в Word) — правило в одном месте.
function позицииППР(){
  return live(ППР_ПОЗ||[]).filter(п=>!позицияСписана(п))
    .sort((a,b)=>(+a.нп||0)-(+b.нп||0));
}
