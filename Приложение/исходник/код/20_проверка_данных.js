function данныеСтаройВерсии(){
  const прочесть=k=>{ try{ const r=ХР.прочестьLS(k); return r?JSON.parse(r):null; }catch(e){ return null; } };
  const d={};
  Object.keys(КЛЮЧИ_ДАННЫХ).forEach(k=>{
    const поле=КЛЮЧИ_ДАННЫХ[k]; if(поле==="конфликты"||поле==="история") return;
    const v=прочесть(k); if(!v) return;
    d[поле]=(v && Array.isArray(v.rows)) ? v.rows : v;
  });
  const ж=прочесть(STORE_KEY); if(ж && Array.isArray(ж.rows)) d.записи=ж.rows;
  return d;
}
