// ── Переезд рабочего места на другой компьютер ───────────
// Раньше переезд делался двумя файлами (резервная копия — данные, файл
// обмена — право выдачи номеров) и тремя ручными шагами в мастере, и
// ничто не мешало потом по ошибке поработать и на старом компьютере:
// два «М1» с правками под одним кодом. Теперь один файл и одна кнопка с
// каждой стороны:
//   • старый компьютер: «Переезд места» — файл со ВСЕМ, что нужно месту
//     (данные как в резервной копии, право выдачи номеров, код места и его
//     роли, настройки места), плюс отметка «отсюда место переехало»;
//   • новый компьютер: этот файл принимается там же, где резервная копия
//     (мастер, шаг 1, или «Обмен» — «Восстановить из копии»): данные
//     ЗАМЕНЯЮТСЯ, код и роли ставятся, право выдачи переходит.
// Отметка на старом компьютере — не запрет (прав администратора нет, и
// мешать работать программа не должна), а предупреждение: при запуске, на
// пульте и в «Обмене». Его файл обмена несёт эту отметку, и любое место,
// принимающее такой файл, видит в предпросмотре, что файл со старого
// компьютера. Новый компьютер помнит время переезда и так же называет
// файл с тем же кодом места, выгруженный после переезда.
// Папки (автокопии, документы) с собой не переезжают: браузер разрешает
// их только на том компьютере, где их выбрали, — их выбирают заново.
const REG_ПЕРЕЕХАЛО="lnk_moved_out", REG_ПРИЕХАЛО="lnk_moved_in";
const ТИП_ПЕРЕЕЗДА="переезд места ЛНК";
// Настройки места, которые едут вместе с ним: порядок сортировок, «принято
// как есть», контроль обмена с другими местами, недавние поиски, стиль.
// НЕ едут: отметка мастера (на новом компьютере её ставит сам переезд),
// ручки папок (lnk_fs — их браузер привязывает к компьютеру) и последняя
// отмена загрузки (она про базу старого компьютера).
const НАСТРОЙКИ_ПЕРЕЕЗДА=["lnk_theme","lnk_jsort","lnk_psort","lnk_tsort","lnk_progsort",
  "lnk_last_backup","lnk_last_export","lnk_last_import","lnk_exch_places","lnk_check_ok","lnk_find_recent","lnk_udl","lnk_list_sort","lnk_ws_prev","lnk_flashes","lnk_autologout","lnk_comm_read","lnk_cal"];
function чтениеОтметки(k){ try{ const r=ХР.getItem(k); return r?JSON.parse(r):null; }catch(e){ return null; } }
function переехалоОтсюда(){ return чтениеОтметки(REG_ПЕРЕЕХАЛО); }
function приехалоСюда(){ return чтениеОтметки(REG_ПРИЕХАЛО); }

function переездВыгрузить(){
  const ws=getWS();
  if(!confirm("Переезд места «"+ws.код+"» на другой компьютер.\n\n"+
    "Программа сохранит ОДИН файл со всем, что нужно месту: данные (как в резервной копии), "+
    "право выдачи номеров, код места и его роли, настройки.\n\n"+
    "После этого этот компьютер будет помечен как оставленный: работать здесь дальше "+
    "не следует — правки, сделанные здесь, разойдутся с новым компьютером.\n\nПродолжить?")) return;
  const когда=new Date().toISOString();
  const настройки={};
  НАСТРОЙКИ_ПЕРЕЕЗДА.forEach(k=>{ try{ const v=ХР.getItem(k); if(v!=null) настройки[k]=v; }catch(e){} });
  const payload=Object.assign({ тип:ТИП_ПЕРЕЕЗДА, формат:1, место:ws.код,
    роли:{мастер:ws.мастер, начальник:ws.начальник},
    версия:DB.версия, выгружено:когда, право:getGrant(), настройки }, всеДанные());
  dl("Переезд места "+ws.код+" "+когда.slice(0,10)+".json", JSON.stringify(payload));
  try{ ХР.setItem(REG_ПЕРЕЕХАЛО, JSON.stringify({когда, код:ws.код})); }catch(e){}
  setChrome(); if(curView==="exchange") renderExchange();
  toast("Файл переезда сохранён. На новом компьютере: мастер первого запуска → «Восстановить из резервной копии»");
}
function переездОтменить(){
  const п=переехалоОтсюда(); if(!п) return;
  if(!confirm("Снять отметку о переезде?\n\nДелайте это, только если переезд не состоялся и место "+
    "«"+п.код+"» остаётся на этом компьютере. Если на новом компьютере уже работают — не снимайте: "+
    "получится два места с одним кодом.")) return;
  try{ ХР.removeItem(REG_ПЕРЕЕХАЛО); }catch(e){}
  setChrome(); if(curView==="exchange") renderExchange(); else switchView(curView||"dash");
  toast("Отметка о переезде снята");
}
// Принять файл переезда (зовёт backupOpen, узнав файл по типу).
function переездПринять(d){
  const ws=getWS(), здесь=кодСохранён();
  const было="журнал "+liveJ().length+", объекты "+live(O).length+", СИ "+live(S).length+", спец. "+live(P).length;
  const станет="журнал "+(d.записи||[]).filter(z=>!z.удалено).length+", объекты "+(d.объекты||[]).filter(z=>!z.удалено).length+
    ", СИ "+(d.приборы||[]).filter(z=>!z.удалено).length+", спец. "+(d.специалисты||[]).filter(z=>!z.удалено).length;
  if(!confirm("Принять переезд места «"+d.место+"» (файл от "+ru(String(d.выгружено||"").slice(0,10))+
    " "+String(d.выгружено||"").slice(11,16)+")?\n\n"+
    (здесь&&ws.код!==d.место?"⚠ Сейчас этот компьютер — место «"+ws.код+"». Оно станет «"+d.место+"».\n\n":"")+
    "Данные этого браузера будут ЗАМЕНЕНЫ данными из файла.\nСейчас: "+было+"\nСтанет: "+станет+
    "\n\nПраво выдачи номеров: "+((d.право&&d.право.место)||"ничьё")+
    (d.роли&&d.роли.начальник?"\nМесто начальника: да":"")+
    "\n\nПапки автокопий и документов выберите после этого заново.")) return false;
  if(Array.isArray(d.записи)){ J=d.записи; saveJournal(); }
  применитьДанные(d, true);
  if(d.право && typeof d.право==="object") saveGrant({место:d.право.место||"", изменено:d.право.изменено||""});
  saveWS({код:d.место, мастер:!!(d.роли&&d.роли.мастер), начальник:!!(d.роли&&d.роли.начальник)});
  Object.entries(d.настройки||{}).forEach(([k,v])=>{
    if(НАСТРОЙКИ_ПЕРЕЕЗДА.indexOf(k)>=0 && typeof v==="string"){ try{ ХР.setItem(k,v); }catch(e){} } });
  try{
    ХР.setItem(REG_ПРИЕХАЛО, JSON.stringify({когда:d.выгружено||new Date().toISOString(), код:d.место,
      принято:new Date().toISOString()}));
    // если место переезжает обратно на компьютер, откуда когда-то уехало
    ХР.removeItem(REG_ПЕРЕЕХАЛО);
    ХР.setItem(REG_МАСТЕР, JSON.stringify({когда:new Date().toISOString(), код:d.место, переезд:true}));
  }catch(e){}
  try{ applyTheme(ХР.getItem("lnk_theme")||"default"); }catch(e){}
  setChrome();
  if(curView==="setup"){ _мастер.код=d.место; _мастер.начальник=!!(d.роли&&d.роли.начальник);
    _мастер.свод=!!(d.роли&&d.роли.мастер); _мастер.шаг=3; renderМастер(); }
  else switchView("exchange");
  toast("Место «"+d.место+"» переехало сюда. Выберите папки автокопий и документов.");
  return true;
}
// Предупреждения о файле обмена, связанные с переездом (для предпросмотра).
function предупрежденияПереезда(d){
  const из=[];
  if(d && d.переехало && d.переехало.когда)
    из.push("файл с компьютера, с которого место «"+(d.переехало.код||d.место)+"» переехало "+
      ru(d.переехало.когда.slice(0,10))+" — правки в нём сделаны на оставленном компьютере");
  const п=приехалоСюда();
  if(d && п && d.место===п.код && d.выгружено && d.выгружено>п.когда && !(d.переехало&&d.переехало.когда))
    из.push("файл места «"+п.код+"» выгружен ПОСЛЕ его переезда на этот компьютер — "+
      "похоже, на старом компьютере продолжали работать");
  return из;
}
// Плашка на пульте и в «Обмене» на оставленном компьютере.
function плашкаПереезда(){
  const п=переехалоОтсюда(); if(!п) return "";
  return `<div class="draftnote" style="margin-bottom:12px">⚠ <b>Место «${esc(п.код)}» переехало
    на другой компьютер ${ru(п.когда.slice(0,10))} ${esc(п.когда.slice(11,16))}.</b> Здесь работать
    больше не следует: правки, сделанные здесь, разойдутся с новым компьютером, а файл обмена
    отсюда будет помечен как файл со старого компьютера.
    <button class="btn small" onclick="переездОтменить()">Переезд не состоялся — снять отметку</button></div>`;
}
function блокПереезда(){
  const п=переехалоОтсюда(), пр=приехалоСюда();
  return `<div class="panel">
      <h3>⇄ Переезд места на другой компьютер</h3>
      ${плашкаПереезда()}
      <div class="note">Один файл со всем, что нужно месту «${esc(getWS().код)}»: данные, право
        выдачи номеров, код и роли места, настройки. На новом компьютере его принимают как
        резервную копию — в мастере первого запуска (шаг 1) или кнопкой «Восстановить из копии».
        Папки автокопий и документов там выбирают заново; папку с документами (PDF) скопируйте
        целиком.</div>
      ${пр?`<div class="note" style="color:var(--ok)">Место «${esc(пр.код)}» переехало на этот компьютер
        ${ru(String(пр.принято||пр.когда).slice(0,10))} (файл от ${ru(пр.когда.slice(0,10))}).</div>`:""}
      <div class="formbtns">${п?"":`<button class="btn" onclick="переездВыгрузить()">⇄ Переезд места…</button>`}</div>
    </div>`;
}
