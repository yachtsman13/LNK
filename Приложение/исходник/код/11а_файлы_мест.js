// Записать верную версию файла (свою — при прикреплении, при первой
// проверке, «мой файл верный» и в споре). Прежний отпечаток запоминается:
// по нему другое место понимает, что новая версия сознательно заменила
// его версию, а не пришла параллельно (тогда это спор).
function записатьВерсиюФайла(путь, сведения){
  const id=idФайла(путь); if(!id) return null;
  const ts=new Date().toISOString(), я=getWS().код;
  let з=ФАЙЛЫ.find(x=>x.id===id);
  if(!з){ з={id}; ФАЙЛЫ.push(з); }
  else if(з.отп && з.отп!==сведения.отп && !з.удалено) з.прежний=з.отп;
  з.путь=путьФайлаДок(путь).join("/"); з.размер=сведения.размер; з.отп=сведения.отп||"";
  delete з.удалено; delete з.спор;
  з.изменено=ts; з.место=я;
  сохранитьФайлы();
  return з;
}
// Слияние реестра при обмене: свежее побеждает, но если два места
// независимо записали РАЗНЫЕ файлы под одним именем, это спор — более
// свежая версия остаётся, другая запоминается в записи (спор) и ждёт
// решения человека. «Независимо» — новая версия не знала о моей: её
// прежний отпечаток не мой, а моя версия записана здесь.
function слитьФайлы(вход){
  let изм=0; const я=getWS().код;
  (вход||[]).forEach(r=>{
    if(!r || r.id==null || r.id==="") return;
    const i=ФАЙЛЫ.findIndex(x=>x.id===r.id);
    if(i<0){ ФАЙЛЫ.push(JSON.parse(JSON.stringify(r))); изм++; return; }
    const L=ФАЙЛЫ[i], Rn=lastTs(r)>lastTs(L);
    if(!L.удалено && !r.удалено && L.отп && r.отп && L.отп!==r.отп){
      const знала=Rn?(r.прежний===L.отп):(L.прежний===r.отп);
      const моя=(L.место===я && r.место!==я);
      if(!знала && моя){
        const поб=JSON.parse(JSON.stringify(Rn?r:L)), про=Rn?L:r;
        // спор уже разобран на другом месте — запись решения новее спора
        поб.спор={отп:про.отп, размер:про.размер, место:про.место||"", когда:lastTs(про)};
        ФАЙЛЫ[i]=поб; изм++; return;
      }
    }
    if(Rn){ ФАЙЛЫ[i]=JSON.parse(JSON.stringify(r)); изм++; }
  });
  if(изм) сохранитьФайлы();
  return изм;
}
function предпросмотрФайлов(вход){
  let нов=0, изм=0;
  (Array.isArray(вход)?вход:[]).forEach(r=>{
    if(!r || !r.id) return;
    const L=ФАЙЛЫ.find(x=>x.id===r.id);
    if(!L){ if(!r.удалено) нов++; return; }
    if(lastTs(r)>lastTs(L) && r.отп!==L.отп) изм++;
  });
  return (нов||изм)?("Файлы документов: "+[нов?"новых "+нов:"", изм?"новых версий "+изм:""].filter(Boolean).join(", ")+
    " — сами файлы берутся с флешки (подпапка «"+ПАПКА_ФАЙЛОВ_ОБМЕНА+"»)"):"";
}

// ── Отпечаток содержимого ─────────────────────────────────
async function отпечатокДанных(буфер){
  try{
    if(!(window.crypto && crypto.subtle)) return "";
    const h=await crypto.subtle.digest("SHA-256", буфер);
    return [...new Uint8Array(h)].map(x=>x.toString(16).padStart(2,"0")).join("");
  }catch(e){ return ""; }
}
// Сведения о своём файле: есть ли, размер, отпечаток. Отпечаток не
// пересчитывается, если размер и время изменения те же, что при прошлой
// проверке, — иначе каждая проверка заново читала бы сотни мегабайт.
async function сведенияФайла(h, путь, кэш){
  let ф;
  try{ ф=await (await файлИзПапкиДок(h, путь)).getFile(); }catch(e){ return {есть:false}; }
  const размер=ф.size!=null?ф.size:null, мод=ф.lastModified||0;
  if(кэш && кэш.есть && кэш.отп && кэш.размер===размер && кэш.мод===мод) return {есть:true, размер, мод, отп:кэш.отп};
  const буфер=await ф.arrayBuffer();
  return {есть:true, размер:размер!=null?размер:буфер.byteLength, мод, отп:await отпечатокДанных(буфер)};
}
// Состояние файла на этом месте — по последней проверке (сама проверка
// асинхронна и требует разрешения браузера, а готовность акта, «Проверка
// данных» и пульт считаются сразу). «ок» / «нет» / «не тот» / «спор» /
// «не проверен».
function состояниеФайла(путь){
  const id=idФайла(путь); if(!id) return "нет";
  const м=файлыМеста(), л=м.ф[id], з=ФАЙЛЫ.find(x=>x.id===id && !x.удалено);
  if(!м.проверено || !л) return "не проверен";
  if(!л.есть) return "нет";
  if(з && ((з.отп && л.отп && з.отп!==л.отп) || (!(з.отп && л.отп) && з.размер!=null && л.размер!=null && з.размер!==л.размер)))
    return "не тот";
  if(з && з.спор) return "спор";
  return "ок";
}
