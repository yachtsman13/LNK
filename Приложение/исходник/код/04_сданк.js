// Заводской номер в журнале часто вклеен в название объекта
// («Баллон (хладон) V=40 л, зав. № 57544») — достаём оттуда.
function завЗаписи(z){
  const s=String(z.зав||"").trim(); if(s) return s;
  const m=/зав\.?\s*№\s*([^,;]+)/i.exec(String(z.объект||""));
  return m?m[1].trim():"";
}
function регЗаписи(z){
  const s=String(z.рег||"").trim(); if(s) return s;
  const m=/рег\.?\s*№\s*([^,;]+)/i.exec(String(z.объект||""));
  return m?m[1].trim():"";
}
// Наименование в предложном падеже: «Баллон (хладон) V=40 л» →
// «баллонах (хладон) V=40 л». Нет в словаре — вернётся как есть.
function вПадеже(имя){
  const н=String(имя||"").trim(); if(!н) return "";
  const з=live(ПАДЕЖИ).find(x=>x.id===н);
  return (з && String(з.форма||"").trim()) || н;
}
