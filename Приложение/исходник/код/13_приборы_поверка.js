// нет, поэтому частей меньше, чем у акта и паспорта.
function wФайлDocx(имя, тело, sectPr){
  const НС='xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main" '+
           'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"';
  const документ='<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'+
    '<w:document '+НС+'><w:body>'+тело+sectPr+'</w:body></w:document>';
  const R='http://schemas.openxmlformats.org/officeDocument/2006/relationships';
  dlBlob(имя, zipStore([
    {имя:"[Content_Types].xml", данные:'<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'+
      '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'+
      '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'+
      '<Default Extension="xml" ContentType="application/xml"/>'+
      '<Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>'+
      '</Types>'},
    {имя:"_rels/.rels", данные:'<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'+
      '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'+
      '<Relationship Id="rId1" Type="'+R+'/officeDocument" Target="word/document.xml"/>'+
      '</Relationships>'},
    {имя:"word/document.xml", данные:документ}
  ]));
}
